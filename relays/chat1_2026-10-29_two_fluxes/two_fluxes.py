def gram_Q():
    b = subprocess.run(["git", "show", "%s:%s" % (REV, SRC)], cwd=ROOT, capture_output=True, check=True).stdout
    assert hashlib.sha256(b).hexdigest() == SHA
    d = json.loads(b)["LR"]
    G = np.array(d["Gram Q"], dtype=np.int64)
    assert int(round(np.linalg.det(G))) == 5 and d["signature (+,-)"] == [2, 2]
    return G


def sqfree(n):
    n = abs(int(n)); out = 1; p = 2
    while p * p <= n:
        while n % (p * p) == 0: n //= p * p
        if n % p == 0: out *= p; n //= p
        p += 1
    return out * n


def cm_d(detNS):
    """the imaginary quadratic d with CM field Q(sqrt5, sqrt(-d)): squarefree part of det NS, with a factor 5 removed"""
    s = sqfree(detNS)
    return s // 5 if s % 5 == 0 else s


def reduce_form(a, b, c):
    """Gauss reduction of the positive-definite binary form a x^2 + 2 b xy + c y^2 (Gram [[a, b], [b, c]])"""
    while True:
        if a > c: a, c = c, a; b = -b
        m = round(b / a)
        if m != 0:
            c = c - 2 * m * b + m * m * a; b = b - m * a; continue
        if a == c and b < 0: b = -b
        if 2 * abs(b) == a and b < 0: b = -b
        return (a, b, c)


def saturation(v, u):
    """basis of (Qv + Qu) cap Z^4: index k = gcd of the 2x2 minors; extra generators (a v + b u)/k"""
    minors = [v[i] * u[j] - v[j] * u[i] for i in range(4) for j in range(i + 1, 4)]
    k = 0
    for m in minors: k = math.gcd(k, int(m))
    gens = [(k, 0), (0, k)]
    if k > 1:
        for a in range(k):
            for bb in range(k):
                if (a or bb) and all((a * v[i] + bb * u[i]) % k == 0 for i in range(4)):
                    gens.append((a, bb))
    # HNF of the 2D lattice generated by gens (coordinates relative to v/k, u/k)
    M = [list(g) for g in gens]
    basis = []
    for col in range(2):
        rows = [r for r in M if r[col] != 0 and all(r[c] == 0 for c in range(col))]
        while len([r for r in rows if r[col] != 0]) > 1:
            rows.sort(key=lambda r: abs(r[col]))
            p = rows[0]
            for r in rows[1:]:
                q = r[col] // p[col]
                for c in range(2): r[c] -= q * p[c]
            rows = [r for r in rows if any(r)]
        piv = [r for r in rows if r[col] != 0]
        if piv: basis.append(piv[0]); M = [r for r in M if r is not piv[0]]
    B = [[(a * v[i] + b * u[i]) // k for i in range(4)] for a, b in basis]
    assert len(B) == 2
    return k, B


def apriori():
    """even negative-definite binary lattices of det <= 36 with two independent vectors of norm -6 (as positive forms)"""
    out = set()
    for a in range(2, 13, 2):
        for c in range(a, 37, 2):
            for b in range(-a // 2, a // 2 + 1):
                if a * c - b * b <= 0 or a * c - b * b > 36: continue
                vecs = [(x, y) for x in range(-6, 7) for y in range(-6, 7) if a * x * x + 2 * b * x * y + c * y * y == 6]
                if any(p[0] * q[1] - p[1] * q[0] != 0 for p, q in itertools.combinations(vecs, 2)):
                    out.add(reduce_form(a, b, c))
    return sorted(out, key=lambda f: (f[0] * f[2] - f[1] ** 2, f))


def run(G, B):
    rng = range(-B, B + 1)
    V = np.array([c for c in itertools.product(rng, repeat=4) if any(c)], dtype=np.int64)
    q = np.einsum("ni,ij,nj->n", V, G, V)
    W = V[q == -6]
    P = W @ G @ W.T                                      # Q(v, u)
    classes = {}
    nplanes = 0
    I, J = np.nonzero(np.triu(np.abs(P) <= 5, k=1))     # negative definite needs det [[-6,b],[b,-6]] = 36 - b^2 > 0
    for i, j in zip(I.tolist(), J.tolist()):
            b = int(P[i, j])
            v, u = W[i].tolist(), W[j].tolist()
            k, Bs = saturation(v, u)
            g = np.array(Bs) @ G @ np.array(Bs).T
            f = reduce_form(-int(g[0, 0]), -int(g[0, 1]), -int(g[1, 1]))
            det = f[0] * f[2] - f[1] ** 2
            assert det * k * k == 36 - b * b, (v, u, k, det, b)
            key = f
            e = classes.setdefault(key, {"det NS": det, "d": cm_d(det), "planes": 0, "b values": set(), "example": (v, u)})
            e["planes"] += 1; e["b values"].add(abs(b)); nplanes += 1
    return len(W), nplanes, classes


def main():
    G = gram_Q()
    A = apriori()
    print("Lambda_A Gram (B1808, LR):", G.tolist())
    print("a priori even negative-definite binary lattices (as positive forms (a, b, c) = a x^2 + 2bxy + c y^2), det <= 36,")
    print("  with two independent vectors of norm 6: %d" % len(A))
    for f in A:
        det = f[0] * f[2] - f[1] ** 2
        print("    %s  det %2d  CM d = %d" % (f, det, cm_d(det)))
    res = {}
    for B in (4, 6, 8):
        n6, npl, cl = run(G, B)
        res[B] = cl
        print("\nB = %d: %d classes with Q = -6; %d negative-definite planes; %d NS classes" % (B, n6, npl, len(cl)))
        for f, e in sorted(cl.items(), key=lambda kv: (kv[1]["det NS"], kv[0])):
            print("    NS(-1) = %s  det %2d  CM field Q(sqrt5, sqrt-%d)  planes %5d  |b| in %s  in a priori list: %s  e.g. %s"
                  % (f, e["det NS"], e["d"], e["planes"], sorted(e["b values"]), f in A, e["example"]))
    s6, s8 = set(res[6]), set(res[8])
    print("\nstable from B = 6 to B = 8:", s6 == s8, "| classes at B = 8 not at B = 6:", sorted(s8 - s6))
    print("CM fields d found at B = 8:", sorted({e["d"] for e in res[8].values()}))
    print("two_fluxes exit 0")


if __name__ == "__main__":
    main()
