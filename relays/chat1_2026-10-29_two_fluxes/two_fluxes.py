import itertools, json, math, subprocess, pathlib, hashlib
import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
ROOT = next(q for q in HERE.parents if (q / ".git").exists())
REV = "965938922"
SRC = "frontier/B1808_three_generations_cut_a_curve_not_a_point/verification/three_generations_in_f2h.json"
