# ------------------------------------------------------------------------------------------------ K-Bessel
_T = None


def kbes(R, x):
    """K_{iR}(x) for real R >= 0 and an array x > 0.5, by the trapezoid rule on [0, T], summed in extended precision
    (numpy's longdouble), since for x < R the value is of order exp(-pi R/2) and the sum cancels."""
    x = np.asarray(x, dtype=float)
    h = 0.02
    T = math.acosh(max(1.0, 60.0 / x.min())) + 0.5
    t = np.arange(0.0, T + h, h).astype(np.longdouble)
    w = np.full(t.shape, np.longdouble(h))
    w[0] = np.longdouble(h) / 2
    E = np.exp(-np.outer(x.ravel().astype(np.longdouble), np.cosh(t)))
    return (E @ (w * np.cos(np.longdouble(R) * t))).astype(float).reshape(x.shape)


def kfun(R, x, exceptional):
    return kv(R, x) if exceptional else kbes(R, x)


# ------------------------------------------------------------------------------------------------ pullback
def pullback(z):
    """Return (z*, nW, nV): z* in D, and the numbers of W and V moves used (factor epsilon^(nW+nV) (-1)^nV)."""
    nW = nV = 0
    for _ in range(1000):
        x = z.real - math.floor(z.real + 0.5)
        z = complex(x, z.imag)
        if abs(z) ** 2 < 0.2 - 1e-15:
            z = -1 / (5 * z)
            nW += 1
        elif x > 0 and abs(z - 0.5) ** 2 < 0.05 - 1e-15:
            z = (5 * z - 3) / (10 * z - 5)
            nV += 1
        elif x < 0 and abs(z + 0.5) ** 2 < 0.05 - 1e-15:
            z = (5 * z + 3) / (-10 * z - 5)
            nV += 1
        else:
            return z, nW, nV
    raise RuntimeError('pullback did not end')


class Setup:
    def __init__(self, M, Q, Y):
        self.M, self.Q, self.Y = M, Q, Y
        self.xm = (2 * np.arange(1, Q + 1) - 1) / (4 * Q)
        pb = [pullback(complex(x, Y)) for x in self.xm]
        self.zs = np.array([p[0] for p in pb])
        self.nW = np.array([p[1] for p in pb])
        self.nV = np.array([p[2] for p in pb])
        assert self.zs.imag.min() > Y + 1e-9, 'a pulled-back point is not above Y'

    def factor(self, eps):
        return eps ** (self.nW + self.nV) * (-1.0) ** self.nV

    _cache = {}

    def kvalues(self, R, exceptional):
        key = (id(self), float(R), exceptional)
        if key not in Setup._cache:
            if len(Setup._cache) > 64:
                Setup._cache.clear()
            n = np.arange(1, self.M + 1)
            Setup._cache[key] = (kfun(R, 2 * np.pi * np.outer(n, self.zs.imag), exceptional),
                                 kfun(R, 2 * np.pi * n * self.Y, exceptional))
        return Setup._cache[key]

    def matrix(self, R, sigma, eps, exceptional=False):
        M, Q = self.M, self.Q
        n = np.arange(1, M + 1)
        cs = np.cos if sigma == 1 else np.sin
        ys = self.zs.imag
        Kst, Kdiag = self.kvalues(R, exceptional)                                      # (M, Q), (M,)
        Bst = np.sqrt(ys)[None, :] * Kst * cs(2 * np.pi * np.outer(n, self.zs.real))  # f(z*) = sum_l a_l Bst[l, m]
        Cm = cs(2 * np.pi * np.outer(n, self.xm))                                   # (M, Q)
        c = self.factor(eps)
        V = (2.0 / Q) * (Cm * c[None, :]) @ Bst.T                                    # V[n, l]
        diag = np.sqrt(self.Y) * Kdiag
        V -= np.diag(diag)
        return V, diag


def solve(S, R, sigma, eps, fix, exceptional=False):
    V, diag = S.matrix(R, sigma, eps, exceptional)
    M = S.M
    idx = [i for i in range(M) if i != fix]
    A = V[np.ix_(idx, idx)]
    b = -V[idx, fix]
    a = np.zeros(M)
    a[fix] = 1.0
    a[idx] = np.linalg.solve(A, b)
    return a


def evalf(a, R, sigma, z, exceptional=False):
    z = np.atleast_1d(np.asarray(z, dtype=complex))
    n = np.arange(1, len(a) + 1)
    cs = np.cos if sigma == 1 else np.sin
    K = kfun(R, 2 * np.pi * np.outer(n, z.imag), exceptional)
    return (a[:, None] * np.sqrt(z.imag)[None, :] * K * cs(2 * np.pi * np.outer(n, z.real))).sum(axis=0)


ZE = (2 + 1j) / 5
TEST_E = np.array([ZE + 0.035 * np.exp(1j * p) for p in (0.3, 1.1, 2.0, 2.9, 4.0, 5.2)])
TEST_W = np.array([0.10 + 0.45j, 0.21 + 0.50j, 0.33 + 0.41j, 0.05 + 0.62j])


def automorphy(a, R, sigma, eps, exceptional=False):
    E1 = lambda z: (2 * z - 1) / (5 * z - 2)
    W = lambda z: -1 / (5 * z)
    f0 = evalf(a, R, sigma, TEST_E, exceptional)
    f1 = evalf(a, R, sigma, E1(TEST_E), exceptional)
    g0 = evalf(a, R, sigma, TEST_W, exceptional)
    g1 = evalf(a, R, sigma, W(TEST_W), exceptional)
    s1 = max(np.abs(f0).max(), 1e-300)
    s2 = max(np.abs(g0).max(), 1e-300)
    return max(np.abs(f1 + f0).max() / s1, np.abs(g1 - eps * g0).max() / s2)


CLASSES = [(-1, -1), (-1, 1), (1, -1), (1, 1)]


class Scanner:
    def __init__(self, M, Q, Y1, Y2):
        self.S1, self.S2 = Setup(M, Q, Y1), Setup(M, Q, Y2)

    def H(self, R, sigma, eps, fix, exceptional=False):
        a1 = solve(self.S1, R, sigma, eps, fix, exceptional)
        a2 = solve(self.S2, R, sigma, eps, fix, exceptional)
        k = 1 if fix == 0 else 0
        k2 = 2
        return a1[k] - a2[k], a1, a2, k, k2


def scan_class(sc, sigma, eps, grid, exceptional=False):
    found = []
    rejected = []
    for fix in (0, 1):
        vals = []
        for R in grid:
            try:
                vals.append(sc.H(R, sigma, eps, fix, exceptional)[0])
            except np.linalg.LinAlgError:
                vals.append(np.nan)
        vals = np.array(vals)
        for i in range(len(grid) - 1):
            if not (np.isfinite(vals[i]) and np.isfinite(vals[i + 1])) or vals[i] * vals[i + 1] > 0:
                continue
            try:
                r = brentq(lambda R: sc.H(R, sigma, eps, fix, exceptional)[0], grid[i], grid[i + 1], xtol=1e-12)
            except Exception:
                continue
            h, a1, a2, k, k2 = sc.H(r, sigma, eps, fix, exceptional)
            agree = abs(a1[k2] - a2[k2]) / max(1.0, abs(a1[k2]))
            aut = automorphy(a1, r, sigma, eps, exceptional)
            rec = dict(R=r, fix='a_%d = 1' % (fix + 1), next_agree=agree, automorphy=aut)
            if agree < 1e-6 and aut < 1e-6:
                found.append(rec)
            else:
                rejected.append(rec)
    # merge the two normalisations
    merged = []
    for rec in sorted(found, key=lambda r: r['R']):
        if merged and abs(rec['R'] - merged[-1]['R']) < 1e-6:
            merged[-1]['fix'] += ', ' + rec['fix']
            continue
        merged.append(rec)
    return merged, rejected


def scaled_svd(S, R, sigma, eps):
    V, diag = S.matrix(R, sigma, eps)
    Vs = V / diag[None, :]
    s = np.linalg.svd(Vs, compute_uv=False)
    return s[::-1]


