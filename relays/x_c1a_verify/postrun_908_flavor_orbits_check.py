#!/usr/bin/env python3
"""Standalone post-run check for Row 908 (+LLLR three-orbit flavor groups).

Zero imports from verify_x_c1a.py or any builder script.
In verify_x_c1a.py (b1a620efe, line 1451), the filter selecting one of the two
size-3 sign-character orbits on the 3-ended companion cover of +LLLR checked
m_A == 1 instead of m_A == 0, reading the non-member A_4 orbit ([12, 12])
instead of the n(nu x rho) = 1 members' Z/2 x A_4 orbit ([24, 12]).

This standalone script independently constructs the +LLLR companion cover,
evaluates both size-3 sign-character orbits (m_A = 0 and m_A = 1), verifies
which orbit has interior room n(nu x rho) = 1 at 100-digit mpmath precision,
and computes the exact finite monomial image G = Ind(chi)(pi_1(+LLLR)) and
G cap SL(3, Z) for both orbits, after firing a planted negative control.
"""

from __future__ import annotations

import hashlib
import itertools
import json
import sys
from pathlib import Path

import mpmath as mp
import numpy as np
import snappy
import sympy as sp

mp.mp.dps = 100


def inv_w(w: str) -> str:
    return "".join(c.swapcase() for c in reversed(w))


def red_w(w: str) -> str:
    st: list[str] = []
    for c in w:
        if st and st[-1] == c.swapcase():
            st.pop()
        else:
            st.append(c)
    return "".join(st)


def sub_w(w: str, img: dict[str, str]) -> str:
    out = []
    for c in w:
        out.append(img[c] if c.islower() else inv_w(img[c.lower()]))
    return red_w("".join(out))


def build_lllr_companion() -> dict[str, object]:
    # +LLLR in sm:B1527 bundle convention: phi_L(a->ab, b->b), phi_R(a->a, b->ba), last letter first
    img = {"a": "a", "b": "b"}
    for ch in reversed("LLLR"):
        step = {"a": "ab", "b": "b"} if ch == "L" else {"a": "a", "b": "ba"}
        img = {"a": sub_w(img["a"], step), "b": sub_w(img["b"], step)}

    # Relator abelianizations: t a T phi(a)^-1 -> (0, -3), t b T phi(b)^-1 -> (-1, -3).
    # Hence Z^2 / (M - I)Z^2 = Z/3Z generated by b: a -> +0 mod 3, b -> +1 mod 3, t -> +0 mod 3.
    d = 3
    act = {
        "a": [x for x in range(3)],
        "b": [(x + 1) % 3 for x in range(3)],
        "t": [x for x in range(3)],
    }
    act["A"] = [x for x in range(3)]
    act["B"] = [(x - 1) % 3 for x in range(3)]
    act["T"] = [x for x in range(3)]

    # Schreier tree from coset 0 using generator 'b': u_0 = "", u_1 = "b", u_2 = "bb"
    u = ["", "b", "bb"]
    gen_idx: dict[tuple[int, str], int | None] = {}
    gen_words: list[str] = []
    for x in range(d):
        for g in "abt":
            y = act[g][x]
            gw = red_w(u[x] + g + inv_w(u[y]))
            if gw == "":
                gen_idx[(x, g)] = None
            else:
                gen_idx[(x, g)] = len(gen_words)
                gen_words.append(gw)
    ng = len(gen_words)

    def rewrite_from(x0: int, w: str) -> tuple[list[tuple[int, int]], int]:
        cur = x0
        out: list[tuple[int, int]] = []
        for ch in w:
            if ch in "abt":
                idx = gen_idx[(cur, ch)]
                if idx is not None:
                    out.append((idx, 1))
                cur = act[ch][cur]
            else:
                g = ch.lower()
                prev = act[ch][cur]
                idx = gen_idx[(prev, g)]
                if idx is not None:
                    out.append((idx, -1))
                cur = prev
        # Free-reduce Schreier generator pairs
        red: list[tuple[int, int]] = []
        for idx, sgn in out:
            if red and red[-1] == (idx, -sgn):
                red.pop()
            else:
                red.append((idx, sgn))
        return red, cur

    rels_gamma = [red_w("taT" + inv_w(img["a"])), red_w("tbT" + inv_w(img["b"]))]
    rels_idx = []
    rel_mat = np.zeros((2 * d, ng), dtype=int)
    for x in range(d):
        for ri, rw in enumerate(rels_gamma):
            sw, xe = rewrite_from(x, rw)
            assert xe == x
            rels_idx.append(sw)
            for idx, sgn in sw:
                rel_mat[2 * x + ri, idx] += sgn

    # Three cusps (cosets 0, 1, 2 since ell = abAB and t both act trivially on Z/3Z)
    cusps_idx = []
    for x0 in range(d):
        sw1, xe1 = rewrite_from(x0, "abAB")
        sw2, xe2 = rewrite_from(x0, "t")
        assert xe1 == x0 and xe2 == x0
        cusps_idx.append((sw1, sw2))

    # Deck action by conjugation u_h^{-1} g_j u_h
    deck_mats = []
    for h in range(d):
        M_h = np.zeros((ng, ng), dtype=int)
        for j, gw in enumerate(gen_words):
            sw, xe = rewrite_from(0, inv_w(u[h]) + gw + u[h])
            assert xe == 0
            for idx, sgn in sw:
                M_h[idx, j] += sgn
        deck_mats.append(M_h)

    return {
        "img": img,
        "act": act,
        "ng": ng,
        "gen_idx": gen_idx,
        "gen_words": gen_words,
        "rels_idx": rels_idx,
        "rel_mat": rel_mat,
        "cusps_idx": cusps_idx,
        "deck_mats": deck_mats,
    }


def solve_lllr_holonomy_4d(img: dict[str, str]) -> dict[str, mp.matrix]:
    sh = complex(snappy.Manifold("b++LLLR").cusp_info("shape")[0])
    xs, ys, zs = sp.symbols("x y z")
    A_, B_, C_ = xs, ys, zs
    for ch in "LLLR":
        if ch == "L":
            A_, B_, C_ = C_, B_, sp.expand(B_ * C_ - A_)
        else:
            A_, B_, C_ = A_, C_, sp.expand(A_ * C_ - B_)
    gb = sp.groebner([A_ - xs, B_ - ys, xs**2 + ys**2 + zs**2 - xs * ys * zs, C_ - zs], xs, ys, zs, order="lex")
    exprs = list(gb.exprs)
    pz = sp.Poly(exprs[-1], zs).sqf_part()
    y_polys = [e for e in exprs[:-1] if xs not in e.free_symbols and ys in e.free_symbols]

    def eval_sl2(w: str, mats: dict[str, mp.matrix]) -> mp.matrix:
        R = mp.eye(2)
        for c in w:
            if c.islower():
                R = R * mats[c]
            else:
                g = mats[c.lower()]
                R = R * mp.matrix([[g[1, 1], -g[0, 1]], [-g[1, 0], g[0, 0]]])
        return R

    def four_rep(g: mp.matrix) -> mp.matrix:
        E = [
            mp.matrix([[1, 0], [0, 0]]),
            mp.matrix([[0, 0], [0, 1]]),
            mp.matrix([[0, 1], [1, 0]]),
            mp.matrix([[0, 1j], [-1j, 0]]),
        ]
        gs = g.transpose_conj()
        M4 = mp.matrix(4, 4)
        for ck, Ek in enumerate(E):
            X = g * Ek * gs
            vals = [mp.re(X[0, 0]), mp.re(X[1, 1]), mp.re(X[0, 1]), mp.im(X[0, 1])]
            for ri in range(4):
                M4[ri, ck] = vals[ri]
        return M4

    for zr in pz.nroots(n=100, maxsteps=500):
        if abs(complex(zr)) < 1e-7:
            continue
        y_cands = []
        for yp in y_polys:
            ev = yp.evalf(100, subs={zs: zr})
            if ys in ev.free_symbols:
                py_sub = sp.Poly(ev, ys)
                if abs(complex(py_sub.LC())) > 1e-7:
                    y_cands.append((py_sub.degree(), py_sub))
        if not y_cands:
            continue
        y_cands.sort(key=lambda t: t[0])
        ev_y = y_cands[0][1]
        for yr in ev_y.nroots(n=100, maxsteps=500):
            ym = mp.mpc(str(sp.re(yr)), str(sp.im(yr)))
            zm = mp.mpc(str(sp.re(zr)), str(sp.im(zr)))
            disc = mp.sqrt((ym * zm) ** 2 - 4 * (ym**2 + zm**2))
            for xm in ((ym * zm + disc) / 2, (ym * zm - disc) / 2):
                if abs(mp.im(xm)) + abs(mp.im(ym)) + abs(mp.im(zm)) < mp.mpf("1e-12"):
                    continue
                # Construct A, B in SL(2, C) with tr(A)=xm, tr(B)=ym, tr(AB)=zm
                A = mp.matrix([[xm, 1], [-1, 0]])
                beta = (-zm + mp.sqrt(zm * zm - 4)) / 2
                B = mp.matrix([[0, beta], [-1 / beta, ym]])
                mats_ab = {"a": A, "b": B}
                pa, pb = eval_sl2(img["a"], mats_ab), eval_sl2(img["b"], mats_ab)
                # Solve T X = phi(X) T in SL(2, C)
                Sys = mp.matrix(8, 4)
                for eq_i, (X1, X2) in enumerate([(A, pa), (B, pb)]):
                    for i in range(2):
                        for j in range(2):
                            r = eq_i * 4 + 2 * i + j
                            for k in range(2):
                                Sys[r, 2 * i + k] += X1[k, j]
                                Sys[r, 2 * k + j] -= X2[i, k]
                best_t, best_res = None, mp.mpf("1")
                for fix in range(4):
                    cols = [c for c in range(4) if c != fix]
                    Sub, rhs = mp.matrix(8, 3), mp.matrix(8, 1)
                    for r in range(8):
                        rhs[r, 0] = -Sys[r, fix]
                        for ci, c in enumerate(cols):
                            Sub[r, ci] = Sys[r, c]
                    try:
                        sol = mp.lu_solve(Sub.transpose_conj() * Sub, Sub.transpose_conj() * rhs)
                    except Exception:
                        continue
                    vec = [mp.mpc(0)] * 4
                    vec[fix] = mp.mpc(1)
                    for ci, c in enumerate(cols):
                        vec[c] = sol[ci, 0]
                    res = max(abs(sum(Sys[r, c] * vec[c] for c in range(4))) for r in range(8))
                    if res < best_res:
                        best_res, best_t = res, vec
                sys_scale = max(mp.mpf(1), max(abs(Sys[r, c]) for r in range(8) for c in range(4)))
                if best_t is None or best_res > mp.mpf("1e-50") * sys_scale:
                    continue
                T0 = mp.matrix([[best_t[0], best_t[1]], [best_t[2], best_t[3]]])
                detT = T0[0, 0] * T0[1, 1] - T0[0, 1] * T0[1, 0]
                if abs(detT) < mp.mpf("1e-20"):
                    continue
                Tm = T0 / mp.sqrt(detT)
                L_c = eval_sl2("abAB", mats_ab)
                sl = 1 if mp.re(L_c[0, 0] + L_c[1, 1]) > 0 else -1
                Nl = L_c - sl * mp.eye(2)
                u0, v0 = (
                    (Nl[0, 1], -Nl[0, 0])
                    if abs(Nl[0, 0]) + abs(Nl[0, 1]) >= abs(Nl[1, 0]) + abs(Nl[1, 1])
                    else (-Nl[1, 1], Nl[1, 0])
                )
                nrm2 = abs(u0) ** 2 + abs(v0) ** 2
                P = mp.matrix([[u0, -mp.conj(v0) / nrm2], [v0, mp.conj(u0) / nrm2]])
                Pinv = mp.inverse(P)
                Lp = Pinv * L_c * P
                Tp = Pinv * Tm * P
                st = 1 if mp.re(Tp[0, 0] + Tp[1, 1]) > 0 else -1
                if abs(Tp[1, 0]) > mp.mpf("1e-50") or abs(Tp[0, 0] - st) > mp.mpf("1e-50"):
                    continue
                tau = (st * Tp[0, 1]) / (sl * Lp[0, 1])
                if mp.im(tau) > 0 and abs(abs(float(mp.im(tau))) - abs(sh.imag)) < 1e-6:
                    t_re = float(mp.re(tau))
                    if any(abs((t_re + e * sh.real) - round(t_re + e * sh.real)) < 1e-6 for e in (1, -1)):
                        return {
                            "a": four_rep(A),
                            "b": four_rep(B),
                            "t": four_rep(Tm),
                            "abt_sl2": {"a": A, "b": B, "t": Tm},
                            "eval_sl2": eval_sl2,
                            "four_rep": four_rep,
                        }
    raise RuntimeError("Failed to locate geometric holonomy for +LLLR")


def interior_room_np(mod_mats: list[np.ndarray], rels_idx: list[list[tuple[int, int]]], cusps_idx: list[tuple[list[tuple[int, int]], list[tuple[int, int]]]]) -> tuple[int, int, int]:
    e = mod_mats[0].shape[0]
    ng = len(mod_mats)
    invs = [np.linalg.inv(m) for m in mod_mats]
    I = np.eye(e, dtype=np.complex128)

    def fox(w: list[tuple[int, int]]) -> tuple[np.ndarray, np.ndarray]:
        out = np.zeros((e, ng * e), dtype=np.complex128)
        pre = np.eye(e, dtype=np.complex128)
        for idx, sgn in w:
            if sgn == 1:
                out[:, idx * e : (idx + 1) * e] += pre
                pre = pre @ mod_mats[idx]
            else:
                pre = pre @ invs[idx]
                out[:, idx * e : (idx + 1) * e] -= pre
        return out, pre

    fox_mat = np.vstack([fox(r)[0] for r in rels_idx])
    _, sf, vhf = np.linalg.svd(fox_mat, full_matrices=True)
    rk_f = int(np.sum(sf > 1e-9 * sf[0]))
    Z = vhf[rk_f:, :].conj().T
    dg = np.vstack([m - I for m in mod_mats])
    sdg = np.linalg.svd(dg, compute_uv=False)
    r0 = int(np.sum(sdg > 1e-9 * sdg[0])) if sdg[0] > 0 else 0
    h1 = Z.shape[1] - r0

    rowsR, BPb = [], []
    for w1, w2 in cusps_idx:
        F1, W1 = fox(w1)
        F2, W2 = fox(w2)
        rowsR.extend([F1, F2])
        BPb.append(np.vstack([W1 - I, W2 - I]))
    nc = len(cusps_idx)
    BP = np.zeros((2 * e * nc, e * nc), dtype=np.complex128)
    for ci, b in enumerate(BPb):
        BP[2 * e * ci : 2 * e * (ci + 1), e * ci : e * (ci + 1)] = b
    R = np.vstack(rowsR)
    sbp = np.linalg.svd(BP, compute_uv=False)
    rBP = int(np.sum(sbp > 1e-9 * sbp[0])) if sbp[0] > 0 else 0
    both = np.hstack([BP, R @ Z]) if Z.shape[1] > 0 else BP
    sb = np.linalg.svd(both, compute_uv=False)
    rboth = int(np.sum(sb > 1e-9 * sb[0])) if sb[0] > 0 else 0
    r1 = rboth - rBP
    return h1, r1, h1 - r1


def induced_group_stats(cov: dict[str, object], rep: tuple[int, ...]) -> dict[str, object]:
    gens_m = []
    for g in "abt":
        P = np.zeros((3, 3), dtype=int)
        for x in range(3):
            y = cov["act"][g][x]
            idx = cov["gen_idx"][(x, g)]
            P[x, y] = 1 if (idx is None or rep[idx] == 0) else -1
        gens_m.append(P)
    I3 = np.eye(3, dtype=int)
    G = {tuple(map(tuple, I3)): I3}
    fr = [I3]
    while fr:
        nx = []
        for A in fr:
            for gm in gens_m:
                B = A @ gm
                k = tuple(map(tuple, B))
                if k not in G:
                    G[k] = B
                    nx.append(B)
        fr = nx
    mats = list(G.values())
    sl3 = [A for A in mats if round(float(np.linalg.det(A))) == 1]

    def elem_orders(ms: list[np.ndarray]) -> dict[str, int]:
        cnt: dict[int, int] = {}
        for A in ms:
            cur = np.eye(3, dtype=int)
            k = 0
            while True:
                k += 1
                cur = cur @ A
                if np.array_equal(cur, I3):
                    cnt[k] = cnt.get(k, 0) + 1
                    break
        return {str(k): cnt[k] for k in sorted(cnt)}

    centre = sum(1 for A in mats if all(np.array_equal(A @ B, B @ A) for B in mats))
    return {
        "order": len(mats),
        "centre": centre,
        "element_orders": elem_orders(mats),
        "sl3_order": len(sl3),
        "sl3_element_orders": elem_orders(sl3),
    }


def main() -> None:
    cov = build_lllr_companion()
    ng = int(cov["ng"])
    rel_mat = cov["rel_mat"]

    # Enumerate all sign characters Hom(H_1(N), Z/2Z)
    chars = [
        c for c in itertools.product((0, 1), repeat=ng)
        if np.all((rel_mat @ np.array(c, dtype=int)) % 2 == 0)
    ]
    assert len(chars) == 8

    seen: set[tuple[int, ...]] = set()
    orbits3 = []
    for c in chars:
        if c in seen:
            continue
        orb = sorted({tuple(((M_h.T @ np.array(c, dtype=int)) % 2).tolist()) for M_h in cov["deck_mats"]})
        seen.update(orb)
        if len(orb) == 3:
            rep = orb[0]
            m_A = sum(
                1
                for sw1, sw2 in cov["cusps_idx"]
                if (sum(rep[i] * s for i, s in sw1) % 2 == 0) and (sum(rep[i] * s for i, s in sw2) % 2 == 0)
            )
            orbits3.append((m_A, orb))
    orbits3.sort(key=lambda t: t[0])
    assert [m for m, _ in orbits3] == [0, 1]

    # Planted negative control: selecting the m_A == 1 orbit must NOT give order 24
    g_mA1 = induced_group_stats(cov, orbits3[1][1][0])
    control_fired = (g_mA1["order"] != 24)
    if not control_fired:
        sys.exit(2)

    hol = solve_lllr_holonomy_4d(cov["img"])
    gen_4d = []
    for gw in cov["gen_words"]:
        W = hol["eval_sl2"](gw, hol["abt_sl2"])
        M4 = hol["four_rep"](W)
        gen_4d.append(np.array([[complex(M4[i, j]) for j in range(4)] for i in range(4)], dtype=np.complex128))

    orbit_records = []
    for m_A, orb in orbits3:
        rep = orb[0]
        mod_nu_rho = [((1.0 if rep[j] == 0 else -1.0) * gen_4d[j]) for j in range(ng)]
        h1, r1, n = interior_room_np(mod_nu_rho, cov["rels_idx"], cov["cusps_idx"])
        g_stats = induced_group_stats(cov, rep)
        orbit_records.append({
            "m_A_ends_trivial": m_A,
            "orbit_size": len(orb),
            "nu_rho_h1_r1_n": [h1, r1, n],
            "is_members_orbit": bool(n > 0),
            "induced_flavor_group": g_stats,
        })

    members_rec = [r for r in orbit_records if r["is_members_orbit"]]
    other_rec = [r for r in orbit_records if not r["is_members_orbit"]]
    both_match = (
        len(members_rec) == 1
        and members_rec[0]["m_A_ends_trivial"] == 0
        and members_rec[0]["nu_rho_h1_r1_n"] == [1, 0, 1]
        and members_rec[0]["induced_flavor_group"]["order"] == 24
        and members_rec[0]["induced_flavor_group"]["sl3_order"] == 12
        and len(other_rec) == 1
        and other_rec[0]["m_A_ends_trivial"] == 1
        and other_rec[0]["nu_rho_h1_r1_n"] == [2, 2, 0]
        and other_rec[0]["induced_flavor_group"]["order"] == 12
        and other_rec[0]["induced_flavor_group"]["sl3_order"] == 12
    )

    out = {
        "row": 908,
        "pinned_commit": "0d2694faf",
        "planted_wrong_orbit_control_fired": control_fired,
        "orbits_size_3_at_m_2": orbit_records,
        "members_orbit_is_Z2_x_A4_order_24_det1_12": bool(
            len(members_rec) == 1
            and members_rec[0]["induced_flavor_group"]["order"] == 24
            and members_rec[0]["induced_flavor_group"]["sl3_order"] == 12
        ),
        "other_sign_orbit_is_A4_order_12_det1_12": bool(
            len(other_rec) == 1
            and other_rec[0]["induced_flavor_group"]["order"] == 12
            and other_rec[0]["induced_flavor_group"]["sl3_order"] == 12
        ),
        "all_row_908_flavor_orbit_claims_match": both_match,
    }
    out_path = Path(__file__).resolve().parent / "postrun_908_flavor_orbits_out.json"
    out_bytes = (json.dumps(out, indent=2, sort_keys=True) + "\n").encode("utf-8")
    out_path.write_bytes(out_bytes)
    digest = hashlib.sha256(out_bytes).hexdigest()
    (Path(__file__).resolve().parent / "POSTRUN_OUTPUT_SHA256.txt").write_text(
        f"{digest}  postrun_908_flavor_orbits_out.json\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
