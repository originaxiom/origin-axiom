#!/usr/bin/env python3
"""The SM seat's harvest review, item 1: every row of main's harvest ledger for this seat whose disposition head is
received, registered or owed without VERIFIED.  Mechanical; reads docs/HARVEST_LEDGER.md from a checkout or a git ref.
    python3 unverified_rows.py LEDGER_FILE > ../SM_HARVEST_UNVERIFIED_ROWS.md"""
import re
import sys

rows = []
for l in open(sys.argv[1], encoding="utf-8"):
    if not l.startswith("| "):
        continue
    c = [x.strip() for x in l.split("|")]
    if len(c) < 8 or not c[1].isdigit() or "SM" not in c[2]:
        continue
    d = c[6]
    if any(k in d[:120] for k in ("RECEIVED", "REGISTERED", "OWED", "owed", "SCHEDULED")) and "VERIFIED" not in d[:120]:
        head = re.sub(r"\s+", " ", d[:110]).replace("|", "/").replace("`", "")
        rows.append((int(c[1]), re.sub(r"\s+", " ", c[3][:70]).replace("|", "/").replace("`", ""), head))
print("# The SM seat's ledger rows not verified (harvest review, item 1)\n")
print("*Generated by `relays/sm_harvest/unverified_rows.py` from main's docs/HARVEST_LEDGER.md. One line per row whose")
print("disposition head says received, registered or owed, and not verified. The heads are cut at 110 characters.*\n")
print("| row | title (cut) | disposition (cut) |")
print("|---|---|---|")
for n, t, d in sorted(rows):
    print("| %d | %s | %s |" % (n, t, d))
print("\n%d rows." % len(rows))
