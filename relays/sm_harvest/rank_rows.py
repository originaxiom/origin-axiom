#!/usr/bin/env python3
"""The SM seat's harvest review: the unverified rows ranked in main's order (its page, M54 item 2).  Mechanical.
  tier 1: rows an open register debt rests on (cited by a QUEUED row marked [DEBT], by harvest row number or by the
          row's own sm label);
  tier 2: rows that carry a sealed number (the row's text says sealed, or names a hash);
  tier 3: the rest.
Rows whose only use is a comparison with data are set aside (main's word: no look without the author's approval); they
are flagged by their text, which is a heuristic, and listed so that a wrong flag can be seen.
    python3 rank_rows.py HARVEST_LEDGER POINT_REGISTER > ../SM_HARVEST_RANKED_ROWS.md"""
import re
import sys

ledger, register = sys.argv[1], sys.argv[2]
rows = []
for l in open(ledger, encoding="utf-8"):
    if not l.startswith("| "):
        continue
    c = [x.strip() for x in l.split("|")]
    if len(c) < 8 or not c[1].isdigit() or "SM" not in c[2]:
        continue
    d = c[6]
    if any(k in d[:120] for k in ("RECEIVED", "REGISTERED", "OWED", "owed", "SCHEDULED")) and "VERIFIED" not in d[:120]:
        rows.append(dict(n=int(c[1]), title=c[3], disp=d))
debts = []
for l in open(register, encoding="utf-8"):
    if l.startswith("| P-") and "QUEUED" in l and "[DEBT]" in l:
        debts.append((l.split("|")[1].strip(), l))
def labels(r):
    out = set(re.findall(r"sm:[BLW]\d+", r["title"]))
    return out
DATA = re.compile(r"\b(measured|PDG|chi\^?2|χ²|the data|data's|against data|value look|sealed look)\b", re.I)
SEALED = re.compile(r"\b(sealed|SHA-256|sha256|hash)\b", re.I)
for r in rows:
    cites = []
    for p, l in debts:
        if re.search(r"(harvest )?rows? %d\b" % r["n"], l) or any(lab in l for lab in labels(r)):
            cites.append(p)
    r["debts"] = cites
    text = r["title"] + " " + r["disp"]
    r["data"] = bool(DATA.search(text))
    r["tier"] = 1 if cites else (2 if SEALED.search(text) else 3)
cut = lambda s, n: re.sub(r"\s+", " ", s[:n]).replace("|", "/").replace("`", "")
print("# The SM seat's unverified ledger rows, ranked in main's order (M54, item 2)\n")
print("*Generated by `relays/sm_harvest/rank_rows.py` from main's docs/HARVEST_LEDGER.md and docs/POINT_REGISTER.md.")
print("Tier 1: rows an open debt rests on (a QUEUED [DEBT] register row cites the harvest row's number or its sm label).")
print("Tier 2: rows that carry a sealed number. Tier 3: the rest. Rows flagged as a comparison with data are set aside,")
print("by a text heuristic, and listed at the end so that a wrong flag can be seen. Heads cut at 90 characters.*\n")
for t in (1, 2, 3):
    sel = [r for r in rows if r["tier"] == t and not r["data"]]
    print("## Tier %d (%d rows)\n" % (t, len(sel)))
    print("| row | title (cut) | cited by | disposition (cut) |")
    print("|---|---|---|---|")
    for r in sorted(sel, key=lambda r: r["n"]):
        print("| %d | %s | %s | %s |" % (r["n"], cut(r["title"], 60), ", ".join(r["debts"]) or "—", cut(r["disp"], 90)))
    print()
aside = [r for r in rows if r["data"]]
print("## Set aside: flagged as a comparison with data (%d rows)\n" % len(aside))
print("| row | tier it would have | title (cut) |")
print("|---|---|---|")
for r in sorted(aside, key=lambda r: r["n"]):
    print("| %d | %d | %s |" % (r["n"], r["tier"], cut(r["title"], 80)))
print("\n%d rows in all; %d QUEUED [DEBT] register rows read." % (len(rows), len(debts)))
