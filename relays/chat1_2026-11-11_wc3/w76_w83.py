import itertools
import json
import sys

import numpy as np


def lyndon(n, alphabet):
    k = len(alphabet)
    out = []
    w = [-1]
    while w:
        w[-1] += 1
        m = len(w)
        if m == n:
            out.append(''.join(alphabet[i] for i in w))
        while len(w) < n:
            w.append(w[len(w) - m])
        while w and w[-1] == k - 1:
            w.pop()
    return out


def canon_rot(w):
    return min(w[i:] + w[:i] for i in range(len(w)))


def mirror(w):
    return w.translate(str.maketrans('LR', 'RL'))


def kind(w):
    m = canon_rot(mirror(w))
    rot = (m == canon_rot(w))
    rev = (m == canon_rot(w[::-1]))
    return rot, rev


def e8_roots():
    roots = []
    for i, j in itertools.combinations(range(8), 2):
        for si, sj in itertools.product((1, -1), repeat=2):
            v = [0.0] * 8
            v[i], v[j] = si, sj
            roots.append(v)
    for signs in itertools.product((0.5, -0.5), repeat=8):
        if sum(1 for s in signs if s < 0) % 2 == 0:
            roots.append(list(signs))
    return np.array(roots)


def components(rs):
    n = len(rs)
    G = np.abs(rs @ rs.T) > 1e-9
    seen = set()
    comps = 0
    for s in range(n):
        if s in seen:
            continue
        comps += 1
        stack = [s]
        seen.add(s)
        while stack:
            x = stack.pop()
            for y in np.where(G[x])[0]:
                if int(y) not in seen:
                    seen.add(int(y))
                    stack.append(int(y))
    return comps


def quarter(axis, sense):
    m = np.zeros((3, 3))
    m[axis, axis] = 1
    a, b = [i for i in range(3) if i != axis]
    m[a, b] = -sense
    m[b, a] = sense
    return m


def close_group(gens):
    elems = [np.eye(gens[0].shape[0], dtype=complex)]
    keys = {tuple(np.round(elems[0], 9).ravel())}
    frontier = list(elems)
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = x @ g
                k = tuple(np.round(y, 9).ravel())
                if k not in keys:
                    keys.add(k)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
        if len(elems) > 5000:
            break
    return elems


def commutant_dim(gens, n):
    rows = [np.kron(g, np.eye(n)) - np.kron(np.eye(n), g.T) for g in gens]
    K = np.vstack(rows)
    return n * n - np.linalg.matrix_rank(K, tol=1e-9)


def main():
    out = {}
    # K1
    print('K1  LLR mirror-symmetric (rotation, reversal): %s; LR: %s' % (kind('LLR'), kind('LR')))
    out['K1'] = (kind('LLR'), kind('LR'))
    # W76a
    words = []
    for n in range(2, 17):
        words += lyndon(n, 'LR')
    sym = [w for w in words if any(kind(w))]
    rot_only = [w for w in sym if kind(w) == (True, False)]
    rev_only = [w for w in sym if kind(w) == (False, True)]
    both = [w for w in sym if kind(w) == (True, True)]
    to12 = [w for w in words if len(w) <= 12]
    sym12 = [w for w in to12 if any(kind(w))]
    a = dict(threads=len(words), mirror_symmetric=len(sym), rotation_only=len(rot_only), reversal_only=len(rev_only),
             both=len(both), threads_to_12=len(to12), mirror_symmetric_to_12=len(sym12))
    print('W76a', a)
    out['W76a'] = a
    # W76b
    import snappy
    vals = []
    bad = []
    for w in sym:
        M = snappy.Manifold('b++' + w)
        st = M.solution_type()
        cs = float(M.chern_simons())
        vals.append((w, st, cs))
        if st != 'all tetrahedra positively oriented' or abs(cs) >= 1e-9:
            bad.append((w, st, cs))
    mx = max(abs(v[2]) for v in vals)
    print('W76b %d bundles; geometric: %d; largest |CS| as returned: %.3g; outside the rule: %d %s'
          % (len(vals), sum(1 for v in vals if v[1] == 'all tetrahedra positively oriented'), mx, len(bad), bad[:5]))
    out['W76b'] = dict(n=len(vals), largest_abs_cs=mx, outside=bad, sample=vals[:5])
    # W83a
    R = e8_roots()
    assert len(R) == 240
    alpha = np.array([1, -1, 0, 0, 0, 0, 0, 0], dtype=float)
    beta = np.array([0, 1, -1, 0, 0, 0, 0, 0], dtype=float)
    gamma = np.array([0, 0, 0, 1, -1, 0, 0, 0], dtype=float)
    k2 = int(np.sum(np.abs(R @ alpha) < 1e-9))
    e6 = R[(np.abs(R @ alpha) < 1e-9) & (np.abs(R @ beta) < 1e-9)]
    in_e6 = bool(np.any(np.all(np.abs(e6 - gamma) < 1e-9, axis=1)))
    a5 = e6[np.abs(e6 @ gamma) < 1e-9]
    r83 = dict(K2_orthogonal_to_one_root=k2, orthogonal_to_A2=len(e6), gamma_in_that_E6=in_e6,
               orthogonal_also_to_gamma=len(a5), rank=int(np.linalg.matrix_rank(a5)), components=components(a5))
    print('W83a', r83)
    out['W83a'] = r83
    # W83b
    cL, cR = np.exp(-1j * np.pi / 4), np.exp(1j * np.pi / 4)
    lifts = None
    for aL, aR in itertools.permutations(range(3), 2):
        for sL, sR in itertools.product((1, -1), repeat=2):
            rL, rR = cL * quarter(aL, sL), cR * quarter(aR, sR)
            if np.allclose(rL @ np.linalg.inv(rR) @ rL, np.linalg.inv(rR) @ rL @ np.linalg.inv(rR), atol=1e-12):
                if len(close_group([rL, rR])) == 96 and lifts is None:
                    lifts = (rL, rR, (aL, sL, aR, sR))
    rL, rR, choice = lifts
    K3 = dict(choice=choice, order=len(close_group([rL, rR])), commutant_on_T=int(commutant_dim([rL, rR], 3)))
    print('K3  ', K3)
    out['K3'] = K3
    qi = np.array([[1j, 0], [0, -1j]])
    qj = np.array([[0, 1], [-1, 0]], dtype=complex)
    s3 = [np.array([[0, 1, 0], [1, 0, 0], [0, 0, 1]], dtype=complex),
          np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0]], dtype=complex)]
    dims = {}
    for label, Tg in (("the weave's lifts", [rL, rR]), ('S3, the permutation triplet', s3), ('trivial', [])):
        gens = [np.kron(g, np.eye(2)) for g in Tg] + [np.kron(np.eye(3), h) for h in (qi, qj)]
        dims[label] = int(commutant_dim(gens, 6)) - 1
    print('W83b trace-free commutant on 6 = T (x) 2_q:', dims)
    out['W83b'] = dims
    json.dump(out, open(sys.argv[1], 'w'), indent=1, default=str)
    return 0


if __name__ == '__main__':
    sys.exit(main())
