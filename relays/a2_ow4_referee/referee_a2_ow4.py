def run_ow4_d(exact_bundle):
    weights_by_D = exact_bundle["weights_by_D"]
    cc = exact_bundle["central_charges"]
    solve_ca = exact_bundle["solve_ca"]

    w_s_4 = weights_by_D[4]["w_s"]
    w_W_4 = weights_by_D[4]["w_W"]
    w_V_4 = weights_by_D[4]["w_V"]
    w_W_6 = weights_by_D[6]["w_W"]
    w_V_6 = weights_by_D[6]["w_V"]

    # PF-OW4-1: Flip Dirac Berezin sign (+a1_D/2 instead of -a1_D/2 => w_W_fault = -w_W_4)
    w_W_fault = -w_W_4
    broda_residual_pf1 = 6 * w_W_fault - Fraction(1, 1)
    fg_balance_pf1 = Fraction(48, 1) * w_W_fault + Fraction(12, 1) * w_V_4
    six_cgrav_2H_pf1 = 6 * (Fraction(8, 1) * w_s_4 + fg_balance_pf1)
    six_cgrav_1H_pf1 = 6 * (Fraction(4, 1) * w_s_4 + fg_balance_pf1)
    pf1_caught = (broda_residual_pf1 != 0) and (fg_balance_pf1 != 0) and (six_cgrav_2H_pf1 < 0)

    # PF-OW4-2: Omit l=0 scalar ghost zero-mode (-6) on S^4 => a2_V shifts from -62/15 to +28/15
    a2_V_true = exact_bundle["a2_s4_V_true"]
    a2_V_fault = exact_bundle["a2_s4_V_no_l0_ghost"]
    a2_V_shift = a2_V_fault - a2_V_true
    c_V_fault, a_V_fault = solve_ca(a2_V_fault, exact_bundle["a2_s2s2_V_true"])
    pf2_caught = (
        (a2_V_fault == Fraction(28, 15))
        and (a2_V_shift == Fraction(6, 1))
        and (a2_V_fault != a2_V_true)
        and (a_V_fault != cc["a_V"])
        and (a_V_fault < 0)
    )

    # PF-OW4-3: Shift N_gen = 2 at N = 5, D = 4 => ghost/repulsive gravity
    n_W_pf3 = 2 * 16
    fg_pf3 = Fraction(n_W_pf3, 1) * w_W_4 + Fraction(12, 1) * w_V_4
