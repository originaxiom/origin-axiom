def compute_bernoulli_numbers(n_max):
    """Exact Bernoulli numbers B_0 .. B_{n_max} (with B_1 = -1/2) via recurrence."""
    B = [Fraction(0, 1)] * (n_max + 1)
    B[0] = Fraction(1, 1)
    for m in range(1, n_max + 1):
        s = Fraction(0, 1)
        for k in range(m):
            s += Fraction(math.comb(m + 1, k), 1) * B[k]
        B[m] = -s / Fraction(m + 1, 1)
    return B


def bernoulli_poly_eval(n, alpha, B):
    """Exact Bernoulli polynomial B_n(alpha) = sum_{k=0}^n C(n,k) B_k alpha^{n-k}."""
    alpha = Fraction(alpha)
    total = Fraction(0, 1)
    for k in range(n + 1):
        total += Fraction(math.comb(n, k), 1) * B[k] * (alpha ** (n - k))
    return total


def poly_mul(p1, p2):
    out = {}
    for e1, c1 in p1.items():
        for e2, c2 in p2.items():
            e = e1 + e2
            out[e] = out.get(e, Fraction(0, 1)) + c1 * c2
    return {e: c for e, c in out.items() if c != 0}


def poly_eval(poly, x):
    x = Fraction(x)
    total = Fraction(0, 1)
    for e, c in poly.items():
        total += c * (x ** e)
    return total


def series_add(s1, s2, max_pow):
    keys = set(s1.keys()) | set(s2.keys())
    out = {}
    for k in keys:
        if k <= max_pow:
            v = s1.get(k, Fraction(0, 1)) + s2.get(k, Fraction(0, 1))
            if v != 0:
                out[k] = v
    return out


def series_scale(s, scalar):
    scalar = Fraction(scalar)
    if scalar == 0:
        return {}
    return {k: v * scalar for k, v in s.items()}


def series_mul(s1, s2, max_pow):
    out = {}
    for e1, c1 in s1.items():
        for e2, c2 in s2.items():
            e = e1 + e2
            if e <= max_pow:
                out[e] = out.get(e, Fraction(0, 1)) + c1 * c2
    return {e: c for e, c in out.items() if c != 0}


def exp_series(coeff, max_pow):
    """Exact Taylor series of exp(coeff * t) through t^{max_pow}."""
    coeff = Fraction(coeff)
    out = {0: Fraction(1, 1)}
    cur = Fraction(1, 1)
    for m in range(1, max_pow + 1):
        cur = cur * coeff / Fraction(m, 1)
        if cur != 0:
            out[m] = cur
    return out


def hurwitz_heat_series_odd_power(p, alpha, j_max, B):
    """
    Exact asymptotic Laurent series of
      F_p(alpha; t) = sum_{k=0}^infty (k + alpha)^p exp(-t (k + alpha)^2)
    for odd integer p = 2r + 1 and rational alpha > 0, via Mellin/Hurwitz-zeta:
      F_p(alpha; t) ~ (r!/2) t^{-(r+1)}
                      - sum_{j=0}^{j_max} ((-1)^j / j!) (B_{2j+p+1}(alpha) / (2j+p+1)) t^j.
    """
    assert p >= 1 and p % 2 == 1
    r = (p - 1) // 2
    out = {-(r + 1): Fraction(math.factorial(r), 2)}
    for j in range(j_max + 1):
        deg = 2 * j + p + 1
        bn = bernoulli_poly_eval(deg, alpha, B)
        sign = -1 if (j % 2 == 0) else 1
        coeff = Fraction(sign, math.factorial(j)) * bn / Fraction(deg, 1)
        if coeff != 0:
            out[j] = out.get(j, Fraction(0, 1)) + coeff
    return out


def build_sphere_spectra_polys(D):
    """
    Build exact polynomial representations g(n) and spectral shift c_shift
    such that lambda(l) = n(l)^2 - c_shift on unit S^D (even D >= 2),
    and assert polynomial == exact combinatorial degeneracy for l = l_min .. 20.
    """
    assert D >= 2 and D % 2 == 0
    m = D // 2

    # 1. Scalar Laplacian: l >= 0, n = l + (D-1)/2, alpha = 1/2
    c_scalar = Fraction(D - 1, 2) ** 2
    poly_s = {1: Fraction(2, math.factorial(D - 1))}
    for j in range(1, m):
        shift_sq = Fraction(2 * j - 1, 2) ** 2
        poly_s = poly_mul(poly_s, {2: Fraction(1, 1), 0: -shift_sq})
    for l in range(0, 21):
        g_comb = Fraction((2 * l + D - 1) * math.factorial(l + D - 2), math.factorial(l) * math.factorial(D - 1))
        n_val = Fraction(l, 1) + Fraction(D - 1, 2)
        assert poly_eval(poly_s, n_val) == g_comb
        assert n_val * n_val - c_scalar == Fraction(l * (l + D - 1), 1)

    # 2. Dirac squared: l >= 0, n = l + D/2, alpha = 1
    c_dirac = Fraction(0, 1)
    poly_D = {1: Fraction(1 << (m + 1), math.factorial(D - 1))}
    for j in range(1, m):
        poly_D = poly_mul(poly_D, {2: Fraction(1, 1), 0: Fraction(-j * j, 1)})
    for l in range(0, 21):
        g_comb = Fraction((1 << (m + 1)) * math.comb(l + D - 1, l), 1)
        n_val = Fraction(l + m, 1)
        assert poly_eval(poly_D, n_val) == g_comb
        assert n_val * n_val - c_dirac == Fraction((l + m) * (l + m), 1)

    # 3. Transverse (co-closed) Hodge 1-forms (for D >= 4): l >= 1, n = l + (D-1)/2, alpha = 1/2
    poly_T = None
    c_trans = None
    if D >= 4:
        c_trans = Fraction(D - 3, 2) ** 2
        poly_T = {1: Fraction(2, math.factorial(D - 2))}
        poly_T = poly_mul(poly_T, {2: Fraction(1, 1), 0: -Fraction(D - 1, 2) ** 2})
        for j in range(1, m - 1):
            shift_sq = Fraction(2 * j - 1, 2) ** 2
            poly_T = poly_mul(poly_T, {2: Fraction(1, 1), 0: -shift_sq})
        for l in range(1, 21):
            g_comb = Fraction(
                l * (l + D - 1) * (2 * l + D - 1) * math.factorial(l + D - 3),
                math.factorial(D - 2) * math.factorial(l + 1),
            )
            n_val = Fraction(l, 1) + Fraction(D - 1, 2)
            assert poly_eval(poly_T, n_val) == g_comb
            assert n_val * n_val - c_trans == Fraction((l + 1) * (l + D - 2), 1)

    return {
        "D": D,
        "scalar": {"poly": poly_s, "alpha": Fraction(1, 2), "n_min": Fraction(D - 1, 2), "c_shift": c_scalar},
        "dirac": {"poly": poly_D, "alpha": Fraction(1, 1), "n_min": Fraction(D, 2), "c_shift": c_dirac},
        "transverse_1form": (
            {"poly": poly_T, "alpha": Fraction(1, 2), "n_min": Fraction(D + 1, 2), "c_shift": c_trans}
            if D >= 4
            else None
        ),
    }


def exact_heat_series_from_poly(spec_info, j_max, out_max_pow, B):
    """
    Compute exact small-t Laurent series of
      K(t) = sum_{n >= n_min, n = k + alpha} P(n) exp(-t (n^2 - c_shift))
    by summing over all k >= 0 via Hurwitz-zeta and explicitly subtracting any
    k >= 0 with k + alpha < n_min.
    """
    poly = spec_info["poly"]
    alpha = spec_info["alpha"]
    n_min = spec_info["n_min"]
    c_shift = spec_info["c_shift"]

    # Sum_{k=0}^infty P(k + alpha) exp(-t (k + alpha)^2)
    raw = {}
    for p, coeff in poly.items():
        fp = hurwitz_heat_series_odd_power(p, alpha, j_max, B)
        raw = series_add(raw, series_scale(fp, coeff), j_max)

    # Multiply by exp(c_shift * t)
    exp_shift = exp_series(c_shift, j_max + 6)
    K_all = series_mul(raw, exp_shift, out_max_pow)

    # Subtract boundary terms with k + alpha < n_min
    k = 0
    while alpha + Fraction(k, 1) < n_min:
        n_val = alpha + Fraction(k, 1)
        val = poly_eval(poly, n_val)
        if val != 0:
            lam = n_val * n_val - c_shift
            term = series_scale(exp_series(-lam, out_max_pow), -val)
            K_all = series_add(K_all, term, out_max_pow)
        k += 1

    return K_all


def eval_laurent_mp(series, t_mp, max_pow=None):
    total = mpmath.mpf(0)
    for e, c in series.items():
        if max_pow is not None and e > max_pow:
            continue
        total += frac_to_mpf(c) * mpmath.power(t_mp, e)
    return total


def direct_sphere_heat_mp(D, field, t_mp, L_max=220):
    """Independent 50-digit direct eigenvalue-degeneracy sum (no polynomials/Hurwitz)."""
    total = mpmath.mpf(0)
    m = D // 2
    if field == "scalar":
        for l in range(0, L_max + 1):
            g = ((2 * l + D - 1) * math.factorial(l + D - 2)) // (math.factorial(l) * math.factorial(D - 1))
            lam = l * (l + D - 1)
            total += mpmath.mpf(g) * mpmath.exp(-t_mp * mpmath.mpf(lam))
    elif field == "dirac":
        scale = 1 << (m + 1)
        for l in range(0, L_max + 1):
            g = scale * math.comb(l + D - 1, l)
            lam = (l + m) * (l + m)
            total += mpmath.mpf(g) * mpmath.exp(-t_mp * mpmath.mpf(lam))
    elif field == "transverse_1form":
        for l in range(1, L_max + 1):
            g = (l * (l + D - 1) * (2 * l + D - 1) * math.factorial(l + D - 3)) // (
                math.factorial(D - 2) * math.factorial(l + 1)
            )
            lam = (l + 1) * (l + D - 2)
            total += mpmath.mpf(g) * mpmath.exp(-t_mp * mpmath.mpf(lam))
    else:
        raise ValueError(field)
    return total


