# OW4-C: (D, N_gen) Scan, All-21 4D Gravity Table, (c, a) Charges, a_0 CC No-Go
# =============================================================================

def run_ow4_c(ow4_a_res, exact_bundle):
    weights_by_D = exact_bundle["weights_by_D"]
    cc = exact_bundle["central_charges"]
    actions = ow4_a_res["actions"]

    sm_action = [x for x in actions if x["N"] == 5 and x["d"] == 5][0]
    n_V_sm = sm_action["n_V"]
    fock_sm = sm_action["fock_even"]
    n_s_1H_sm = sm_action["n_s_1H"]
    n_s_2H_sm = sm_action["n_s_2H"]

    # 1. (D in {4, 6, 8, 10}, N_gen in {1, 2, 3, 4}) scan on N=5, d=5 engine
    d_ngen_scan = []
    exact_fg_solutions = []
    for D in (4, 6, 8, 10):
        w_s = weights_by_D[D]["w_s"]
        w_W = weights_by_D[D]["w_W"]
        w_V = weights_by_D[D]["w_V"]
        n_gen_req = (-Fraction(n_V_sm, 1) * w_V) / (Fraction(fock_sm, 1) * w_W) if w_V < 0 else None

        for N_gen in (1, 2, 3, 4):
            n_W = N_gen * fock_sm
            fg_bal = Fraction(n_W, 1) * w_W + Fraction(n_V_sm, 1) * w_V
            cgrav_min_1H = Fraction(n_s_1H_sm, 1) * w_s + fg_bal
            cgrav_min_2H = Fraction(n_s_2H_sm, 1) * w_s + fg_bal
            cgrav_conf = fg_bal
            is_exact_fg = (fg_bal == 0)
            if is_exact_fg:
                exact_fg_solutions.append((D, N_gen))
            d_ngen_scan.append({
                "D": D,
                "N_gen": N_gen,
                "n_W": n_W,
                "n_V": n_V_sm,
                "w_s": frac_str(w_s),
                "w_W": frac_str(w_W),
                "w_V": frac_str(w_V),
                "fermion_gauge_balance": frac_str(fg_bal),
                "exact_fg_cancellation": is_exact_fg,
                "N_gen_required_for_cancellation": frac_str(n_gen_req) if n_gen_req is not None else "impossible",
                "C_grav_min_1H": frac_str(cgrav_min_1H),
                "C_grav_min_2H": frac_str(cgrav_min_2H),
                "6_C_grav_min_1H": frac_str(6 * cgrav_min_1H),
                "6_C_grav_min_2H": frac_str(6 * cgrav_min_2H),
                "6_C_grav_conf": frac_str(6 * cgrav_conf),
                "attractive_min_1H": (cgrav_min_1H > 0),
                "attractive_min_2H": (cgrav_min_2H > 0),
            })

    # 2. All-21 4D Gravity Table (for N_gen in {1, 2, 3})
    w_s_4 = weights_by_D[4]["w_s"]
    w_W_4 = weights_by_D[4]["w_W"]
    w_V_4 = weights_by_D[4]["w_V"]

    all21_4d_table = []
    af_attractive_1to3_1H = []
    af_attractive_1to3_2H = []
    vector_like_neg_checks = []

    for act in actions:
        per_ngen = {}
        for N_gen in (1, 2, 3):
            n_W = (N_gen * act["fock_even"]) if act["is_chiral"] else 0
            fg = Fraction(n_W, 1) * w_W_4 + Fraction(act["n_V"], 1) * w_V_4
            cg_1H = Fraction(act["n_s_1H"], 1) * w_s_4 + fg
            cg_2H = Fraction(act["n_s_2H"], 1) * w_s_4 + fg
            if not act["is_chiral"]:
                vector_like_neg_checks.append((cg_1H < 0) and (cg_2H < 0))
            if act["anomaly_free"] and cg_1H > 0:
                af_attractive_1to3_1H.append((act["N"], act["d"], act["cycle_type"], N_gen))
            if act["anomaly_free"] and cg_2H > 0:
                af_attractive_1to3_2H.append((act["N"], act["d"], act["cycle_type"], N_gen))
            per_ngen[f"N_gen={N_gen}"] = {
                "n_W": n_W,
                "6_C_grav_min_1H": frac_str(6 * cg_1H),
                "6_C_grav_min_2H": frac_str(6 * cg_2H),
                "6_C_grav_conf": frac_str(6 * fg),
                "attractive_1H": (cg_1H > 0),
                "attractive_2H": (cg_2H > 0),
            }
        all21_4d_table.append({
            "N": act["N"],
            "d": act["d"],
            "cycle_type": act["cycle_type"],
            "a": act["a"],
            "b": act["b"],
            "n_V": act["n_V"],
            "n_s_1H": act["n_s_1H"],
            "n_s_2H": act["n_s_2H"],
            "is_chiral": act["is_chiral"],
            "anomaly_free": act["anomaly_free"],
            "gravity_4d": per_ngen,
        })
    vector_like_all_negative = (len(vector_like_neg_checks) > 0) and all(vector_like_neg_checks)

    # 3. 4D Trace Anomaly Total Charges (c, a) for unique (N=5, d=5, N_gen=3)
    n_W_3 = 3 * fock_sm
    c_tot_2H = n_s_2H_sm * cc["c_s"] + n_W_3 * cc["c_W"] + n_V_sm * cc["c_V"]
    a_tot_2H = n_s_2H_sm * cc["a_s"] + n_W_3 * cc["a_W"] + n_V_sm * cc["a_V"]
    c_tot_1H = n_s_1H_sm * cc["c_s"] + n_W_3 * cc["c_W"] + n_V_sm * cc["c_V"]
    a_tot_1H = n_s_1H_sm * cc["a_s"] + n_W_3 * cc["a_W"] + n_V_sm * cc["a_V"]

    # 4. Honest a_0 Cosmological Constant No-Go (computed directly from heat-kernel a0_s, a0_W, a0_V)
    a0_s_4 = weights_by_D[4]["a0_s"]
    a0_W_4 = weights_by_D[4]["a0_W"]
    a0_V_4 = weights_by_D[4]["a0_V"]
    a0_tot_2H = n_s_2H_sm * a0_s_4 + n_W_3 * a0_W_4 + n_V_sm * a0_V_4
    a0_tot_1H = n_s_1H_sm * a0_s_4 + n_W_3 * a0_W_4 + n_V_sm * a0_V_4
    # Cross-check against n_B - n_F from OW4-A
    assert a0_tot_2H == Fraction(sm_action["n_B_2H"] - sm_action["n_F_chiral_3gen"], 1)
    assert a0_tot_1H == Fraction(sm_action["n_B_1H"] - sm_action["n_F_chiral_3gen"], 1)

    cc_quartic_cancels = (a0_tot_2H == 0) or (a0_tot_1H == 0)
    cc_nogo_confirmed = (a0_tot_2H != 0) and (a0_tot_1H != 0)

    ow4_c_pass = (
        exact_fg_solutions == [(4, 3)]
        and len(af_attractive_1to3_1H) == 1
        and len(af_attractive_1to3_2H) == 1
        and af_attractive_1to3_1H[0] == (5, 5, [1, 2, 2], 3)
        and af_attractive_1to3_2H[0] == (5, 5, [1, 2, 2], 3)
        and vector_like_all_negative
        and c_tot_2H == Fraction(37, 15)
        and a_tot_2H == Fraction(127, 45)
        and c_tot_1H == Fraction(73, 30)
        and a_tot_1H == Fraction(253, 90)
        and a0_tot_2H == Fraction(-64, 1)
        and a0_tot_1H == Fraction(-68, 1)
        and cc_nogo_confirmed
        and (not cc_quartic_cancels)
    )

    return {
        "D_Ngen_scan": d_ngen_scan,
        "unique_exact_fg_cancellation": [{"D": d, "N_gen": ng} for d, ng in exact_fg_solutions],
        "all21_4d_gravity_table": all21_4d_table,
        "unique_attractive_af_1to3_1H": [
            {"N": t[0], "d": t[1], "cycle_type": t[2], "N_gen": t[3]} for t in af_attractive_1to3_1H
        ],
        "unique_attractive_af_1to3_2H": [
            {"N": t[0], "d": t[1], "cycle_type": t[2], "N_gen": t[3]} for t in af_attractive_1to3_2H
        ],
        "all_vector_like_ghost_gravity": vector_like_all_negative,
        "trace_anomaly_4d_SM": {
            "2H": {"c": frac_str(c_tot_2H), "a": frac_str(a_tot_2H), "c_positive": (c_tot_2H > 0), "a_positive": (a_tot_2H > 0)},
            "1H": {"c": frac_str(c_tot_1H), "a": frac_str(a_tot_1H), "c_positive": (c_tot_1H > 0), "a_positive": (a_tot_1H > 0)},
        },
        "honest_a0_cc_nogo": {
            "a0_s": frac_str(a0_s_4),
            "a0_W": frac_str(a0_W_4),
            "a0_V": frac_str(a0_V_4),
            "a0_total_2H": frac_str(a0_tot_2H),
            "a0_total_1H": frac_str(a0_tot_1H),
            "quartic_cc_cancellation_occurs": cc_quartic_cancels,
            "cc_nogo_confirmed": cc_nogo_confirmed,
        },
        "ow4_c_pass": ow4_c_pass,
    }


