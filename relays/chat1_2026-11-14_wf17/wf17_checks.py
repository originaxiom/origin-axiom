def cyc_reduce(w):
    w, u = list(w), []
    while len(w) >= 2 and w[0] == -w[-1]:
        u.append(w[0])
        w = w[1:-1]
    return tuple(u), tuple(w)


def find_conjugator(f, det):
    target = apply(f, LAM)
    u, c = cyc_reduce(target)
    base = LAM if det == 1 else inv(LAM)
    for k in range(len(base)):
        if base[k:] + base[:k] == c:
            g = red(u + inv(base[:k]))
            if red(g + base + inv(g)) == target:
                return g
    raise RuntimeError("no conjugator")


def census(word, sign, p, plant=False):
    f = word_aut(word, sign)
    A = abel_mat(f)
    det = A[0][0] * A[1][1] - A[0][1] * A[1][0]
    tor = abs((A[0][0] - 1) * (A[1][1] - 1) - A[0][1] * A[1][0])
    g1 = gcd(gcd(A[0][0] - 1, A[0][1]), gcd(A[1][0], A[1][1] - 1))
    e = tor // g1
    g = find_conjugator(f, det)
    mu = red(inv(g) + (3,))
    ga, gb = abel2(g)
    gen = next(x for x in range(2, p) if all(pow(x, (p - 1) // q, p) != 1 for q in prime_factors(p - 1)))
    zz = pow(gen, (p - 1) // e, p)
    chars = []
    for k1 in range(e):
        for k2 in range(e):
            if (k1, k2) != (0, 0) and (k1 * A[0][0] + k2 * A[1][0] - k1) % e == 0 and \
                    (k1 * A[0][1] + k2 * A[1][1] - k2) % e == 0:
                chars.append((pow(zz, k1, p), pow(zz, k2, p), pow(zz, (k1 * ga + k2 * gb) % e, p)))
    fr = word_aut(word, -sign) if plant else f
    rels = [red((3, 1, -3) + inv(fr[1])), red((3, 2, -3) + inv(fr[2]))]

    def is_hom(mats):
        R = Rep(mats, p)
        return all(R.of(r) == ident(len(mats[1])) for r in rels)
    if plant:
        return sum(not is_hom({1: [[c[0]]], 2: [[c[1]]], 3: [[c[2]]]}) for c in chars)
    cls, slope = {}, {}
    for ch in chars:
        r1 = Rep({1: [[ch[0]]], 2: [[ch[1]]], 3: [[ch[2]]]}, p)
        F = [[r1.fox(r, gi)[0][0] for gi in (1, 2, 3)] for r in rels]
        cls[ch] = None
        for zb in nullspace_mod(F, p, 3):
            lv = r1.cocycle_value({1: [zb[0]], 2: [zb[1]], 3: [zb[2]]}, LAM)[0] % p
            if lv:
                iv = pow(lv, p - 2, p)
                c = {gi: [zb[gi - 1] * iv % p] for gi in (1, 2, 3)}
                cls[ch] = c
                slope[ch] = r1.cocycle_value(c, mu)[0]
                break
    I, fire_ok, nmod, hom_ok = {}, True, 0, True
    for l in chars:
        c = cls[l]
        if c is None:
            continue
        for al in chars:
            if al == l:
                continue
            be = [al[i] * pow(l[i], p - 2, p) % p for i in range(3)]
            V = {gi: [[al[gi - 1], c[gi][0] * be[gi - 1] % p], [0, be[gi - 1]]] for gi in (1, 2, 3)}
            hom_ok &= is_hom(V)
            R = Rep(V, p)
            D = {gi: [list(row) for row in zip(*R.inv[gi])] for gi in (1, 2, 3)}
            nV, nD = cohomology(R, rels, mu, LAM)["n"], cohomology(Rep(D, p), rels, mu, LAM)["n"]
            I[(l, al)] = nV - nD
            fire_ok &= nV == int(slope.get(al) is not None and slope[al] == slope[l])
            nmod += 1
    dual_ok = True
    for (l, al), v in I.items():
        partner = tuple(l[i] * pow(al[i], p - 2, p) % p for i in range(3))
        dual_ok &= I.get((l, partner)) == -v
    hist = {}
    for v in I.values():
        hist[v] = hist.get(v, 0) + 1
    return dict(det=det, tor=tor, e=e, nchar=len(chars), with_class=sum(c is not None for c in cls.values()),
                nmod=nmod, hom_ok=hom_ok, dual_ok=dual_ok, fire_ok=fire_ok, hist=dict(sorted(hist.items())),
                nonzero=sum(1 for v in I.values() if v))


