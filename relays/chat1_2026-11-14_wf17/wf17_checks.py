        allg = sl2(7)
        mf = matmul_p(7)

        def order(A):
            k, X = 1, A
            while X != (1, 0, 0, 1):
                X, k = mf(X, A), k + 1
            return k
        o8 = [A for A in allg if order(A) == 8]
