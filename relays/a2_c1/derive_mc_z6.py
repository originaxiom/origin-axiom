    [ 0,  2,  0, -1,  0,  0],  # alpha_2
    [-1,  0,  2, -1,  0,  0],  # alpha_3
    [ 0, -1, -1,  2, -1,  0],  # alpha_4
    [ 0,  0,  0, -1,  2, -1],  # alpha_5
