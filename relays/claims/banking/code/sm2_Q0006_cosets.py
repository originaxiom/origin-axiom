def category(pn, d, S):
    X1 = flint.fmpq_poly([0, 1])
    p2 = flint.fmpq_poly([int(c) for c in pn.coeffs()])(2 * X1) / flint.fmpq(2) ** d
    Sq = flint.fmpq_poly([int(c) for c in S.coeffs()])
    whole = flint.fmpq_poly([0, -9, 0, 1]) * Sq if not CONTROL else Sq * flint.fmpq_poly([0, 1])
    if p2 == whole: return "a"
    if p2 == Sq: return "a'"
    if Sq.degree() >= 0 and p2 % Sq == 0: return "b"
    return "c"

