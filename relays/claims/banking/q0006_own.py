PLANT = ARGS == ["--plant-no-x"]
PRIMES = [p for p in range(2 ** 61 - 1, 2 ** 61 - 40000, -2) if p % 3 == 1 and flint.fmpz(p).is_prime()][:3]


def group(n):
    def Cm(v): return (v[1], v[2], v[0])
    def Sg(v): return (v[1], v[0], (v[0] * v[1] - v[2]) % n)
    start = (3, 3, 3)
    seen, q = {start}, deque([start])
    while q:
        v = q.popleft()
        for u in (Cm(v), Sg(v)):
            if u not in seen:
                seen.add(u); q.append(u)
    pts = sorted(seen); ix = {v: i for i, v in enumerate(pts)}
    gC = np.array([ix[Cm(v)] for v in pts], dtype=np.int32)
    gS = np.array([ix[Sg(v)] for v in pts], dtype=np.int32)
    ident = np.arange(len(pts), dtype=np.int32)
    elems, key = [ident], {ident.tobytes(): 0}
    q = deque([0])
    while q:                                              # g -> s o g, products as maps
        a = q.popleft()
        for s in (gC, gS):
            b = s[elems[a]]
            k = b.tobytes()
            if k not in key:
                key[k] = len(elems); elems.append(b); q.append(key[k])
    P = np.array(elems)
    m = len(elems)
    mul = np.empty((m, m), dtype=np.int32)                # mul[a, b] = a o b
    for a in range(m):
        prod = P[a][P]
        for b in range(m):
            mul[a, b] = key[prod[b].tobytes()]
    inv = np.empty(m, dtype=np.int32)
    for a in range(m):
        inv[a] = int(np.where(mul[a] == 0)[0][0])
    c, s = key[gC.tobytes()], key[gS.tobytes()]
    stab = [a for a in range(m) if P[a][ix[start]] == ix[start]]
    return m, mul, inv, c, s, stab, len(pts)


def closure(gens, mul):
    H = {0}; q = deque([0])
    while q:
        a = q.popleft()
        for g in gens:
            b = int(mul[a, g])
            if b not in H:
                H.add(b); q.append(b)
    return frozenset(H)


def classes(m, mul, inv):
    order = []
    for a in range(m):
        k, b = 1, a
        while b != 0:
            b = int(mul[b, a]); k += 1
        order.append(k)
    cyc = {}
    for a in range(m):
        Z = closure([a], mul)
        cyc.setdefault(Z, a)
    cyc = [(Z, a) for Z, a in cyc.items()]

    def inv_key(H):
        return (len(H), tuple(sorted(Counter(order[h] for h in H).items())))

    def conjugate(H, gens, R):                         # is some g H g^-1 equal to R?
        for g in range(m):
            gi = int(inv[g])
            if all(int(mul[mul[g, h], gi]) in R for h in gens):
                return True
        return False
    reps, byk = [], {}
    def add(H, gens):
        k = inv_key(H)
        for (R, _) in byk.get(k, []):
            if conjugate(H, gens, R):
                return False
        byk.setdefault(k, []).append((H, gens)); reps.append((H, gens))
        return True
    add(frozenset([0]), [])
    for Z, a in cyc:
        add(Z, [a])
    i = 0
    while i < len(reps):
        H, gens = reps[i]; i += 1
        for Z, a in cyc:
            if a in H:
                continue
            J = closure(gens + [a], mul)
            add(J, gens + [a])
    return reps


def rho(m, mul, c, s):                                  # rho(C) = w, rho(sigma) = -1, as (a mod 3, b mod 2)
    val = {0: (0, 0)}; q = deque([0]); ok = True
    while q:
        a = q.popleft()
        for g, (da, db) in ((c, (1, 0)), (s, (0, 1))):
            b = int(mul[g, a]); v = ((val[a][0] + da) % 3, (val[a][1] + db) % 2)
            if b in val:
                ok = ok and val[b] == v
            else:
                val[b] = v; q.append(b)
    return val, ok


def sectors(perm_list, Cp, p):
    nco = len(Cp)
    corb, rep = [], {}
    for v in range(nco):
        if v in rep:
            continue
        o = [v, Cp[v], Cp[Cp[v]]] if Cp[v] != v else [v]
        for k, u in enumerate(o):
            rep[u] = (len(corb), k)
        corb.append(o)
    three = [i for i, o in enumerate(corb) if len(o) == 3]
    cidx = {i: k for k, i in enumerate(three)}
    w = next(pow(g, (p - 1) // 3, p) for g in range(2, 50) if pow(g, (p - 1) // 3, p) != 1)
    winv, third = pow(w, p - 2, p), pow(3, p - 2, p)
    inv = {1: 1, 3: third}
    Nm = [[0] * len(corb) for _ in corb]
    Cm = [[0] * len(three) for _ in three]
    for i, o in enumerate(corb):
        for u in o:
            for mv in perm_list:
                t, _ = rep[mv[u]]
                Nm[t][i] = (Nm[t][i] + inv[len(corb[t])]) % p
    for i in three:
        for j, u in enumerate(corb[i]):
            for mv in perm_list:
                t, k = rep[mv[u]]
                if len(corb[t]) != 3:
                    continue
                Cm[cidx[t]][cidx[i]] = (Cm[cidx[t]][cidx[i]] + pow(winv, j, p) * pow(w, k, p) % p * third) % p
    pn = flint.nmod_mat(Nm, p).charpoly() if corb else flint.nmod_poly([1], p)
    S = flint.nmod_mat(Cm, p).charpoly() if three else flint.nmod_poly([1], p)
    d = pn.degree()
    co = [int(x) for x in pn.coeffs()]
    half = pow(2, p - 2, p)
    scaled = flint.nmod_poly([co[i] * pow(2, i, p) * pow(half, d, p) % p for i in range(d + 1)], p)
    whole = flint.nmod_poly([0, -9 % p, 0, 1], p) * S
    if scaled == whole:
        return "a"
    if scaled == S:
        return "a'"
    q, r = divmod(scaled, S)
    if S.degree() == 0:
        return "b0"                                     # an empty charged sector: S = 1 divides everything
    return "b" if r == 0 else "c"


def level(n):
    m, mul, inv, c, s, stab, npts = group(n)
    reps = classes(m, mul, inv)
    val, rho_ok = rho(m, mul, c, s)
    stabset = frozenset(stab)
    gi = lambda a: int(inv[a])
    rows, cats, empty = [], Counter(), []
    stab_cat = None
    for H, gens in reps:
        lab = {}
        cos = 0
        for x in range(m):
            if x in lab:
                continue
            for h in H:
                lab[int(mul[x, h])] = cos
            cos += 1
        reps_x = {}
        for x in range(m):
            reps_x.setdefault(lab[x], x)
        def act(g):
            return [lab[int(mul[g, reps_x[i]])] for i in range(cos)]
        C1, S1 = act(c), act(s)
        comp = lambda f, g: [f[g[i]] for i in range(cos)]            # f o g
        C2 = comp(C1, C1)
        L = comp(S1, C2); R = comp(S1, C1); X = comp(C1, comp(S1, C1))
        invp = lambda f: [f.index(i) for i in range(cos)] if cos < 50 else [dict((f[i], i) for i in range(cos))[i] for i in range(cos)]
        moves = [L, R, invp(L), invp(R)] + ([] if PLANT else [X, invp(X)])
        cs = [sectors(moves, C1, p) for p in PRIMES]
        cat = cs[0] if len(set(cs)) == 1 else "disagree:" + ",".join(cs)
        cats[cat] += 1
        if cat == "b0":
            empty.append(cos)
        is_stab = len(H) == len(stabset) and any(
            all(int(mul[mul[g, h], gi(g)]) in stabset for h in gens) for g in range(m))
        if is_stab:
            stab_cat = cat
        if cat == "a":
            fixes = sum(C1[i] == i for i in range(cos))
            triv = all(val[h] == (0, 0) for h in H)
            rows.append((len(H), cos, fixes, triv, is_stab))
    rows.sort()
    return m, npts, len(reps), dict(cats), stab_cat, len(stabset), m // len(stabset), rows, rho_ok, sorted(empty)


