def card_categories(n, cats, empty, want):
    """the card's definitions: (b) is S dividing otherwise, so an empty charged sector (S = 1) is (b), and (a') is its
    own category; the recorded line is compared with them, and with the reading that folds (a') into (b) and counts an
    empty charged sector as (c)"""
    global cats_ok
    mine = {"a": cats.get("a", 0), "a'": cats.get("a'", 0), "b": cats.get("b", 0) + cats.get("b0", 0),
            "c": cats.get("c", 0)}
    print("DECISIVE: mod %d: categories by the card's definitions %s; the recorded line %s; equal %s"
          % (n, sorted(mine.items()), sorted(want.items()), {k: v for k, v in mine.items() if v} == want))
    folded = {"a": mine["a"], "b": mine["a'"] + cats.get("b", 0), "c": mine["c"] + cats.get("b0", 0)}
    print("DECISIVE: mod %d: (a') folded into (b), an empty charged sector (at indices %s) counted as (c): %s; equal "
          "to the recorded line %s" % (n, empty, sorted(folded.items()), folded == want))
    if {k: v for k, v in mine.items() if v} != want:
        cats_ok = False

