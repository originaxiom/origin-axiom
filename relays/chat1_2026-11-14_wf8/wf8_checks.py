#!/usr/bin/env python3
"""W-F8: three distinctions against n. Data-free; this seat's own code.

    python3 -I -u wf8_checks.py

DEFINITIONS
  W_n = <s_1, ..., s_n | s_i^2>, letters 1..n; words are reduced strings with no letter twice in a row. The even part
  E_n (the records) is the kernel of the parity character; an even reduced word splits into consecutive pairs s_j s_k,
  and the pair basis x_i = s_i s_(i+1) (i = 1..n-1) gives H_1(E_n): s_j s_k = x_j + ... + x_(k-1) for j < k and its
  negative for j > k. The puncture of the half-turn face is p = s_1 ... s_n.
  Hurwitz move h_i (i = 1..n-1): s_i -> s_(i+1), s_(i+1) -> s_(i+1) s_i s_(i+1), other letters fixed; its inverse
  h_i^-1: s_i -> s_i s_(i+1) s_i, s_(i+1) -> s_i. A step's matrix is its action on H_1(E_n) in the pair basis.
  The alternating history H_n = h_1 h_2^-1 h_3 h_4^-1 ... h_(n-1)^(+-1) (applied right to left).

EXPECTATIONS, written before the run (by hand: chi(W_n) = n/2 - (n - 1) = 1 - n/2, so E_n is free of rank n - 1 with
chi = 2 - n; p has parity n mod 2; for odd n the puncture lifts to one cusp, generated by p^2, on a surface of genus
(n - 1)/2; for even n it lifts to two cusps, p and s_1 p s_1, on a surface of genus (n - 2)/2):
  T1  For n = 2..7, the matrices of every h_i and h_i^-1 on H_1(E_n) (rank n - 1) are in GL(n - 1, Z).
  T2  For odd n the class of p^2 in H_1(E_n) is 0; for even n the class of p is non-zero, and s_1 p s_1 has the
      opposite class. So only odd n gives one cusp, and only n = 3 gives the records' rank 2.
  T3  Every h_i and h_i^-1 keeps p exactly (as a reduced word), n = 2..7.
  T4  The spectral radius of H_n on H_1(E_n) is 1 for n = 2 and above 1 for n = 3, 4, 5, 6, 7 (a history with
      exponential growth exists for every n >= 3).
  T5  Control: for n = 3, H_3's matrix is hyperbolic in GL(2, Z) (det 1, |trace| > 2).
  Plant: h_1 h_1^-1 has spectral radius 1 (the identity) for every n.
"""
import numpy as np


def say(*a):
    print(*a, flush=True)


def red(w):
    out = []
    for g in w:
        if out and out[-1] == g:
            out.pop()
        else:
            out.append(g)
    return tuple(out)


def img(f, w):
    out = []
    for g in w:
        out.extend(f[g])
    return red(out)


def compose(f, g):  # f o g: apply g, then f
    return {k: img(f, v) for k, v in g.items()}


def h(n, i, inverse=False):
    f = {k: (k,) for k in range(1, n + 1)}
    if not inverse:
        f[i], f[i + 1] = (i + 1,), (i + 1, i, i + 1)
    else:
        f[i], f[i + 1] = (i, i + 1, i), (i,)
    return f


def cls(n, w):
    assert len(w) % 2 == 0
    v = [0] * (n - 1)
    for k in range(0, len(w), 2):
        j, l = w[k], w[k + 1]
        lo, hi, sg = (j, l, 1) if j < l else (l, j, -1)
        for i in range(lo, hi):
            v[i - 1] += sg
    return v


def matrix(n, f):
    return np.array([cls(n, img(f, (i, i + 1))) for i in range(1, n)]).T


def radius(M):
    return max(abs(np.linalg.eigvals(M.astype(float)))) if M.size else 1.0


t1 = t2 = t3 = t4 = t5 = plant = True
for n in range(2, 8):
    p = tuple(range(1, n + 1))
    # T1
    mats = [matrix(n, h(n, i)) for i in range(1, n)] + [matrix(n, h(n, i, True)) for i in range(1, n)]
    t1 &= all(abs(round(np.linalg.det(Mx))) == 1 for Mx in mats)
    # T2
    if n % 2:
        c2 = cls(n, red(p + p))
        t2 &= c2 == [0] * (n - 1)
        say("n =", n, "| p odd; class of p^2:", c2)
    else:
        c1, c1b = cls(n, p), cls(n, red((1,) + p + (1,)))
        t2 &= any(c1) and c1b == [-x for x in c1]
        say("n =", n, "| p even; class of p:", c1, "; of s_1 p s_1:", c1b)
    # T3
    t3 &= all(img(h(n, i, inv_), p) == p for i in range(1, n) for inv_ in (False, True))
    # T4
    H = {k: (k,) for k in range(1, n + 1)}
    for i in range(1, n):
        H = compose(H, h(n, i, inverse=(i % 2 == 0)))
    MH = matrix(n, H)
    r = radius(MH)
    t4 &= (abs(r - 1) < 1e-9) if n == 2 else (r > 1 + 1e-6)
    say("n =", n, "| rank of records", n - 1, "| spectral radius of H_n:", round(float(r), 6), "| matrix", MH.tolist())
    if n == 3:
        t5 = round(np.linalg.det(MH)) == 1 and abs(int(np.trace(MH))) > 2
    I1 = compose(h(n, 1), h(n, 1, True))
    plant &= abs(radius(matrix(n, I1)) - 1) < 1e-9 and np.array_equal(matrix(n, I1), np.eye(n - 1, dtype=int))
say("T1 holds:", t1)
say("T2 holds:", t2)
say("T3 holds:", t3)
say("T4 holds:", t4)
say("T5 holds:", t5)
say("plant (h_1 h_1^-1 is the identity, radius 1):", plant)
