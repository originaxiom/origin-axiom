def mul(A, B):
    return (A[0] * B[0] + A[1] * B[2], A[0] * B[1] + A[1] * B[3], A[2] * B[0] + A[3] * B[2], A[2] * B[1] + A[3] * B[3])


def det(A):
    return A[0] * A[3] - A[1] * A[2]


def reduce_form(a, b, c):
    while True:
        if c < a:
            a, b, c = c, -b, a
        elif abs(b) > a:
            k = (b + a) // (2 * a) if b > 0 else -((-b + a) // (2 * a))
            b, c = b - 2 * k * a, c - k * b + k * k * a
        else:
            if b < 0 and (a == c or -b == a):
                b = -b
            return (a, b, c)


def eta(tau):
    q = mp.exp(2j * mp.pi * tau)
    return mp.exp(2j * mp.pi * tau / 24) * mp.nprod(lambda n: 1 - q ** n, [1, mp.inf])


def t_of(tau):
    return (eta(tau) / eta(5 * tau)) ** 6


def s_of(tau):
    """r(tau)^5, with r = q^(1/5) prod (1 - q^n)^(n/5), (n/5) the Legendre symbol."""
    q = mp.exp(2j * mp.pi * tau)
    leg = {0: 0, 1: 1, 2: -1, 3: -1, 4: 1}
    r = mp.exp(2j * mp.pi * tau / 5)
    for n in range(1, 1201):                         # an explicit product: |q|^1200 is far below the precision here
        if leg[n % 5] == 1:
            r *= 1 - q ** n
        elif leg[n % 5] == -1:
            r /= 1 - q ** n
    return r ** 5


def moeb(M, z):
    return (M[0] * z + M[1]) / (M[2] * z + M[3])


