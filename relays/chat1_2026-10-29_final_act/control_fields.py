#!/usr/bin/env python3
"""Which short word states are arithmetic? (THE FINAL ACT'S BAR, its controls; the web seat, 2026-10-29). Data-free.

For a cusped hyperbolic 3-manifold the invariant trace field is the field generated by the shape parameters
(Neumann-Reid 1992, Thm 2.4), and an arithmetic hyperbolic 3-manifold's invariant trace field has exactly one
complex place (Maclachlan-Reid, The Arithmetic of Hyperbolic 3-Manifolds, Thm 8.3.2); a cusped arithmetic one is
commensurable with a Bianchi group, so its field is imaginary quadratic. This script finds each short once-punctured
torus bundle's shape field by an integer relation on SnapPy's high-precision shapes (PARI's algdep), keeps the factor
the shape satisfies, and reports its reduced polynomial, degree, discriminant and number of real places.
A field of degree > 2, or with more than one complex place, certifies non-arithmetic; an imaginary quadratic field
is necessary for arithmeticity, not sufficient (integral traces are also needed), so it is reported as such.
"""
import warnings

warnings.filterwarnings("ignore")
import snappy  # noqa: E402
from snappy import pari  # noqa: E402

pari.set_real_precision(150)

STATES = ["b++LR", "b+-LR", "b++LLR", "b+-LLR", "b++LLLR", "b+-LLLR", "b++LLRR", "b+-LLRR"]


def shape_field(spec):
    M = snappy.Manifold(spec)
    shapes = M.tetrahedra_shapes("rect", bits_prec=800)
    fields = set()
    for z in shapes:
        p = pari.algdep(z, 8)
        for fac in pari.factor(p)[0]:
            if pari.poldegree(fac) > 1 and abs(complex(pari.subst(fac, "x", z))) < 1e-100:
                red = pari.polredabs(fac)
                deg = int(pari.poldegree(red))
                real_places = int(pari.polsturm(red))
                complex_places = (deg - real_places) // 2
                fields.add((str(red), deg, str(pari.nfdisc(red)), real_places, complex_places))
    return M.identify()[0], fields


def main():
    print("word state | census name | shape field (polredabs) | degree | discriminant | real places | complex places | reading")
    for spec in STATES:
        name, fields = shape_field(spec)
        for poly, deg, disc, r, c in sorted(fields):
            if deg == 2 and r == 0:
                reading = "imaginary quadratic: necessary for arithmeticity (not sufficient alone)"
            elif c != 1:
                reading = "NON-ARITHMETIC (more than one complex place)"
            else:
                reading = "degree > 2: non-arithmetic for a cusped manifold"
            print(f"{spec[1:3]}{spec[3:]} | {name} | {poly} | {deg} | {disc} | {r} | {c} | {reading}")
        if len(fields) != 1:
            print(f"   note: {spec} gave {len(fields)} field candidates")


if __name__ == "__main__":
    main()
