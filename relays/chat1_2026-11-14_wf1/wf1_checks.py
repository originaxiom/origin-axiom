import numpy as np


def say(*a):
    print(*a, flush=True)


# ===================== Part A =====================
ok = True
for n in range(1, 7):
    ev = np.linalg.eigvalsh(2 * np.eye(n) - np.ones((n, n)))
    sig = (int((ev > 1e-9).sum()), int((ev < -1e-9).sum()), int((abs(ev) < 1e-9).sum()))
    want = (1, 0, 0) if n == 1 else (1, 0, 1) if n == 2 else (n - 1, 1, 0)
    ok &= sig == want
    say("A1 rank", n, "signature (+, -, 0):", sig)
say("A1 holds:", ok)


def red3(w):
    out = []
    for ch in w:
        if out and out[-1] == ch:
            out.pop()
        else:
            out.append(ch)
    return "".join(out)


inv3 = lambda w: w[::-1]
X3, Y3 = "ab", "bc"
com = red3(X3 + Y3 + inv3(X3) + inv3(Y3))
lhs = red3("a" + com + "a")
rhs = red3(inv3("abc") * 2)
I2 = np.eye(2)
s1 = np.array([[0, 1], [1, 0]], complex)
s2 = np.array([[0, -1j], [1j, 0]])
s3 = np.array([[1, 0], [0, -1]], complex)
xP, yP = s1 @ s2, s2 @ s3
cP = xP @ yP @ np.linalg.inv(xP) @ np.linalg.inv(yP)
a2 = (lhs == rhs and np.allclose(s1 @ s2 @ s3, 1j * I2) and np.allclose(s3 @ s2 @ s1, -1j * I2)
      and np.isclose(np.linalg.det(xP), 1) and np.isclose(np.linalg.det(yP), 1) and np.allclose(cP, -I2))
say("A2 [x,y] =", com, "; a[x,y]a =", lhs, "; (abc)^-2 =", rhs, "; Pauli [x,y] trace", np.round(np.trace(cP).real, 12))
say("A2 holds:", a2)

rng = np.random.default_rng(20261114)
a3 = True
for _ in range(200):
    Q = rng.normal(size=(2, 2)) + 1j * rng.normal(size=(2, 2))
    Qi = np.linalg.inv(Q)
    sg = [np.diag(rng.choice([-1, 1], size=2)).astype(complex) for _ in range(3)]
    t = [Q @ d @ Qi for d in sg]
    xx, yy = t[0] @ t[1], t[1] @ t[2]
    cc = xx @ yy @ np.linalg.inv(xx) @ np.linalg.inv(yy)
    a3 &= np.allclose(cc, I2, atol=1e-8)
say("A3 compatible distinctions give [x, y] = I on 200 draws:", a3)

chi = {k: Fraction(2) - Fraction(3, 2) - (1 - Fraction(1, k)) for k in range(2, 13)}
chi_inf = Fraction(2) - Fraction(3, 2) - 1
a4 = chi[2] == 0 and all(chi[k] < 0 for k in range(3, 13)) and chi_inf == Fraction(-1, 2)
say("A4 chi(S^2(2,2,2,k)) for k = 2..12:", [str(chi[k]) for k in range(2, 13)], "; at the puncture:", chi_inf)
say("A4 holds:", a4)

PAIR = {"ab": (1, 0), "ba": (-1, 0), "bc": (0, 1), "cb": (0, -1), "ac": (1, 1), "ca": (-1, -1)}


def ab3(w):
    v = [0, 0]
    for i in range(0, len(w), 2):
        p = w[i:i + 2]
        v[0] += PAIR[p][0]
        v[1] += PAIR[p][1]
    return v


def redesc_matrix(sub):
    img = lambda w: red3("".join(sub[ch] for ch in w))
    return np.array([ab3(img(X3)), ab3(img(Y3))]).T


MOVES = {
    "swap a,b": {"a": "b", "b": "a", "c": "c"}, "swap b,c": {"a": "a", "b": "c", "c": "b"},
    "swap a,c": {"a": "c", "b": "b", "c": "a"}, "a through b": {"a": "bab", "b": "b", "c": "c"},
    "b through a": {"a": "a", "b": "aba", "c": "c"}, "c through b": {"a": "a", "b": "b", "c": "bcb"},
    "b through c": {"a": "a", "b": "cbc", "c": "c"},
}
MM = {k: redesc_matrix(v) for k, v in MOVES.items()}
targets = {"L": np.array([[1, 1], [0, 1]]), "R": np.array([[1, 0], [1, 1]]), "P": np.array([[0, 1], [1, 0]])}
found = {}
for r in (1, 2, 3):
    for combo in itertools.product(MM, repeat=r):
        M = np.eye(2, dtype=int)
        for k in combo:
            M = M @ MM[k]
        for tn, T in targets.items():
            if tn not in found and (np.array_equal(M, T) or np.array_equal(M, -T)):
                found[tn] = combo
for tn in "LRP":
    say("A5", tn, "up to sign = product of re-descriptions:", found.get(tn))
say("A5 holds:", all(t in found for t in "LRP"))

# ===================== Part B =====================
L = np.array([[1, 1], [0, 1]])
R = np.array([[1, 0], [1, 1]])
D = np.diag([1, -1])
J = np.array([[0, 1], [-1, 0]])
Jinv = np.array([[0, -1], [1, 0]])


def mat(w):
    M = np.eye(2, dtype=np.int64)
    for ch in w:
        M = M @ (L if ch == "L" else R)
    return M


def inv2(M):
    a, b, c, d = M.ravel()
    det = a * d - b * c
    return det * np.array([[d, -b], [-c, a]])


b1, nw = True, 0
for k in range(1, 13):
    for w in itertools.product("LR", repeat=k):
        A = mat(w)
        nw += 1
        b1 &= np.array_equal(mat(w[::-1]), D @ inv2(A) @ D) and np.array_equal(inv2(A), J @ A.T @ Jinv)
say("B1 words checked:", nw, "; rev(w) = D w^-1 D and w^-1 = J w^T J^-1 for all:", b1)


def red(w):
    out = []
    for g in w:
        if out and out[-1] == -g:
            out.pop()
        else:
            out.append(g)
    return tuple(out)


def apply(aut, w):
    out = []
    for g in w:
        im = aut[abs(g)]
        out.extend(im if g > 0 else [-h for h in reversed(im)])
    return red(out)


def compose(f, g):  # f o g
    return {1: apply(f, g[1]), 2: apply(f, g[2])}


ID = {1: (1,), 2: (2,)}
AUT = {"L": {1: (1,), 2: (1, 2)}, "R": {1: (1, 2), 2: (2,)}}
AUTINV = {"L": {1: (1,), 2: (-1, 2)}, "R": {1: (1, -2), 2: (2,)}}
DAUT = {1: (1,), 2: (-2,)}
PAUT = {1: (2,), 2: (1,)}
NEG = {1: (-1,), 2: (-2,)}
INNER_A = {1: (1,), 2: (1, 2, -1)}
INNER_B = {1: (2, 1, -2), 2: (2,)}


def aut_of(w, eps=1):
    f = dict(ID)
    for ch in w:
        f = compose(f, AUT[ch])
    return compose(f, NEG) if eps == -1 else f


def aut_inv_of(w, eps=1):
    f = dict(ID)
    for ch in reversed(w):
        f = compose(f, AUTINV[ch])
    return compose(f, NEG) if eps == -1 else f


def abel(word):
    v = [0, 0]
    for g in word:
        v[abs(g) - 1] += 1 if g > 0 else -1
    return v


def abmat(f):
    return np.array([abel(f[1]), abel(f[2])]).T


# quaternions as SU(2)
QI = np.array([[1j, 0], [0, -1j]])
QJ = np.array([[0, 1], [-1, 0]], complex)
QK = QI @ QJ
RHO = {1: QI, -1: -QI, 2: QJ, -2: -QJ}


def rho(w):
    M = np.eye(2, dtype=complex)
    for g in w:
        M = M @ RHO[g]
    return M


def key(M):
    return tuple(np.round(M.ravel(), 9).tolist())


gens = [QI, QJ, (np.eye(2) + QI) / np.sqrt(2), (np.eye(2) + QI + QJ + QK) / 2]
O48 = {key(np.eye(2, dtype=complex)): np.eye(2, dtype=complex)}
frontier = list(O48.values())
while frontier:
    nxt = []
    for M in frontier:
        for g in gens:
            N = M @ g
            if key(N) not in O48:
                O48[key(N)] = N
                nxt.append(N)
    frontier = nxt
O48 = list(O48.values())


def find_h(f):
    ta, tb = rho(f[1]), rho(f[2])
    sols = [h for h in O48 if np.allclose(h @ QI @ h.conj().T, ta) and np.allclose(h @ QJ @ h.conj().T, tb)]
    return sols


def comps(U):
    s = np.trace(U).real / 2
    c = [np.trace(U @ np.linalg.inv(q)).real / 2 for q in (QI, QJ, QK)]
    return s, c


def is_order3type(U):
    s, c = comps(U)
    return all(abs(abs(v) - 0.5) < 1e-9 for v in [s] + c)


def bit(U):
    s, c = comps(U)
    return int(np.sign(s) * np.sign(c[0]) * np.sign(c[1]) * np.sign(c[2]))


def odd(U):
    s, c = comps(U)
    return any(abs(abs(v) - 1 / np.sqrt(2)) < 1e-9 for v in [s] + c)


def order_of(U):
    M, n = U.copy(), 1
    while not np.allclose(M, np.eye(2)):
        M = M @ U
        n += 1
    return n


# census
def is_primitive(w):
    n = len(w)
    return not any(n % d == 0 and w == w[:d] * (n // d) for d in range(1, n))


sig = lambda w: w.translate(str.maketrans("LR", "RL"))
rots = lambda w: [w[i:] + w[:i] for i in range(len(w))]


def canon(w):
    return min(rots(w) + rots(sig(w)))


states = set()
for n in range(2, 13):
    for t in itertools.product("LR", repeat=n):
        w = "".join(t)
        if "L" in w and "R" in w and is_primitive(w):
            states.add(canon(w))
states = sorted(states, key=lambda w: (len(w), w))
manif = {}
for w in states:
    manif.setdefault(min(canon(w), canon(w[::-1])), []).append(w)
n_states, n_manif = 2 * len(states), 2 * len(manif)
chk_ab = all(np.array_equal(abmat(aut_of(w, e)), e * mat(w)) for w in states for e in (1, -1))
chk_inv = all(np.array_equal(abmat(aut_inv_of(w)), inv2(mat(w))) for w in states[:200])
planted1 = np.array_equal(abmat({1: (1,), 2: (1, -2)}), L)
say("B0 states:", n_states, "; manifolds:", n_manif, "; automorphisms abelianise to the matrices:", chk_ab and chk_inv,
    "; 2O has", len(O48), "elements")
say("B0 planted error 1 (b -> ab^-1 claimed as L) passes the abelianisation check:", planted1)

cyc = lambda u, v: len(u) == len(v) and u in (v + v)
amph = [m for m in manif if cyc(sig(m), m) or cyc(sig(m[::-1]), m)]
say("B2 amphichiral manifolds (each counted with both signs):", 2 * len(amph), "of", n_manif,
    "; the root LR among them:", "LR" in amph)

# B3
oddstates = [w for w in states if mat(w).trace() % 2 == 1]
hL, hR, hP, hD, hN = (find_h(AUT["L"]), find_h(AUT["R"]), find_h(PAUT), find_h(DAUT), find_h(NEG))
hIa, hIb = find_h(INNER_A), find_h(INNER_B)
say("B3 h(L), h(R), h(P) odd:", odd(hL[0]), odd(hR[0]), odd(hP[0]), "; h(D), h(-I), inner a, inner b even:",
    not odd(hD[0]), not odd(hN[0]), not odd(hIa[0]), not odd(hIb[0]))
cnt = dict(found_unique=0, total=0, order3=0, inv_flip=0, L_flip=0, R_flip=0, P_flip=0, D_keep=0, N_keep=0,
           Ia_keep=0, Ib_keep=0, planted_flip=0)
both_values = 0
for w in oddstates:
    seen_bits = set()
    for e in (1, -1):
        for r in rots(w):
            f = aut_of(r, e)
            hs = find_h(f)
            cnt["total"] += 1
            if len(hs) != 2:
                continue
            cnt["found_unique"] += 1
            h = hs[0]
            if not is_order3type(h):
                continue
            cnt["order3"] += 1
            b = bit(h)
            seen_bits.add(b)
            hinv = find_h(aut_inv_of(r, e))[0]
            cnt["inv_flip"] += bit(hinv) == -b
            cnt["planted_flip"] += bit(h) == -b
            for nm, X, Xi in (("L", AUT["L"], AUTINV["L"]), ("R", AUT["R"], AUTINV["R"]), ("P", PAUT, PAUT)):
                g = compose(compose(X, f), Xi)
                cnt[nm + "_flip"] += bit(find_h(g)[0]) == -b
            for nm, X in (("D", DAUT), ("N", NEG)):
                g = compose(compose(X, f), X)
                cnt[nm + "_keep"] += bit(find_h(g)[0]) == b
            for nm, X, Xi in (("Ia", INNER_A, {1: (1,), 2: (-1, 2, 1)}), ("Ib", INNER_B, {1: (-2, 1, 2), 2: (2,)})):
                g = compose(compose(X, f), Xi)
                cnt[nm + "_keep"] += bit(find_h(g)[0]) == b
    both_values += seen_bits == {1, -1}
N = cnt["total"]
say("B3 odd-trace states:", 2 * len(oddstates), "; (state, rotation, sign) cases:", N)
say("B3a h found, unique up to sign:", cnt["found_unique"], "of", N, "; of order 3 or 6:", cnt["order3"], "of", N)
say("B3b inversion flips the bit:", cnt["inv_flip"], "of", N)
say("B3c conjugation flips by L, R, P:", cnt["L_flip"], cnt["R_flip"], cnt["P_flip"], "; keeps by D, -I, inner a, inner b:",
    cnt["D_keep"], cnt["N_keep"], cnt["Ia_keep"], cnt["Ib_keep"], "; each of", N)
say("B3d odd-trace states on which the bit takes both values:", both_values, "of", len(oddstates))
say("B3 planted error 2, the word in place of its inverse, reported as flipped:", cnt["planted_flip"], "of", N)
