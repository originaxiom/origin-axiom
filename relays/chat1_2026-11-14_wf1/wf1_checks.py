#!/usr/bin/env python3
"""W-F1: the distinction layer under the grammar, and the hand at the common point. Data-free, this seat's own code.

    python3 -I -u wf1_checks.py

Nothing of main's arcs or of any other seat's code is read or run. No value of tau, no frame, no measured number.

DEFINITIONS
  Part A (the distinction layer). A distinction is an involution. W3 = Z/2 * Z/2 * Z/2 on letters a, b, c (each its
  own inverse). Its even part is generated by x = ab and y = bc. The Tits form of the universal Coxeter group of rank n
  is B = 2I - J (ones on the diagonal, -1 off it). Pauli: s1, s2, s3 (each squares to I, pairwise anticommuting).
  The orbifold S^2(2,2,2,k): Euler characteristic 2 - 3/2 - (1 - 1/k), and 2 - 3/2 - 1 for k = infinity (a puncture).
  A re-description of the three distinctions is a substitution of a, b, c (a permutation, or reading one through
  another: a -> bab). Its matrix is its action on H_1 of the even part, in the basis x = ab, y = bc.
  Part B (the arrow). L = [[1,1],[0,1]], R = [[1,0],[1,1]], D = diag(1,-1), P = [[0,1],[1,0]], acting on columns.
  As automorphisms of F_2 = <a, b>: L: a -> a, b -> ab;  R: a -> ab, b -> b;  D: a -> a, b -> b^-1;  P: a <-> b;
  -I: a -> a^-1, b -> b^-1. A word X1...Xk acts as X1 o ... o Xk, so its abelianisation is the matrix product.
  A state (GENESIS section 3, as this seat reads it): a primitive word in L and R using both letters, length 2 to 12,
  up to rotation and the swap L <-> R, with a sign eps = +-1. Its manifold: the state up to reversal of the word.
  A manifold is amphichiral when it has an orientation-reversing self-equivalence; for these bundles that is: w is a
  rotation of sigma(w) (sigma swaps the letters) or of sigma(rev w).
  The common point: rho(a) = i, rho(b) = j in SU(2). For an automorphism phi, h(phi) is an element of the binary
  octahedral group 2O (48 elements) with h rho(g) h^-1 = rho(phi(g)) for g = a, b; it is defined up to sign.
  For an odd-trace word h has order 3 or 6, h = s + x i + y j + z k with all of s, x, y, z equal to +-1/2, and its bit
  is sign(s) sign(x) sign(y) sign(z): which of the two classes of rotations of order 3 in A_4 the act lands in.
  h is even (in 2T, an even permutation of S_4) or odd (in 2O minus 2T).

EXPECTATIONS, written before the run (Part A from standard facts; Part B derived by hand by this seat):
  A1  The Tits form of rank 1 is positive; of rank 2 it is degenerate (1, 0, 1); of rank n >= 3 it is (n - 1, 1, 0).
  A2  In W3, a [x, y] a = (abc)^-2 as reduced words. With Pauli: s1 s2 s3 = iI and s3 s2 s1 = -iI; x = s1 s2 and
      y = s2 s3 have determinant 1, and [x, y] = -I, trace -2.
  A3  Compatible distinctions (three commuting involutions in GL(2, C)) give [x, y] = I, trace +2, on 200 draws.
  A4  chi(S^2(2,2,2,k)) is 0 at k = 2 (flat; then [x, y] = 1), negative for every k from 3 to 12, and -1/2 at the
      puncture.
  A5  Products of at most three re-descriptions give, up to sign, L, R and P on H_1 of the even part.
  B0  Controls of the setup: the census gives 758 states and 536 manifolds (GENESIS section 3); every automorphism of
      a word abelianises to the word's matrix; 2O has 48 elements; for every word h is found and is unique up to sign.
      Planted error 1: an automorphism b -> ab^-1 claimed to be L fails the abelianisation check.
  B1  rev(w) = D w^-1 D, and w^-1 = J w^T J^-1 with J = [[0,1],[-1,0]], for every word in L, R of length 1 to 12.
  B2  The root (LR) is amphichiral. The number of amphichiral manifolds among the 536 is reported.
  B3  For every odd-trace state, at every rotation and with either sign:
        a. h has order 3 or 6, so the bit is defined;
        b. bit(phi^-1) = -bit(phi);
        c. conjugating phi by L, R or P flips the bit (h(L), h(R), h(P) are odd); by D, by -I, or by the inner
           automorphisms (conjugation by a, by b) keeps it;
        d. so the bit takes both values on the rotations of every odd-trace state: it belongs to where the word starts,
           not to the thread.
      Planted error 2: the inversion step replaced by the word itself must report no flip anywhere.
"""
import itertools
