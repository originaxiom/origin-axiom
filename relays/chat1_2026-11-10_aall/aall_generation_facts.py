#!/usr/bin/env python3
"""
A-all in weave form: four more exact facts, added after the referee's read (the web seat, 2026-11-10). Data-free.

An amendment in its own file: aall_level5_facts.py and its output are unchanged. Not a sealed card. Scratch versions
were run before this commit and read (F8's indices; the referee's own counts for F9 and F10 were also seen). This
file is committed before the run made in place. F8 uses sympy's coset enumeration, capped.

Conventions as in aall_level5_facts.py: L = [[1,0],[1,1]], R = [[1,1],[0,1]], column vectors, the mark v = (1, 3),
the eigenline of LR mod 5. A line is v up to sign.

F8   The index in PSL(2, Z) of the group generated by a few whole histories (inverses of whole histories allowed):
     (a) four charge-invisible histories, L^6 R (LR)^k and L R^6 (LR)^k for k = 1, 2;
     (b) LR, L^5 and L R^5 L^-1;
     (c) LR and L^6 R LR alone;
     (d) LR and the line-invisible word L^2 R L^2 R L^2 R alone.
     The stabiliser of the line +-v has index 12.
F9   Positive words of length 1 ... 12 whose matrix keeps the line +-v: how many there are, and how many of them can
     be written as E (LR)^k with E a positive word, E = +-I mod 5 and k >= 0.
F10  Cyclic words (necklaces with both letters) of length 2 ... 12 with trace = +-2 mod 5: how many there are, and how
     many have no rotation whose matrix keeps the line +-v.
F11  LR and RL together generate SL(2, F5).

0 of 19.
"""
from itertools import product

from sympy.combinatorics.coset_table import coset_enumeration_r
from sympy.combinatorics.fp_groups import FpGroup
from sympy.combinatorics.free_groups import free_group

Lm, Rm = (1, 0, 1, 1), (1, 1, 0, 1)
V = (1, 3)


def mul(A, B, N=None):
    C = (A[0] * B[0] + A[1] * B[2], A[0] * B[1] + A[1] * B[3], A[2] * B[0] + A[3] * B[2], A[2] * B[1] + A[3] * B[3])
    return tuple(x % N for x in C) if N else C


def mat(word, N=None):
    M = (1, 0, 0, 1)
    for ch in word:
        M = mul(M, Lm if ch == 'L' else Rm, N)
    return M


def keeps_line(M5):
    w = ((M5[0] * V[0] + M5[1] * V[1]) % 5, (M5[2] * V[0] + M5[3] * V[1]) % 5)
    return w in (V, ((-V[0]) % 5, (-V[1]) % 5))


def is_pm_identity(M5):
    return M5 in ((1, 0, 0, 1), (4, 0, 0, 4))


# ---------------------------------------------------------------- F8
F, s, t = free_group("s, t")
G = FpGroup(F, [s**2, (s * t)**3])      # PSL(2, Z): S of order 2, ST of order 3; R = t, L = s t^-1 s
gR, gL = t, s * t**-1 * s


def W(word):
    g = F.identity
    for ch in word:
        g = g * (gL if ch == 'L' else gR)
    return g


def index(gens, cap=3000):
    try:
        C = coset_enumeration_r(G, gens, max_cosets=cap)
        C.compress()
        return str(len(C.table))
    except ValueError:
        return f'not found finite within {cap} cosets'


print('F8')
cases = [
    ('(a) L^6 R (LR)^k and L R^6 (LR)^k, k = 1, 2',
     [W('LLLLLLR' + 'LR'), W('LLLLLLR' + 'LRLR'), W('LRRRRRR' + 'LR'), W('LRRRRRR' + 'LRLR')]),
    ('(b) LR, L^5, L R^5 L^-1', [W('LR'), gL**5, gL * gR**5 * gL**-1]),
    ('(c) LR and L^6 R LR', [W('LR'), W('LLLLLLRLR')]),
    ('(d) LR and L^2 R L^2 R L^2 R', [W('LR'), W('LLRLLRLLR')]),
]
for name, gens in cases:
    print(f'  {name}: index {index(gens)}', flush=True)
for w in ('LLLLLLRLR', 'LLLLLLRLRLR', 'LRRRRRRLR', 'LRRRRRRLRLR', 'LLRLLRLLR'):
    print(f'  {w} keeps the line +-v: {keeps_line(mat(w, 5))}')

# ---------------------------------------------------------------- F9
print('F9')
total = split = 0
for n in range(1, 13):
    for tup in product('LR', repeat=n):
        w = ''.join(tup)
        if not keeps_line(mat(w, 5)):
            continue
        total += 1
        ok = False
        k = 0
        while 2 * k <= n:
            if k == 0 or w.endswith('LR' * k):
                if is_pm_identity(mat(w[:n - 2 * k], 5)):
                    ok = True
                    break
            else:
                break
            k += 1
        split += ok
print(f'  positive words of length 1..12 keeping the line: {total}; of the form E (LR)^k with E = +-I mod 5: {split}')

# ---------------------------------------------------------------- F10
print('F10')
seen = set()
n_cyc = n_miss = 0
example = None
for n in range(2, 13):
    for tup in product('LR', repeat=n):
        w = ''.join(tup)
        if 'L' not in w or 'R' not in w:
            continue
        rots = [w[i:] + w[:i] for i in range(n)]
        key = min(rots)
        if key in seen:
            continue
        seen.add(key)
        M = mat(w, 5)
        if (M[0] + M[3]) % 5 not in (2, 3):
            continue
        n_cyc += 1
        if not any(keeps_line(mat(r, 5)) for r in rots):
            n_miss += 1
            if example is None:
                example = key
print(f'  cyclic words of length 2..12 with trace +-2 mod 5: {n_cyc}; with no rotation keeping the line: {n_miss}'
      f' (first: {example})')

# ---------------------------------------------------------------- F11
print('F11')
gens = [mat('LR', 5), mat('RL', 5)]
H = {(1, 0, 0, 1)}
frontier = [(1, 0, 0, 1)]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            x = mul(g, h, 5)
            if x not in H:
                H.add(x)
                new.append(x)
    frontier = new
print(f'  the group generated by LR and RL mod 5 has order {len(H)} (SL(2, F5) has 120)')
