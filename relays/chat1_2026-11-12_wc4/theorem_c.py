def commutant_dim(gens):
    n = gens[0].shape[0]
    I = sp.eye(n)
    rows = []
    for g in gens:
        A = (kron(g.T, I) - kron(I, g)).applyfunc(sp.expand)                # vec(X g - g X), columns stacked
        rows.extend(A.tolist())
    M = DomainMatrix([[k(e) for e in r] for r in rows], (len(rows), n * n), K)
    return n * n - M.rank()


