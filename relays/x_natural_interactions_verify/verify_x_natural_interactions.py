def sigma_wick_xyz(g_mat: mp.matrix, lam2: mp.mpf) -> mp.matrix:
    s_out = mp.zeros(3, 3)
    for a in range(3):
        for b in range(3):
            acc = mp.mpf(0)
            for c in range(3):
                for d in range(3):
                    if len({a, c, d}) < 3:
                        continue
                    for e in range(3):
                        for f in range(3):
                            if len({b, e, f}) == 3:
                                acc += g_mat[c, e] * g_mat[d, f]
            s_out[a, b] = (lam2 / 2) * acc
    return s_out


def run_ni_2() -> tuple[dict[str, Any], bool]:
    mp.mp.dps = 35
    # 1. Verify the 5 exact critical points of F(x,y,z) = x^2 + y^2 + z^2 - xyz:
    crit_points = [(0, 0, 0), (2, 2, 2), (2, -2, -2), (-2, 2, -2), (-2, -2, 2)]
    crit_records = []
    for x, y, z in crit_points:
        grad = (2 * x - y * z, 2 * y - x * z, 2 * z - x * y)
        assert grad == (0, 0, 0)
        kap = x * x + y * y + z * z - x * y * z - 2
        hess = mp.matrix([[2, -z, -y], [-z, 2, -x], [-y, -x, 2]])
        evs = sorted(mp.re(v) for v in mp.eighe(hess)[0])
        crit_records.append({"point": [x, y, z], "kappa": kap, "hessian_eigs": [int(mp.nint(v)) for v in evs]})
    assert crit_records[0]["hessian_eigs"] == [2, 2, 2]
    assert all(r["hessian_eigs"] == [-2, 4, 4] and r["kappa"] == 2 for r in crit_records[1:])

    # 2. Canonical coupling of F = (1/2)(X^2 + Y^2 + Z^2) - lam_Mark X Y Z (X = sqrt(2) x):
    lam2_mark = q_mp(1, 8)
    # Check isotropic critical point G_iso = 2 * I_3 at lam^2 = 1/8:
    g_iso = 2 * mp.eye(3)
    res_iso = mat_frob((g_iso ** (-1)) - mp.eye(3) + sigma_wick_xyz(g_iso, lam2_mark))
    assert res_iso < p10_mp(-32)

    # 3. Solve 2D Newton directly on (a, b) for S_3-broken G_* = a I_3 + b (J_3 - I_3) (b != 0) at lam^2 = 1/8:
    def ds_res_ab(av: mp.mpf, bv: mp.mpf) -> tuple[mp.mpf, mp.mpf]:
        gm = av * mp.eye(3) + bv * (mp.ones(3, 3) - mp.eye(3))
        rm = (gm ** (-1)) - mp.eye(3) + sigma_wick_xyz(gm, lam2_mark)
        return rm[0, 0], rm[0, 1]

    av = q_mp(185, 100)
    bv = q_mp(28, 100)
    h_st = p10_mp(-14)
    for _ in range(22):
        f1, f2 = ds_res_ab(av, bv)
        if max(abs(f1), abs(f2)) < p10_mp(-31):
            break
        f1a, f2a = ds_res_ab(av + h_st, bv)
        f1b, f2b = ds_res_ab(av, bv + h_st)
        j11, j21 = (f1a - f1) / h_st, (f2a - f2) / h_st
        j12, j22 = (f1b - f1) / h_st, (f2b - f2) / h_st
        dj = j11 * j22 - j12 * j21
        av += (-f1 * j22 + f2 * j12) / dj
        bv += (-j11 * f2 + j21 * f1) / dj

    g_star = av * mp.eye(3) + bv * (mp.ones(3, 3) - mp.eye(3))
    res_star = mat_frob((g_star ** (-1)) - mp.eye(3) + sigma_wick_xyz(g_star, lam2_mark))
    t_star = bv / av
    g0_star = av + 2 * bv
    g2_star = av - bv
    quintic_residual = abs(3 * (t_star ** 5) + (t_star ** 4) - 13 * (t_star ** 3) - 15 * (t_star ** 2) - 4 * t_star + 1)
    assert res_star < p10_mp(-30) and quintic_residual < p10_mp(-30) and g0_star > 0 and g2_star > 0

    # Planted control PC_NI_2: Naive fixed-point iteration G_{k+1} = (I - Sigma(G_k))^{-1} at subcritical lam^2 = 1/9
    # or perturbed near G_* fails to stabilize on the saddle-like broken branch (repels to isotropic off-diag = 0):
    g_iter = (av - q_mp(1, 50)) * mp.eye(3) + (bv - q_mp(1, 50)) * (mp.ones(3, 3) - mp.eye(3))
    for _ in range(80):
        g_iter = (mp.eye(3) - sigma_wick_xyz(g_iter, q_mp(1, 9))) ** (-1)
    pc2_naive_offdiag = abs(g_iter[0, 1])
    pc2_ok = bool(pc2_naive_offdiag < p10_mp(-20) and abs(bv) > q_mp(25, 100))

    return {
        "critical_points_F": crit_records,
        "canonical_lam_Mark_sq": "1/8",
        "bifurcation_lam_bif_sq": "1/8",
        "isotropic_critical_residual": mp.nstr(res_iso, 8),
        "coexisting_broken_t_star": mp.nstr(t_star, 16),
        "coexisting_broken_g0_neutral": mp.nstr(g0_star, 16),
        "coexisting_broken_g2_doublet": mp.nstr(g2_star, 16),
        "coexisting_broken_ratio_g0_over_g2": mp.nstr(g0_star / g2_star, 16),
        "coexisting_broken_matrix_residual": mp.nstr(res_star, 8),
        "quintic_polynomial_residual": mp.nstr(quintic_residual, 8),
    }, pc2_ok


