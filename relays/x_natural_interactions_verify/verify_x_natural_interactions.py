            z_pt = c_scale * int_eta4(w_pt)
            t_lat = mp.im(z_pt) / s3_2
            s_lat = mp.re(z_pt) - t_lat / 2
            phs = [2 * mp.pi * s_lat, 2 * mp.pi * t_lat, -2 * mp.pi * (s_lat + t_lat)]
            ev3 = [mp.cos(p) for p in phs]
            od3 = [mp.sin(p) for p in phs]
            evq = [sum(omegas_q[(q * a) % 3] * ev3[a] for a in range(3)) / mp.sqrt(3) for q in range(3)]
            odq = [sum(omegas_q[(q * a) % 3] * od3[a] for a in range(3)) / mp.sqrt(3) for q in range(3)]
            # Planted P-breaking chiral weight (1 + (1/2) * Im(evq[1] * conj(odq[1]))? Or 1 + sin(2*pi*(s-t))*...):
            # A Z_3-invariant, P-odd function on E_omega is f_Podd = sin(2*pi*(s_lat - t_lat)) + sin(2*pi*(t_lat - (-s_lat - t_lat))) + sin(2*pi*((-s_lat - t_lat) - s_lat))!
            f_podd = (
                mp.sin(2 * mp.pi * (s_lat - t_lat))
                + mp.sin(2 * mp.pi * (2 * t_lat + s_lat))
                + mp.sin(2 * mp.pi * (-2 * s_lat - t_lat))
            )
