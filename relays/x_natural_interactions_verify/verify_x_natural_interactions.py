# Module NI_4: Frame-Free Analytic Overlaps on X_omega via 6-Coset Modular Chart
# ---------------------------------------------------------------------------
def run_ni_4() -> tuple[dict[str, Any], bool]:
    mp.mp.dps = 32
    omega6 = q_mp(1, 2) + I_MP * mp.sqrt(3) / 2
    omega3 = q_mp(-1, 2) + I_MP * mp.sqrt(3) / 2

    # Exact integer polynomial coefficients of prod_{n=1}^{38} (1 - q^n)^4 up to q^38:
    m_max = 38
    poly = [0] * (m_max + 1)
    poly[0] = 1
    for n in range(1, m_max + 1):
        nxt = poly[:]
        for ck, mult in ((1, -4), (2, 6), (3, -4), (4, 1)):
            sh = ck * n
            if sh <= m_max:
                for j in range(m_max + 1 - sh):
                    nxt[j + sh] += mult * poly[j]
        poly = nxt

    def eta4_mod(w: mp.mpc) -> mp.mpc:
        q = mp.exp(2 * I_MP * mp.pi * w)
        qp = mp.mpc(1)
        s = mp.mpc(0)
        for m in range(m_max + 1):
            if poly[m]:
                s += poly[m] * qp
            qp *= q
        return mp.exp(2 * I_MP * mp.pi * w / 6) * s

    def int_eta4(w: mp.mpc) -> mp.mpc:
        q = mp.exp(2 * I_MP * mp.pi * w)
        e16 = mp.exp(2 * I_MP * mp.pi * w / 6)
        qp = mp.mpc(1)
        s = mp.mpc(0)
        for m in range(m_max + 1):
            if poly[m]:
                k6 = 6 * m + 1
                s += (poly[m] * qp) / (2 * I_MP * mp.pi * mp.mpf(k6) / 6)
            qp *= q
        return e16 * s

    w_base = q_mp(31, 100) + I_MP * q_mp(93, 100)
    om_lr = int_eta4((2 * w_base + 1) / (w_base + 1)) - int_eta4(w_base)
    c_scale = 1 / om_lr
    l2_omega = mp.pi - mp.log(3 / (mp.pi * abs(om_lr)))
    rho2_fp = 1 / ((abs(c_scale) ** 2) * (abs(eta4_mod(omega6)) ** 2) * (q_mp(3, 4)))

    # Split vertical integration on D_{Gamma'} = union_{k=0}^5 T^k F at v_mid = 2 (smooth analytic integrands on both halves!):
