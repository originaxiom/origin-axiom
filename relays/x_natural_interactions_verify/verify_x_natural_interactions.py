def l_int(v: tuple[int, int, int]) -> tuple[int, int, int]:
    return (v[0], v[2], v[0] * v[2] - v[1])


def linv_int(v: tuple[int, int, int]) -> tuple[int, int, int]:
    return (v[0], v[0] * v[1] - v[2], v[1])


def r_int(v: tuple[int, int, int]) -> tuple[int, int, int]:
    return (v[2], v[1], v[1] * v[2] - v[0])


def rinv_int(v: tuple[int, int, int]) -> tuple[int, int, int]:
    return (v[0] * v[1] - v[2], v[1], v[0])


