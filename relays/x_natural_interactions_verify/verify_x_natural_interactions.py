    proj_chg = [abs((u_chg.H * grad_k3)[i]) for i in range(3)]
    assert abs(proj_chg[0] - 3 * s3) < p10_mp(-30) and max(proj_chg[1], proj_chg[2]) < p10_mp(-30)

