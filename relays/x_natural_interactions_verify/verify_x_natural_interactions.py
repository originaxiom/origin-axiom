    def dlinv_m(v: tuple[int, int, int]) -> mp.matrix:
        return mp.matrix([[1, 0, 0], [v[1], v[0], -1], [0, 1, 0]])

    def drinv_m(v: tuple[int, int, int]) -> mp.matrix:
        return mp.matrix([[v[1], v[0], -1], [0, 1, 0], [1, 0, 0]])

