import mpmath as mp
mp.mp.dps = 40


def eta(s):
    q = mp.exp(2j * mp.pi * s)
    return mp.exp(2j * mp.pi * s / 24) * mp.qp(q)


def mob(M, t):
    a, b, c, d = M
    return (a * t + b) / (c * t + d)


def period(M, t0=mp.mpc(0, 1)):
    t1 = mob(M, t0)
    return mp.quad(lambda u: eta(t0 + u * (t1 - t0)) ** 4 * (t1 - t0), [0, 1])


# 2. the cusp width of SL(2,Z)' at infinity: T -> 1, S -> 9 in Z/12, -I = S^2 -> 6
in_kernel = [k for k in range(1, 13) if (k % 12 == 0) or ((k + 6) % 12 == 0)]
print(f"powers k <= 12 with T^k or -T^k in SL(2,Z)': {in_kernel}  (width 6 in PSL(2,Z))")

LR, RL = (2, 1, 1, 1), (1, 1, 1, 2)            # the paper's convention, L = [[1,1],[0,1]], R = [[1,0],[1,1]]
P1, P2 = period(LR), period(RL)
print(f"periods of eta^4 dt: over LR {mp.nstr(P1, 15)}, over RL {mp.nstr(P2, 15)}")
print(f"|P1| = {mp.nstr(abs(P1), 15)}, |P2| = {mp.nstr(abs(P2), 15)}; P2/P1 = {mp.nstr(P2 / P1, 15)} "
      f"(arg/pi = {mp.nstr(mp.arg(P2 / P1) / mp.pi, 12)})")
# a check that the integral is a period (path independence): from another base point
P1b = period(LR, mp.mpc(0.2, 1.7))
print(f"base-point independence: |P1(i) - P1(0.2+1.7i)| = {mp.nstr(abs(P1 - P1b), 5)}")
lam = 1 / abs(P1)                                  # the hexagonal lattice's shortest vector has length 1
kappa = 3 * lam / mp.pi
Lh = lambda h: -mp.log(kappa) + mp.pi * h / 3
print(f"|lambda| = {mp.nstr(lam, 15)}; the leading flat radius at height h: (3|lambda|/pi) e^(-pi h/3)")
print(f"h_max = 1 (min |c| = 1: LR has c = 1); L_max(omega) = L(1) = {mp.nstr(Lh(1), 12)}")
print(f"the length-2 horocycle at height 3: L_2(omega) = L(3) = {mp.nstr(Lh(3), 12)}; L_2 - L_max = 2 pi/3 = "
      f"{mp.nstr(2 * mp.pi / 3, 12)}")
# the next order: the horocycle Im t = h is not exactly a flat circle; its radius varies by the O(e^{-2 pi h}) term
for h in (1, 3):
    rs = []
    for x in [k / 24 * 6 for k in range(24)]:
        t = mp.mpc(x, h)
        z = lam * mp.quad(lambda u: eta(t + 1j * u) ** 4 * 1j, [0, mp.inf]) * (-1)
        rs.append(abs(z))
    print(f"height {h}: flat radius along the horocycle from {mp.nstr(min(rs), 10)} to {mp.nstr(max(rs), 10)}; "
          f"log(1/r) from {mp.nstr(-mp.log(max(rs)), 10)} to {mp.nstr(-mp.log(min(rs)), 10)}")
