#!/usr/bin/env python3
"""SM-C19, a check after main's M41: does the unitary S6 carry U_M to its inverse and exchange the +-pi/6 pair?  And the
four classes over the group generated by T6 and S6 (unitary/antiunitary x keeps/inverts U_M).  This seat's own code;
main's level6_higgs.py is used for U_M, T6, S6 only.
    python3 check_s6.py MAIN_CHECKOUT"""
import importlib.util, itertools, json, pathlib, sys
import numpy as np
CHK = pathlib.Path(sys.argv[1]).resolve() / "frontier/B1957_the_seats_claims_register/verification/checks"
sys.path.insert(0, str(CHK))
spec = importlib.util.spec_from_file_location("l6", CHK / "level6_higgs.py"); L6 = importlib.util.module_from_spec(spec); spec.loader.exec_module(L6)
UM, T6, S6 = L6.UM, L6.T6, L6.S6
ev, V = np.linalg.eig(UM); ph = np.angle(ev) / np.pi
vp = V[:, np.argmin(abs(ph - 1 / 6))]; vm = V[:, np.argmin(abs(ph + 1 / 6))]; vp /= np.linalg.norm(vp); vm /= np.linalg.norm(vm)


def eq_up_to_phase(A, B):
    i = np.unravel_index(np.argmax(abs(B)), B.shape); p = A[i] / B[i]
    return abs(abs(p) - 1) < 1e-8 and np.abs(A - p * B).max() < 1e-8


out = {"S6 U_M S6^-1 = U_M^-1": bool(eq_up_to_phase(S6 @ UM @ np.linalg.inv(S6), np.linalg.inv(UM))),
       "|<v-|S6 v+>|": float(abs(np.vdot(vm, S6 @ vp)))}
# enumerate the group generated by T6, S6 up to phases (words up to length 12, deduplicated)
def key(A):
    f = A.ravel(); i = int(np.flatnonzero(abs(f) > 1e-6)[0]); B = f / (f[i] / abs(f[i]))
    return np.round(B, 4).tobytes()
seen = {key(np.eye(6)): np.eye(6, dtype=complex)}; frontier = [np.eye(6, dtype=complex)]
while frontier and len(seen) < 3000:
    nxt = []
    for A in frontier:
        for g in (T6, S6):
            B = A @ g; k = key(B)
            if k not in seen:
                seen[k] = B; nxt.append(B)
    frontier = nxt
G = list(seen.values())
cls = {}
for A in G:
    for anti in (False, True):
        U = A @ UM.conj() @ np.linalg.inv(A) if anti else A @ UM @ np.linalg.inv(A)
        keeps = eq_up_to_phase(U, UM); inverts = eq_up_to_phase(U, np.linalg.inv(UM))
        img = A @ (vp.conj() if anti else vp)
        exch = abs(np.vdot(vm, img)) > 0.999999; kp = abs(np.vdot(vp, img)) > 0.999999
        c = ("antiunitary" if anti else "unitary", "keeps U_M" if keeps else ("inverts U_M" if inverts else "neither"),
             "exchanges" if exch else ("keeps the pair" if kp else "mixes"))
        cls[str(c)] = cls.get(str(c), 0) + 1
out["group size up to phases"] = len(G)
out["classes"] = cls
print(json.dumps(out, indent=1))
pathlib.Path(__file__).with_name("check_s6.json").write_text(json.dumps(out, indent=1))
