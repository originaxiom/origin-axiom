"""e15 (data-free): the group facts chat1's opinion on the ladder's rule rests on (relay to the SM seat's §268), computed
rather than recalled.
  G1  Delta(2,3,N) = <S, U | S^2, U^3, (SU)^N> for N = 2..5: its order (sympy coset enumeration) and the order of T = SU in
      it. As quotients of PSL(2,Z), Delta(2,3,N) maps onto Delta(2,3,M) exactly when T^N is trivial in Delta(2,3,M), i.e.
      when ord(T) in Delta(2,3,M) divides N; the table of such pairs.
  G2  the binary groups as unit quaternions: 2T (the 24 Hurwitz units), 2O (2T and the 24 units (+-1 +-1 0 0)/sqrt2 in all
      positions), 2I (2T and the 96 even permutations of (0, +-1, +-phi, +-1/phi)/2); closure and orders checked.
  G3  every subgroup of each binary group generated by at most two elements (all subgroups of these groups are): their
      orders; whether a subgroup of order 12 exists, and whether it is the binary dihedral group of order 12 (non-abelian,
      one involution, an element of order 6); whether 2T sits in 2O and in 2I (as the same 24 quaternions); Lagrange's
      bars (24 against 60, 48 against 120).
  G4  A5 (the even permutations of five letters): its subgroup orders (all subgroups two-generated) and that it is simple
      (no normal subgroup but 1 and itself), so S4 is neither a subgroup nor a quotient of it.
    python3 -B e15_ladder_groups_check.py        # writes e15_ladder_groups_check_out.txt"""
import itertools, math, pathlib
from sympy.combinatorics.fp_groups import FpGroup
from sympy.combinatorics.free_groups import free_group
from sympy.combinatorics import Permutation, PermutationGroup

HERE = pathlib.Path(__file__).resolve().parent
out = []

# G1
F, s, u = free_group("s u")
ordT = {}
for N in range(2, 6):
    G = FpGroup(F, [s ** 2, u ** 3, (s * u) ** N])
    P, _ = G._to_perm_group()
    gs = P.generators
    T = gs[0] * gs[1]                         # the images of s and u in the permutation representation, then T = SU
    ordT[N] = T.order()
    out.append(f"G1 Delta(2,3,{N}): order {G.order()}, ord(T) = {ordT[N]}")
pairs = [(N, M) for N in range(2, 6) for M in range(2, 6) if N != M and N % ordT[M] == 0]
out.append(f"G1 Delta(2,3,N) onto Delta(2,3,M) as quotients of PSL(2,Z) (N != M): {pairs}")

# G2
phi = (1 + 5 ** 0.5) / 2


def qmul(a, b):
    a0, a1, a2, a3 = a; b0, b1, b2, b3 = b
    return (a0 * b0 - a1 * b1 - a2 * b2 - a3 * b3, a0 * b1 + a1 * b0 + a2 * b3 - a3 * b2,
            a0 * b2 - a1 * b3 + a2 * b0 + a3 * b1, a0 * b3 + a1 * b2 - a2 * b1 + a3 * b0)


def key(q):
    return tuple(round(x, 9) + 0.0 for x in q)


def signs(v):
    nz = [i for i, x in enumerate(v) if x != 0]
    for ss in itertools.product((1, -1), repeat=len(nz)):
        w = list(v)
        for i, e in zip(nz, ss):
            w[i] = e * w[i]
        yield tuple(w)


T24 = set()
for i in range(4):
    for e in (1, -1):
        v = [0, 0, 0, 0]; v[i] = e; T24.add(key(v))
for v in signs((0.5, 0.5, 0.5, 0.5)):
    T24.add(key(v))
O24 = set()
for i, j in itertools.combinations(range(4), 2):
    v = [0, 0, 0, 0]; v[i] = v[j] = 1 / 2 ** 0.5
    for w in signs(tuple(v)):
        O24.add(key(w))
I96 = set()
even = [p for p in itertools.permutations(range(4)) if sum(1 for a, b in itertools.combinations(range(4), 2) if p[a] > p[b]) % 2 == 0]
for w in signs((0, 0.5, phi / 2, 1 / (2 * phi))):
    for p in even:
        I96.add(key(tuple(w[p[k]] for k in range(4))))
GR = {"2T": T24, "2O": T24 | O24, "2I": T24 | I96}
for name, Gset in GR.items():
    closed = all(key(qmul(a, b)) in Gset for a in Gset for b in Gset)
    out.append(f"G2 {name}: {len(Gset)} elements, closed under multiplication: {closed}")


# G3
def closure(gens):
    S = {key((1, 0, 0, 0))}; frontier = list(S)
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                c = key(qmul(a, g))
                if c not in S:
                    S.add(c); new.append(c)
        frontier = new
    return frozenset(S)


def order_of(q):
    n, a = 1, q
    while key(a) != key((1, 0, 0, 0)):
        a = qmul(a, q); n += 1
    return n


for name, Gset in GR.items():
    L = sorted(Gset)
    subs = {closure([a, b]) for a in L for b in L}
    orders = sorted({len(H) for H in subs})
    o12 = [H for H in subs if len(H) == 12]
    dic = []
    for H in o12:
        ab = all(key(qmul(a, b)) == key(qmul(b, a)) for a in H for b in H)
        ords = sorted(order_of(q) for q in H)
        dic.append((not ab) and ords.count(2) == 1 and 6 in ords)
    out.append(f"G3 {name}: subgroup orders {orders}; subgroups of order 12: {len(o12)}, of them binary dihedral: {sum(dic)}")
out.append(f"G3 2T's 24 quaternions inside 2O: {T24 <= GR['2O']}; inside 2I: {T24 <= GR['2I']}")
out.append(f"G3 Lagrange: 60 % 24 = {60 % 24} (so no S4 in A5); 120 % 48 = {120 % 48} (so no 2O in 2I)")

# G4
A5 = PermutationGroup([Permutation([1, 2, 0, 3, 4]), Permutation([0, 1, 3, 4, 2]), Permutation([1, 0, 3, 2, 4])])
el = list(A5.elements)
subs = {PermutationGroup([a, b]).order() for a in el for b in el}
sizes = sorted(len(c) for c in A5.conjugacy_classes())
others = [z for z in sizes if z != 1] if sizes.count(1) == 1 else None
unions = {1 + sum(c) for r in range(len(others) + 1) for c in itertools.combinations(others, r)}
proper = sorted(d for d in unions if 1 < d < 60 and 60 % d == 0)
out.append(f"G4 A5: order {A5.order()}; two-generated subgroup orders {sorted(subs)}; class sizes {sizes}; "
           f"unions of classes with the identity whose size is a proper divisor of 60 (a normal subgroup needs one): {proper}")
(HERE / "e15_ladder_groups_check_out.txt").write_text("\n".join(out) + "\n")
