# G3
phi = (1 + 5 ** 0.5) / 2


def qmul(x, y):
    a0, a1, a2, a3 = x; b0, b1, b2, b3 = y
    return np.array([a0 * b0 - a1 * b1 - a2 * b2 - a3 * b3, a0 * b1 + a1 * b0 + a2 * b3 - a3 * b2,
                     a0 * b2 - a1 * b3 + a2 * b0 + a3 * b1, a0 * b3 + a1 * b2 - a2 * b1 + a3 * b0])


def signs(v):
    nz = [i for i, x in enumerate(v) if x != 0]
    for ss in itertools.product((1, -1), repeat=len(nz)):
        w = list(v)
        for i, e in zip(nz, ss):
            w[i] = e * w[i]
        yield tuple(w)


def dedup(vs):
    outl = []
    for v in vs:
        v = np.array(v, dtype=float)
        if not any(np.max(np.abs(v - w)) < 1e-9 for w in outl):
            outl.append(v)
    return outl


