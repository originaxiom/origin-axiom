def table(E):
    A = np.array(E); n = len(E); tab = np.empty((n, n), dtype=int); worst = 0.0
    for x in range(n):
        for y in range(n):
            p = qmul(A[x], A[y]); d = np.max(np.abs(A - p), axis=1); z = int(np.argmin(d))
            tab[x, y] = z; worst = max(worst, float(d[z]))
    return tab, worst


def closure_idx(tab, gens, one):
    S = {one}; frontier = [one]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                z = int(tab[x, g])
                if z not in S:
                    S.add(z); new.append(z)
        frontier = new
    return frozenset(S)


