def _normalize_phase(M: np.ndarray) -> np.ndarray:
    flat = M.ravel()
    idx = int(np.argmax(np.abs(flat) > 1e-4))
    z = flat[idx]
    return M * (abs(z) / z)


def _key(M: np.ndarray) -> bytes:
    return np.rint(M.real * 1e6).astype(np.int64).tobytes() + np.rint(M.imag * 1e6).astype(np.int64).tobytes()


def closure(gens: list[np.ndarray], proj: bool = False, limit: int = 200000) -> list[np.ndarray]:
    n = gens[0].shape[0]
    I = np.eye(n, dtype=complex)
    seen = {_key(I): I}
    q = deque([I])
    while q:
        cur = q.popleft()
        for g in gens:
            nxt = g @ cur
            if proj:
                nxt = _normalize_phase(nxt)
            kk = _key(nxt)
            if kk not in seen:
                seen[kk] = nxt
                q.append(nxt)
                if len(seen) > limit:
                    raise RuntimeError("closure limit exceeded")
    return list(seen.values())


def fs_indicator(elems: list[np.ndarray], basis: np.ndarray | None = None) -> complex:
    tot = 0j
    for g in elems:
        h = g if basis is None else basis.conj().T @ g @ basis
        tot += np.trace(h @ h)
    return tot / len(elems)


def as_int(z: complex) -> int | None:
    zr = int(round(z.real))
    return zr if abs(z - zr) < 1e-7 else None


def proj_eq(X: np.ndarray, Y: np.ndarray) -> bool:
    den = np.vdot(Y.ravel(), Y.ravel())
    c = np.vdot(Y.ravel(), X.ravel()) / den
    return abs(c) > 1e-8 and np.linalg.norm(X - c * Y) < 1e-8


def polar_unitary(X: np.ndarray) -> np.ndarray:
    u, _, vh = np.linalg.svd(X)
    return u @ vh


def ext_power(M: np.ndarray, k: int) -> np.ndarray:
    n = M.shape[0]
    subs = list(itertools.combinations(range(n), k))
    out = np.zeros((len(subs), len(subs)), dtype=complex)
    for i, I_ in enumerate(subs):
        for j, J_ in enumerate(subs):
            out[i, j] = np.linalg.det(M[np.ix_(I_, J_)])
    return out


def sym_power(M: np.ndarray, n: int) -> np.ndarray:
    def poly_pow(c: list[complex], e: int) -> np.ndarray:
        r = np.array([1.0 + 0j])
        for _ in range(e):
            r = np.convolve(r, np.array(c, dtype=complex))
        return r

    out = np.zeros((n + 1, n + 1), dtype=complex)
    for k in range(n + 1):
        out[:, k] = np.convolve(poly_pow([M[0, 0], M[1, 0]], n - k), poly_pow([M[0, 1], M[1, 1]], k))
    return out


def element_order(g: np.ndarray, maxk: int = 400) -> int:
    n = g.shape[0]
    cur = g.copy()
    for k in range(1, maxk + 1):
        if np.linalg.norm(cur - np.eye(n)) < 1e-8:
            return k
        cur = cur @ g
    return -1


