def _gf_bfs(gens: list[np.ndarray], p: int) -> list[np.ndarray]:
    n = gens[0].shape[0]
    I = np.eye(n, dtype=np.int64)
    seen = {I.tobytes(): I}
    q = deque([I])
    while q:
        cur = q.popleft()
        for g in gens:
            nxt = (g @ cur) % p
            kb = nxt.tobytes()
            if kb not in seen:
                seen[kb] = nxt
                q.append(nxt)
    return list(seen.values())


def h1_action(phi: dict[str, str], A: np.ndarray, B: np.ndarray, U: np.ndarray) -> np.ndarray:
    """Action z -> (x -> U^-1 z(phi(x))) on H^1(F_2; rho) in an orthonormal complement of B^1."""
    n = A.shape[0]
    rep = {"a": A, "b": B, "A": np.linalg.inv(A), "B": np.linalg.inv(B)}

    def z_of_word(zv: dict[str, np.ndarray], w: str) -> np.ndarray:
        tot = np.zeros(n, dtype=complex)
        pre = np.eye(n, dtype=complex)
        for ch in w:
            if ch in "ab":
                tot = tot + pre @ zv[ch]
                pre = pre @ rep[ch]
            else:
                pre = pre @ rep[ch]
                tot = tot - pre @ zv[ch.lower()]
        return tot

    Ui = np.linalg.inv(U)
    M = np.zeros((2 * n, 2 * n), dtype=complex)
    for col in range(2 * n):
        e = np.zeros(2 * n, dtype=complex)
        e[col] = 1
        zv = {"a": e[:n], "b": e[n:]}
        M[:, col] = np.concatenate([Ui @ z_of_word(zv, phi["a"]), Ui @ z_of_word(zv, phi["b"])])
    Bm = np.column_stack([np.concatenate([A[:, k] - np.eye(n)[:, k], B[:, k] - np.eye(n)[:, k]]) for k in range(n)])
    Qc = null_basis(Bm.conj().T)
    return Qc.conj().T @ M @ Qc


