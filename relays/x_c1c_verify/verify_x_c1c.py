def _esym(ev: np.ndarray) -> tuple[complex, complex, complex]:
    c = np.poly(ev)
    return complex(-c[1]), complex(c[2]), complex(-c[3]) if len(c) > 3 else 0j


def chi248_su6_branch(g: np.ndarray) -> complex:
    ev = np.linalg.eigvals(g)
    t, e2, e3 = _esym(ev)
    return 10 + abs(t) ** 2 + 6 * (t + t.conjugate()) + 3 * (e2 + e2.conjugate()) + 2 * e3


def chi248_su5_branch(g: np.ndarray) -> complex:
    ev = np.linalg.eigvals(g)
    t, e2, _ = _esym(ev)
    return 23 + abs(t) ** 2 + 10 * (t + t.conjugate()) + 5 * (e2 + e2.conjugate())


def theta_of(g: np.ndarray) -> np.ndarray:
    ev = np.linalg.eigvals(g)
    lam = np.angle(ev) / (2 * np.pi)
    K = int(round(float(lam.sum())))
    lam[-1] -= K
    if abs(lam.sum()) > 1e-9:
        raise RuntimeError("eigenvalue logs do not sum to zero")
    th = np.zeros(8)
    th[: len(lam)] = lam
    return th


def chi248_roots(g: np.ndarray) -> complex:
    th = theta_of(g)
    return 8 + complex(np.sum(np.exp(2j * np.pi * (E8 @ th))))


def centralizer_dim(elems: list[np.ndarray], route_su5: bool = False) -> dict:
    v1, v2, v3 = [], [], []
    for g in elems:
        if abs(np.linalg.det(g) - 1) > 1e-8:
            raise RuntimeError("element not in SU(n)")
        if route_su5:
            v1.append(chi248_su5_branch(g))
            g6 = np.eye(6, dtype=complex)
            g6[:5, :5] = g
            v3.append(chi248_su6_branch(g6))
        else:
            v1.append(chi248_su6_branch(g))
        v2.append(chi248_roots(g))
    v1a, v2a = np.array(v1), np.array(v2)
    agree = float(np.max(np.abs(v1a - v2a)))
    if route_su5:
        agree = max(agree, float(np.max(np.abs(np.array(v3) - v2a))))
    mean = complex(np.mean(v2a))
    return {"dim": as_int(mean), "routes_max_disagreement_below_1e-8": bool(agree < 1e-8), "values": v2a}


