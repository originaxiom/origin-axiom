def e8_roots() -> np.ndarray:
    R = []
    for i in range(8):
        for j in range(i + 1, 8):
            for si in (1, -1):
                for sj in (1, -1):
                    v = np.zeros(8)
                    v[i] = si
                    v[j] = sj
                    R.append(v)
    for s in itertools.product((1, -1), repeat=8):
        if s.count(-1) % 2 == 0:
            R.append(0.5 * np.array(s, dtype=float))
    return np.array(R)


