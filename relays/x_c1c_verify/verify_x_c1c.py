def eval_word(w: str, A: np.ndarray, B: np.ndarray) -> np.ndarray:
    n = A.shape[0]
    rep = {"a": A, "b": B, "A": np.linalg.inv(A), "B": np.linalg.inv(B)}
    M = np.eye(n, dtype=complex)
    for ch in w:
        M = M @ rep[ch]
    return M


def pair_image(phi: dict[str, str], A: np.ndarray, B: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    return eval_word(phi["a"], A, B), eval_word(phi["b"], A, B)


def lift(phi: dict[str, str], A: np.ndarray, B: np.ndarray) -> tuple[np.ndarray | None, int]:
    """Unitary U of determinant one with U A U^-1 = phi(a)(A, B) and U B U^-1 = phi(b)(A, B)."""
    Ap, Bp = pair_image(phi, A, B)
    Z = intertwiner_basis([(A, Ap), (B, Bp)])
    if Z.shape[1] == 0:
        return None, 0
    n = A.shape[0]
    X = sum((RNG.normal() + 1j * RNG.normal()) * Z[:, k].reshape(n, n) for k in range(Z.shape[1]))
    U = polar_unitary(X)
    U = U * (np.linalg.det(U) ** (-1.0 / n))
    if np.linalg.norm(U @ A @ U.conj().T - Ap) > 1e-7 or np.linalg.norm(U @ B @ U.conj().T - Bp) > 1e-7:
        raise RuntimeError("lift failed to intertwine")
    return U, int(Z.shape[1])


