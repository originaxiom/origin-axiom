"""The fixed-point companion of a signed word state (B1491): the regular cover whose deck group is the group of
cusp-trivial characters' dual, i.e. the torsion of H1; built with SnapPy's cover() from the characters themselves."""
import itertools, math
import numpy as np
import snappy

L = np.array([[1, 0], [1, 1]]); R = np.array([[1, 1], [0, 1]])


def trace(sign, w):
    M = np.eye(2, dtype=np.int64)
    for c in w: M = M @ (L if c == "L" else R)
    return int(sign * (M[0, 0] + M[1, 1]))


def toint(ch): return (ord(ch) - 96) if ch.islower() else -(ord(ch) - 64)


def expvec(word, ng):
    v = [0] * ng
    for ch in word:
        g = toint(ch); v[abs(g) - 1] += 1 if g > 0 else -1
    return v


def companion(M):
    G = M.fundamental_group(); gens = list(G.generators()); rels = list(G.relators()); ng = len(gens)
    per = G.peripheral_curves()
    import sympy
    from sympy.matrices.normalforms import smith_normal_form
    E = sympy.Matrix([expvec(r, ng) for r in rels]) if rels else sympy.zeros(1, ng)
    D = smith_normal_form(E, domain=sympy.ZZ)
    diag = [abs(int(D[i, i])) for i in range(min(D.shape)) if D[i, i] != 0]
    N = 1
    for d in diag:
        if d > 1: N = N * d // math.gcd(N, d)
    if N == 1: return None, 1
    # characters of order dividing N trivial on the cusp: exponent vectors x mod N with E x = 0 and peripheral words 0
    Em = [expvec(r, ng) for r in rels]
    pw = [expvec(w, ng) for pc in per for w in pc]
    X = []
    for x in itertools.product(range(N), repeat=ng):
        if all(sum(a * b for a, b in zip(e, x)) % N == 0 for e in Em) and all(sum(a * b for a, b in zip(e, x)) % N == 0 for e in pw):
            X.append(x)
    # psi(g) = (chi(g))_chi ; sheets = the subgroup generated by the psi(g)
    vec = [tuple(x[j] % N for x in X) for j in range(ng)]
    zero = tuple([0] * len(X)); sheets = {zero}; frontier = [zero]
    while frontier:
        s = frontier.pop(); 
        for v in vec:
            for sg in (1, -1):
                t = tuple((a + sg * b) % N for a, b in zip(s, v))
                if t not in sheets: sheets.add(t); frontier.append(t)
    sheets = sorted(sheets); idx = {s: i for i, s in enumerate(sheets)}
    perms = [[idx[tuple((a + b) % N for a, b in zip(s, v))] for s in sheets] for v in vec]
    C = M.cover(perms)
    return C, len(sheets)
