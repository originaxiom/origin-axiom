class SpinHejhalSolver:
    def __init__(
        self,
        a_gen: np.ndarray,
        b_gen: np.ndarray,
        v1: np.complex128,
        v2: np.complex128,
        s1: int,
        s2: int,
        y_height: np.float64,
        lmax: np.float64,
        seed: int,
        maxlen: int,
        cmax: np.float64,
        margin: np.float64,
    ) -> None:
        self.y = y_height
        gen = {"a": a_gen, "A": np.linalg.inv(a_gen), "b": b_gen, "B": np.linalg.inv(b_gen)}
        mlat = np.array([[v1.real, v2.real], [v1.imag, v2.imag]], dtype=np.float64)
        minv = np.linalg.inv(mlat)
        umat = minv.T
        u1 = umat[0, 0] + NP_IMAG * umat[1, 0]
        u2 = umat[0, 1] + NP_IMAG * umat[1, 1]
        sh1 = NP_ZERO if s1 == 1 else q_np(1, 2)
        sh2 = NP_ZERO if s2 == 1 else q_np(1, 2)

        def trans_lift(n1: int, n2: int) -> np.ndarray:
            sgn = np.float64((s1 ** (n1 % 2)) * (s2 ** (n2 % 2)))
            om = np.float64(n1) * v1 + np.float64(n2) * v2
            return sgn * np.array([[NP_ONE, om], [NP_ZERO, NP_ONE]], dtype=np.complex128)

        mats: list[np.ndarray] = []
        seen: set[tuple[int, ...]] = set()
        scale9 = p10_np(9)
        for length in range(1, maxlen + 1):
            for tup in itertools.product("abAB", repeat=length):
                wd = "".join(tup)
                if any(p + q in CANCEL_PAIRS for p, q in zip(wd, wd[1:])):
                    continue
                m = np.eye(2, dtype=np.complex128)
                for ch in wd:
                    m = m @ gen[ch]
                c = m[1, 0]
                if abs(c) < p10_np(-12) or abs(c) > cmax:
                    continue
                if c.real > p10_np(-12) or (abs(c.real) <= p10_np(-12) and c.imag > NP_ZERO):
                    cc, dd = c, m[1, 1]
                else:
                    cc, dd = -c, -m[1, 1]
                key = (
                    int(np.round(cc.real * scale9)),
                    int(np.round(cc.imag * scale9)),
                    int(np.round(dd.real * scale9)),
                    int(np.round(dd.imag * scale9)),
                )
                if key not in seen:
                    seen.add(key)
                    mats.append(m)

        m_arr = np.array(mats, dtype=np.complex128)
        a_v, b_v, c_v, d_v = m_arr[:, 0, 0], m_arr[:, 0, 1], m_arr[:, 1, 0], m_arr[:, 1, 1]
        c2_v = np.abs(c_v) ** 2
        ac_conj_v = a_v * np.conj(c_v)

        rcut = (np.pi * lmax / NP_TWO + margin) / (NP_TWO * np.pi * y_height)
        n_bound = int(np.ceil(rcut * q_np(4))) + 4
        mus_list = []
        for m1 in range(-n_bound, n_bound + 1):
            for m2 in range(-n_bound, n_bound + 1):
                mu = (np.float64(m1) + sh1) * u1 + (np.float64(m2) + sh2) * u2
                if abs(mu) <= rcut:
                    mus_list.append(mu)
        self.mus = np.array(mus_list, dtype=np.complex128)

        rng = np.random.default_rng(seed)
        n_target = q_np(4, 5) * np.float64(len(self.mus))
        aspect = abs(v2) / abs(v1)
        n1_grid = max(4, int(np.ceil(np.sqrt(n_target / aspect))))
        n2_grid = max(4, int(np.ceil(n_target / np.float64(n1_grid))))
        zs_all = []
        for i1 in range(n1_grid):
            for i2 in range(n2_grid):
                j1 = rng.uniform(q_np(-1, 5), q_np(1, 5))
                j2 = rng.uniform(q_np(-1, 5), q_np(1, 5))
                xi1 = (np.float64(i1) + q_np(1, 2) + j1) / np.float64(n1_grid) - q_np(1, 2)
                xi2 = (np.float64(i2) + q_np(1, 2) + j2) / np.float64(n2_grid) - q_np(1, 2)
                zs_all.append(xi1 * v1 + xi2 * v2)

        zs_keep, zstar_keep, tstar_keep, ks_keep = [], [], [], []
        su2_max = NP_ZERO
        rty = np.sqrt(y_height)
        for z0 in zs_all:
            zc = z0
            tc = y_height
            gtot = np.eye(2, dtype=np.complex128)
            nv = np.round(minv @ np.array([zc.real, zc.imag], dtype=np.float64))
            ni1, ni2 = int(nv[0]), int(nv[1])
            zc = zc - (np.float64(ni1) * v1 + np.float64(ni2) * v2)
            if ni1 or ni2:
                gtot = trans_lift(-ni1, -ni2) @ gtot
            for _ in range(400):
                wv = c_v * zc + d_v
                denom = (wv.real * wv.real + wv.imag * wv.imag) + c2_v * (tc * tc)
                t2_v = tc / denom
                idx = int(np.argmax(t2_v))
                if t2_v[idx] <= tc * (NP_ONE + p10_np(-13)):
                    break
                zc = ((a_v[idx] * zc + b_v[idx]) * np.conj(wv[idx]) + ac_conj_v[idx] * (tc * tc)) / denom[idx]
                tc = t2_v[idx]
                gtot = m_arr[idx] @ gtot
                nv = np.round(minv @ np.array([zc.real, zc.imag], dtype=np.float64))
                ni1, ni2 = int(nv[0]), int(nv[1])
                zc = zc - (np.float64(ni1) * v1 + np.float64(ni2) * v2)
                if ni1 or ni2:
                    gtot = trans_lift(-ni1, -ni2) @ gtot
            if tc > y_height * (NP_ONE + p10_np(-9)):
                rts = np.sqrt(tc)
                sinv = np.array([[NP_ONE / rts, -zc / rts], [NP_ZERO, rts]], dtype=np.complex128)
                smat = np.array([[rty, z0 / rty], [NP_ZERO, NP_ONE / rty]], dtype=np.complex128)
                k_mat = sinv @ gtot @ smat
                dev = max(
                    np.max(np.abs(k_mat @ k_mat.conj().T - np.eye(2))),
                    abs(np.linalg.det(k_mat) - NP_ONE),
                )
                if dev > su2_max:
                    su2_max = dev
                zs_keep.append(z0)
                zstar_keep.append(zc)
                tstar_keep.append(tc)
                ks_keep.append(np.conj(k_mat))

        self.su2_max = su2_max
        self.zs = np.array(zs_keep, dtype=np.complex128)
        self.zstar = np.array(zstar_keep, dtype=np.complex128)
        self.tstar = np.array(tstar_keep, dtype=np.float64)
        self.ks = np.array(ks_keep, dtype=np.complex128)

        absmu = np.abs(self.mus)
        self.norms, self.nrm_idx = np.unique(np.round(absmu, 12), return_inverse=True)
        self.theta_fac = -NP_IMAG * np.exp(NP_IMAG * np.angle(self.mus))
        heights = np.concatenate([[y_height], self.tstar])
        args = NP_TWO * np.pi * np.outer(self.norms, heights)
        self.arg_shape = args.shape
        flat = args.ravel()
        self.active_idx = np.flatnonzero(flat < q_np(42))
        flat_act = flat[self.active_idx]
        self.n_flat = len(flat)
        h_step = q_np(7, 50)  # 0.14 (B933/probe.py step: Euler-Maclaurin error < 10^-25)
        tol_exp = q_np(44)
        t0_b = np.arccosh((np.pi * lmax / NP_TWO + tol_exp) / np.min(flat))
        tmax_b = np.arccosh((np.pi * lmax / NP_TWO + tol_exp + t0_b / NP_TWO + NP_ONE) / np.min(flat))
        q_nodes = int(np.ceil(tmax_b / h_step)) + 1
        self.ts = h_step * np.arange(q_nodes, dtype=np.float64)
        self.wts = np.full(q_nodes, h_step, dtype=np.float64)
        self.wts[0] = h_step / NP_TWO
        self.exp_table = np.exp(-np.outer(flat_act, np.cosh(self.ts)))
        self.p0 = np.exp(NP_TWO * NP_IMAG * np.pi * (np.outer(self.zs.real, self.mus.real) + np.outer(self.zs.imag, self.mus.imag)))
        self.p1 = np.exp(NP_TWO * NP_IMAG * np.pi * (np.outer(self.zstar.real, self.mus.real) + np.outer(self.zstar.imag, self.mus.imag)))
        self.y32 = y_height ** q_np(3, 2)
        self.t32 = self.tstar ** q_np(3, 2)

    def sigma(self, lam: np.float64, nsv: int = 3) -> np.ndarray:
        kc = (
            np.cosh(self.ts / NP_TWO) * np.cos(lam * self.ts)
            - NP_IMAG * np.sinh(self.ts / NP_TWO) * np.sin(lam * self.ts)
        ) * self.wts
        k_act = (self.exp_table @ np.ascontiguousarray(kc.real)) + NP_IMAG * (self.exp_table @ np.ascontiguousarray(kc.imag))
        k_full = np.zeros(self.n_flat, dtype=np.complex128)
        k_full[self.active_idx] = k_act
        k_vals = k_full.reshape(self.arg_shape)
        k1y = k_vals[self.nrm_idx, 0]
        k1s = k_vals[self.nrm_idx, 1:]
        c1x = self.y32 * k1y[None, :] * self.p0
        c2x = self.y32 * (self.theta_fac * np.conj(k1y))[None, :] * self.p0
        c1s = self.t32[:, None] * k1s.T * self.p1
        c2s = self.t32[:, None] * (self.theta_fac[None, :] * np.conj(k1s.T)) * self.p1
        r1 = c1s - (self.ks[:, 0, 0][:, None] * c1x + self.ks[:, 0, 1][:, None] * c2x)
        r2 = c2s - (self.ks[:, 1, 0][:, None] * c1x + self.ks[:, 1, 1][:, None] * c2x)
        v_mat = np.vstack([r1, r2])
        cn = np.linalg.norm(v_mat, axis=0)
        cn[cn == NP_ZERO] = NP_ONE
        return smallest_sv_chol_rr(v_mat / cn[None, :], nsv)


def v_crossing_refine(sig_fn, center: np.float64, half_width: np.float64) -> tuple[np.float64, np.ndarray]:
    a = center - half_width
    b = center + half_width
    inv_phi = (np.sqrt(q_np(5)) - NP_ONE) / NP_TWO
    c = b - inv_phi * (b - a)
    d = a + inv_phi * (b - a)
    fc = sig_fn(c)[0]
    fd = sig_fn(d)[0]
    tol = p10_np(-5)
    while b - a > tol:
        if fc < fd:
            b, d, fd = d, c, fc
            c = b - inv_phi * (b - a)
            fc = sig_fn(c)[0]
        else:
            a, c, fc = c, d, fd
            d = a + inv_phi * (b - a)
            fd = sig_fn(d)[0]
    x0 = q_np(1, 2) * (a + b)
    # Guaranteed straddling V-extrapolation: step 1 uses 2e-5 > (b-a), step 2 uses 1e-6
    if min(fc, fd) < p10_np(-3):
        for step in (q_np(2, 100000), p10_np(-6)):
            fm2 = sig_fn(x0 - NP_TWO * step)[0]
            fm1 = sig_fn(x0 - step)[0]
            fp1 = sig_fn(x0 + step)[0]
            fp2 = sig_fn(x0 + NP_TWO * step)[0]
            sl_l = (fm1 - fm2) / step
            sl_r = (fp2 - fp1) / step
            if sl_l < NP_ZERO < sl_r:
                x_cand = ((fp1 - sl_r * (x0 + step)) - (fm1 - sl_l * (x0 - step))) / (sl_l - sl_r)
                if a - NP_TWO * step <= x_cand <= b + NP_TWO * step:
                    x0 = x_cand
    return x0, sig_fn(x0)


