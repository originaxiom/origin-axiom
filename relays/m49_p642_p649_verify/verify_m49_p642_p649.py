def legendre_sym(a: int, p: int) -> int:
    r = a % p
    if r == 0:
        return 0
    pw = pow(r, (p - 1) // 2, p)
    return 1 if pw == 1 else -1


def f2_rank_from_sign_vectors(vecs: list[tuple[int, ...]]) -> int:
    rows: list[int] = []
    for v in vecs:
        mask = 0
        for idx, s in enumerate(v):
            if s == -1:
                mask |= 1 << idx
        for b in rows:
            if (mask ^ b) < mask:
                mask ^= b
        if mask != 0:
            rows.append(mask)
            rows.sort(reverse=True)
    return len(rows)


