def build_scalar_maass_m004(y_height: np.float64, seed: int, margin: np.float64 = q_np(24)) -> Any:
    sq3 = np.sqrt(q_np(3))
    w_np = q_np(-1, 2) + NP_IMAG * (sq3 / NP_TWO)
    a4_np = np.array([[NP_ONE, NP_ONE], [NP_ZERO, NP_ONE]], dtype=np.complex128)
    b4_np = np.array([[NP_ONE, NP_ZERO], [-w_np, NP_ONE]], dtype=np.complex128)
    gen4 = {"a": a4_np, "A": np.linalg.inv(a4_np), "b": b4_np, "B": np.linalg.inv(b4_np)}
    v1 = NP_ONE + NP_ZERO * NP_IMAG
    v2 = NP_TWO * NP_IMAG * sq3
    mlat = np.array([[v1.real, v2.real], [v1.imag, v2.imag]], dtype=np.float64)
    minv = np.linalg.inv(mlat)
    umat = minv.T
    u1 = umat[0, 0] + NP_IMAG * umat[1, 0]
    u2 = umat[0, 1] + NP_IMAG * umat[1, 1]

    mats: list[np.ndarray] = []
    seen: set[tuple[int, ...]] = set()
    scale9 = p10_np(9)
    for length in range(1, 6):
        for tup in itertools.product("abAB", repeat=length):
            wd = "".join(tup)
            if any(p + q in CANCEL_PAIRS for p, q in zip(wd, wd[1:])):
                continue
            m = np.eye(2, dtype=np.complex128)
            for ch in wd:
                m = m @ gen4[ch]
            c = m[1, 0]
            if abs(c) < p10_np(-12) or abs(c) > q_np(11, 5):
                continue
            cc, dd = (c, m[1, 1]) if (c.real > p10_np(-12) or (abs(c.real) <= p10_np(-12) and c.imag > NP_ZERO)) else (-c, -m[1, 1])
            key = (
                int(np.round(cc.real * scale9)),
                int(np.round(cc.imag * scale9)),
                int(np.round(dd.real * scale9)),
                int(np.round(dd.imag * scale9)),
            )
            if key not in seen:
                seen.add(key)
                mats.append(m)
    m_arr = np.array(mats, dtype=np.complex128)
    a_v, b_v, c_v, d_v = m_arr[:, 0, 0], m_arr[:, 0, 1], m_arr[:, 1, 0], m_arr[:, 1, 1]
    c2_v = np.abs(c_v) ** 2
    ac_conj_v = a_v * np.conj(c_v)

    rmax = q_np(13, 2)
    rcut = (np.pi * rmax / NP_TWO + margin) / (NP_TWO * np.pi * y_height)
    nb = int(np.ceil(rcut * q_np(4))) + 4
    mus = np.array(
        [
            np.float64(m1) * u1 + np.float64(m2) * u2
            for m1 in range(-nb, nb + 1)
            for m2 in range(-nb, nb + 1)
            if p10_np(-12) < abs(np.float64(m1) * u1 + np.float64(m2) * u2) <= rcut
        ],
        dtype=np.complex128,
    )
    rng = np.random.default_rng(seed)
    n_target = q_np(8, 5) * np.float64(len(mus))
    aspect = abs(v2) / abs(v1)
    n1_grid = max(4, int(np.ceil(np.sqrt(n_target / aspect))))
    n2_grid = max(4, int(np.ceil(n_target / np.float64(n1_grid))))
    zs_keep, zstar_keep, tstar_keep = [], [], []
    for i1 in range(n1_grid):
        for i2 in range(n2_grid):
            xi1 = (np.float64(i1) + q_np(1, 2) + rng.uniform(q_np(-1, 5), q_np(1, 5))) / np.float64(n1_grid) - q_np(1, 2)
            xi2 = (np.float64(i2) + q_np(1, 2) + rng.uniform(q_np(-1, 5), q_np(1, 5))) / np.float64(n2_grid) - q_np(1, 2)
            z0 = xi1 * v1 + xi2 * v2
            zc, tc = z0, y_height
            nv = np.round(minv @ np.array([zc.real, zc.imag], dtype=np.float64))
            zc = zc - (nv[0] * v1 + nv[1] * v2)
            for _ in range(400):
                wv = c_v * zc + d_v
                denom = (wv.real * wv.real + wv.imag * wv.imag) + c2_v * (tc * tc)
                t2_v = tc / denom
                idx = int(np.argmax(t2_v))
                if t2_v[idx] <= tc * (NP_ONE + p10_np(-13)):
                    break
                zc = ((a_v[idx] * zc + b_v[idx]) * np.conj(wv[idx]) + ac_conj_v[idx] * (tc * tc)) / denom[idx]
                tc = t2_v[idx]
                nv = np.round(minv @ np.array([zc.real, zc.imag], dtype=np.float64))
                zc = zc - (nv[0] * v1 + nv[1] * v2)
            if tc > y_height * (NP_ONE + p10_np(-9)):
                zs_keep.append(z0)
                zstar_keep.append(zc)
                tstar_keep.append(tc)

    zs = np.array(zs_keep, dtype=np.complex128)
    zstar = np.array(zstar_keep, dtype=np.complex128)
    tstar = np.array(tstar_keep, dtype=np.float64)
    absmu = np.abs(mus)
    norms, nrm_idx = np.unique(np.round(absmu, 12), return_inverse=True)
    heights = np.concatenate([[y_height], tstar])
    args = NP_TWO * np.pi * np.outer(norms, heights)
    arg_shape = args.shape
    flat = args.ravel()
    active_idx = np.flatnonzero(flat < q_np(42))
    flat_act = flat[active_idx]
    n_flat = len(flat)
    h_step = q_np(7, 50)
    tol_exp = q_np(44)
    t0_b = np.arccosh((np.pi * rmax / NP_TWO + tol_exp) / np.min(flat))
    tmax_b = np.arccosh((np.pi * rmax / NP_TWO + tol_exp + t0_b / NP_TWO + NP_ONE) / np.min(flat))
    q_nodes = int(np.ceil(tmax_b / h_step)) + 1
    ts = h_step * np.arange(q_nodes, dtype=np.float64)
    wts = np.full(q_nodes, h_step, dtype=np.float64)
    wts[0] = h_step / NP_TWO
    exp_table = np.exp(-np.outer(flat_act, np.cosh(ts)))
    p0 = np.exp(NP_TWO * NP_IMAG * np.pi * (np.outer(zs.real, mus.real) + np.outer(zs.imag, mus.imag)))
    p1 = np.exp(NP_TWO * NP_IMAG * np.pi * (np.outer(zstar.real, mus.real) + np.outer(zstar.imag, mus.imag)))

    def sig_scalar(rv: np.float64, nsv: int = 3) -> np.ndarray:
        k_full = np.zeros(n_flat, dtype=np.float64)
        k_full[active_idx] = exp_table @ (np.cos(rv * ts) * wts)
        k_vals = k_full.reshape(arg_shape)
        ky, ks = k_vals[nrm_idx, 0], k_vals[nrm_idx, 1:]
        v_mat = (tstar[:, None] * ks.T * p1) - (y_height * ky[None, :] * p0)
        cn = np.linalg.norm(v_mat, axis=0)
        cn[cn == NP_ZERO] = NP_ONE
        return smallest_sv_chol_rr(v_mat / cn[None, :], nsv)

    return sig_scalar


