import sympy as sp
from fractions import Fraction as Fr

x, y, z = sp.symbols('x y z')

# ---- the four-dimensional algebra over Z[x,y,z]: basis (I, A, B, AB)
def vadd(u, v): return tuple(sp.expand(u[i] + v[i]) for i in range(4))
def smul(s, u): return tuple(sp.expand(s*u[i]) for i in range(4))
I4  = (sp.Integer(1), 0, 0, 0)
EA  = (0, sp.Integer(1), 0, 0)
EB  = (0, 0, sp.Integer(1), 0)
EAB = (0, 0, 0, sp.Integer(1))
# products of basis elements (derived above from Cayley-Hamilton + the SL2 identity)
TBL = {
    (0, 0): I4, (0, 1): EA, (0, 2): EB, (0, 3): EAB,
    (1, 0): EA, (2, 0): EB, (3, 0): EAB,
    (1, 1): (sp.Integer(-1), x, 0, 0),                 # A^2 = xA - I
    (1, 2): EAB,                                        # A*B = AB
    (1, 3): (0, 0, sp.Integer(-1), x),                  # A*(AB) = xAB - B
    (2, 1): (sp.expand(z - x*y), y, x, sp.Integer(-1)), # B*A
    (2, 2): (sp.Integer(-1), 0, y, 0),                  # B^2 = yB - I
    (2, 3): (-x, sp.Integer(1), z, 0),                  # B*(AB)
    (3, 1): (-y, z, sp.Integer(1), 0),                  # (AB)*A
    (3, 2): (0, sp.Integer(-1), 0, y),                  # (AB)*B = yAB - A
    (3, 3): (sp.Integer(-1), 0, 0, z),                  # (AB)^2 = z AB - I
}
def mul(u, v):
    out = (sp.Integer(0),)*4
    for i in range(4):
        if u[i] == 0:
            continue
        for j in range(4):
            if v[j] == 0:
                continue
            out = vadd(out, smul(sp.expand(u[i]*v[j]), TBL[(i, j)]))
    return out
LETTER = {'a': EA, 'b': EB,
          'A': (x, sp.Integer(-1), 0, 0),               # A^-1 = xI - A
          'B': (y, 0, sp.Integer(-1), 0)}               # B^-1 = yI - B
def word_vec(w):
    v = I4
    for ch in w:
        v = mul(v, LETTER[ch])
    return v
def word_trace_poly(w):
    c = word_vec(w)
    return sp.expand(2*c[0] + x*c[1] + y*c[2] + z*c[3])

# ---- the record's own holonomy, exact pair arithmetic (the ground truth)
def padd(u, v): return (u[0] + v[0], u[1] + v[1])
def pmul(u, v):
    a, b = u; c, d = v
    return (a*c - b*d, a*d + b*c + b*d)
def pneg(u): return (-u[0], -u[1])
ZERO, ONE, W = (Fr(0), Fr(0)), (Fr(1), Fr(0)), (Fr(0), Fr(1))
def mmul(P, Q):
    return tuple(tuple(padd(pmul(P[i][0], Q[0][j]), pmul(P[i][1], Q[1][j]))
                 for j in range(2)) for i in range(2))
def mtr(P): return padd(P[0][0], P[1][1])
Ma = ((ONE, ONE), (ZERO, ONE))
Mb = ((ONE, ZERO), (pneg(W), ONE))
def minv(P):
    (p, q), (r, s) = P
    assert padd(pmul(p, s), pneg(pmul(q, r))) == ONE
    return ((s, pneg(q)), (pneg(r), p))
MAT = {'a': Ma, 'b': Mb, 'A': minv(Ma), 'B': minv(Mb)}
INV = {'a': 'A', 'A': 'a', 'b': 'B', 'B': 'b'}
def true_trace(w):
    P = ((ONE, ZERO), (ZERO, ONE))
    for ch in w:
        P = mmul(P, MAT[ch])
    return mtr(P)

# THE BEAT: the three numbers the first two letters fix
BEAT = {x: sp.Integer(2), y: sp.Integer(2), z: sp.Integer(2) - sp.Symbol('om')}
om = sp.Symbol('om')
def pair_to_sym(t): return sp.expand(sp.Integer(t[0].numerator) + sp.Integer(t[1].numerator)*om) \
    if t[0].denominator == 1 and t[1].denominator == 1 else None
def reduce_om(e):
    """reduce a polynomial in om modulo om^2 = om - 1 (exact)."""
    p = sp.Poly(sp.expand(e), om)
    coeffs = p.all_coeffs()[::-1]          # c0 + c1 om + c2 om^2 + ...
    c0, c1 = sp.Integer(0), sp.Integer(0)
    lo, hi = sp.Integer(0), sp.Integer(0)  # running (const, om) for om^k
    for k, c in enumerate(coeffs):
        if k == 0:
            lo, hi = sp.Integer(1), sp.Integer(0)
        elif k == 1:
            lo, hi = sp.Integer(0), sp.Integer(1)
        else:
            lo, hi = -hi, sp.expand(lo + hi)   # om^k = om^{k-1}*om, om^2 = om - 1
        c0 = sp.expand(c0 + c*lo); c1 = sp.expand(c1 + c*hi)
    return (c0, c1)

# ---- P1: the table is consistent with the true holonomy
for w in ("ab", "ba", "aab", "abab", "aBAb"):
    poly = word_trace_poly(w)
    got = reduce_om(poly.subs(BEAT))
    want = true_trace(w)
    assert got == (sp.Integer(want[0].numerator), sp.Integer(want[1].numerator)), (w, got, want)
print("P1: the four-dimensional multiplication table reproduces the true holonomy")
