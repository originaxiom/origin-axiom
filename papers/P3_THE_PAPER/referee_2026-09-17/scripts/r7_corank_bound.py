"""WHY three is out of reach: h1 at a locus is a COrank, and corank is bounded by how many
dimensions the character variety has to spend.

r6 established the fact (0 genuine loci at h1 = 3 in every cover of m004 to degree 8 plus the
family).  This asks for the reason, and tests it.

  h1(chi) = (g - rank J(chi)) - 1   for chi nontrivial,  J = Fox Jacobian (rels x gens).

So h1 = k is the condition "J drops rank by k below its generic value".  In the space of matrices
the corank->=k locus has codimension k^2.  The characters live on the character torus of H1, whose
dimension is b1 = (number of cusps) for a cusped hyperbolic 3-manifold (half-lives-half-dies).
Naive expectation: h1 = k needs b1 >= k^2, so
      h1 = 1 free (b1 >= 1, always) ;  h1 = 2 wants b1 >= 4 ;  h1 = 3 wants b1 >= 9.
m004 has ONE cusp.  Every one-cusped manifold has b1 = 1, so only h1 = 1 is expected there --
which is exactly the 20904-with-no-exceptions that r6 found.

Two things are checked here:
  (1) m004's own Alexander polynomial: separable, and its roots are not roots of unity.
      That is why h1 = 0 at every finite-order character of m004 itself, and why the loci only
      appear upstairs.
  (2) the cusps -> max h1 table over every cover to degree 8 and the family.
      Falsifiable prediction: no one-cusped manifold in the scan carries h1 >= 2.
"""
import snappy, warnings, itertools, sys
