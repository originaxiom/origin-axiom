"""B1687 -- the weave's group is the one-qubit Clifford group modulo phases (P-223): live, the moves on Q8's axes generate the
octahedral group (order 24, element orders 1:1, 2:9, 3:8, 4:6) and sigma = L o P is the order-3 turn about the body diagonal
while the swap is a half turn (det +1); the bite: the group generated by L alone is not all of it. Stored: G/Z = Aut(Q8)
matching L and R (order 24 paired)."""
import importlib.util, io, contextlib, json, pathlib
import numpy as np
A = pathlib.Path(__file__).resolve().parents[1] / "frontier" / "B1687_the_weave_as_the_qubit_clifford_group" / "verification"


def _m():
    spec = importlib.util.spec_from_file_location("aut_q8_b", A / "aut_q8.py")
    m = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(m)
    return m


def test_moves_live():
    m = _m()
    assert len(m.G) == 24 and m.ords(m.G).count(2) == 9 and m.ords(m.G).count(3) == 8 and m.ords(m.G).count(4) == 6
    s = m.M["sigma"].astype(int); assert np.trace(s) == 0 and np.array_equal(np.linalg.matrix_power(s, 3), np.eye(3, dtype=int))
    assert round(np.linalg.det(m.M["P"])) == 1 and len(m.GP) == 24
    assert len(m.gen([m.M["L"].astype(int)])) == 4                     # the bite: L alone generates only a quarter-turn cycle


def test_stored_isomorphism():
    d = json.loads((A / "graph_iso.json").read_text(encoding="utf-8"))
    assert d["order_G"] == 96 and d["centre_orders"] == [1, 2, 4, 4] and d["paired_order"] == 24 and d["isomorphism_matching_L_and_R"]
