def _chk():
    """the arc's checks, loaded from their own file (a module of the same name elsewhere must not shadow them)"""
    spec = importlib.util.spec_from_file_location("b1526_genesis_v16_checks", VER / "genesis_v16_checks.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _q5(text):
    return [i + 1 for i, w in enumerate(Q5) if re.search(r"\b" + w + r"\b", text, re.I)]


def _norm(text):
    return " ".join(text.split())


