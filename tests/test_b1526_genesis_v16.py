def test_c4_catches_what_it_is_for():
    """planted controls for C4's diff: an unmarked insertion, a changed word of main's and a removed line are each caught"""
    chk = _chk()
    v15, v16 = V15M.read_text(encoding="utf-8"), V16_KEPT.read_text(encoding="utf-8")
    deleted, unmarked = chk.diff_report(v15, v16)
    assert deleted == chk.EXPECTED_DELETIONS and unmarked == []
    head = "## 2. The grammar: what a description is made of"
    assert v16.count(head) == 1
    assert chk.diff_report(v15, v16.replace(head, "A planted unmarked sentence.\n\n" + head))[1] != []
    word = "Every legal state belongs to the state space"
    assert v16.count(word) == 1
    assert chk.diff_report(v15, v16.replace(word, "Every legal state lies in the state space"))[0] != chk.EXPECTED_DELETIONS
    lines = v16.split("\n")
    i = next(k for k in range(100, len(lines)) if lines[k].strip())     # a line with words in it
    del lines[i]
    d, u = chk.diff_report(v15, "\n".join(lines))
    assert d != chk.EXPECTED_DELETIONS and u != []


