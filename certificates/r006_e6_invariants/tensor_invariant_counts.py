HERE = Path(__file__).resolve().parent
TWISTED_SHA256 = "4a0fb415c7681e052681ab4c1a703d666751776d8fb883edf5ccda44a5cfeba6"
CCB_SHA256 = "5facb27879bd0ea76c7378f6432867be9019a9e6a4ba796e34040d31bb51f9f2"


def sha256(path):
    import hashlib
    return hashlib.sha256(path.read_bytes()).hexdigest()


twisted = HERE / "twisted_double.py"
ccb = HERE / "paper" / "verify" / "check_charge_bracket.py"
assert sha256(twisted) == TWISTED_SHA256
