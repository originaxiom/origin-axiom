# Execute only stages 0--3 of the locked source: exact E6 plus the verified 27.
source = twisted.read_text(encoding="utf-8")
cut = source.index("# ---------------- stage 4")
ns = {"__file__": str(twisted), "__name__": "locked_twisted_prefix"}
exec(compile(source[:cut], str(twisted), "exec"), ns)

N = ns["N"]
DIM = ns["DIM"]
ROOTS = ns["ROOTS"]
rho27_Q = ns["rho27_Q"]
evec = ns["evec"]

CART = (
    (2, 0, -1, 0, 0, 0),
    (0, 2, 0, -1, 0, 0),
    (-1, 0, 2, -1, 0, 0),
    (0, -1, -1, 2, -1, 0),
    (0, 0, 0, -1, 2, -1),
    (0, 0, 0, 0, -1, 2),
)

# Cartan weights of the verified crystal basis.
cartans = []
for i in range(N):
    h = [F(0)] * DIM
    h[i] = F(1)
    cartans.append(rho27_Q(h))
weights = [tuple(cartans[i][a][a] for i in range(N)) for a in range(27)]
zero = (F(0),) * N


def weight_sum(indices):
    return tuple(sum(weights[i][h] for i in indices) for h in range(N))


def sparse_rank(rows):
    """Exact row rank over Q; every retained pivot row is normalized."""
    pivots = {}
    for original in rows:
        row = {int(k): F(v) for k, v in original.items() if v}
        while row:
            pivot = min(row)
            if pivot not in pivots:
                scale = row[pivot]
                row = {k: v / scale for k, v in row.items() if v}
                pivots[pivot] = row
                break
            scale = row[pivot]
            known = pivots[pivot]
            for k, value in known.items():
                new = row.get(k, F(0)) - scale * value
                if new:
                    row[k] = new
                elif k in row:
                    del row[k]
    return len(pivots)


# Root actions: source basis index -> (target basis index, rational coefficient).
root_actions = {}
for root in ROOTS:
    matrix = rho27_Q(evec(root))
    action = {}
    for source_index in range(27):
        hits = [(target, matrix[target][source_index]) for target in range(27)
                if matrix[target][source_index]]
        assert len(hits) <= 1
        if hits:
            action[source_index] = hits[0]
    root_actions[root] = action


def symmetric_basis(degree):
    return [indices for indices in combinations_with_replacement(range(27), degree)
            if weight_sum(indices) == zero]


def symmetric_equations(monomials, roots):
    """Derivation equations for symmetric covariant degree-three tensors."""
    assert monomials and len(monomials[0]) == 3
    position = {monomial: i for i, monomial in enumerate(monomials)}
    rows = {}
    for root in roots:
        action = root_actions[root]
        # Dual-action equations, indexed by target-weight triples.
        for monomial in monomials:
            column = position[monomial]
            counts = {i: monomial.count(i) for i in set(monomial)}
            for source, (target, coefficient) in action.items():
                if target not in counts:
                    continue
                out = list(monomial)
                out.remove(target)
                out.append(source)
                out = tuple(sorted(out))
                key = (root, out)
                row = rows.setdefault(key, {})
                row[column] = row.get(column, F(0)) - counts[target] * coefficient
    return list(rows.values())


def ordered_equations(basis, roots):
    position = {triple: i for i, triple in enumerate(basis)}
    rows = {}
    for root in roots:
        action = root_actions[root]
        for triple, column in position.items():
            for slot in range(3):
                source = triple[slot]
                if source not in action:
                    continue
                target, coefficient = action[source]
                out = list(triple)
                out[slot] = target
                key = (root, tuple(out))
                row = rows.setdefault(key, {})
                row[column] = row.get(column, F(0)) + coefficient
    return list(rows.values())


def inner(left, right):
    return sum(left[i] * CART[i][j] * right[j]
               for i in range(N) for j in range(N))


def selected_a2_cubed():
    a0 = (1, 0, 0, 0, 0, 0)
    a2 = (0, 0, 1, 0, 0, 0)
    span = {tuple(c * a0[k] + d * a2[k] for k in range(N))
            for c in (-1, 0, 1) for d in (-1, 0, 1)}
    first = {root for root in ROOTS if root in span}
    left = {root for root in ROOTS if inner(root, a0) == inner(root, a2) == 0}
    components = []
    while left:
        component = {min(left)}
        changed = True
        while changed:
            changed = False
            for root in sorted(left - component):
                if any(inner(root, member) != 0 for member in component):
                    component.add(root)
                    changed = True
        left -= component
        components.append(component)
    assert len(first) == 6 and sorted(map(len, components)) == [6, 6]
    selected = tuple(sorted(first | components[0] | components[1]))
    assert len(selected) == 18
    return selected


