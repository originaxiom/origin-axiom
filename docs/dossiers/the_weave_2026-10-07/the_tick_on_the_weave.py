def lyndon_upto(n):
    """Duval's algorithm: every binary Lyndon word of length 1..n, as strings over L < R"""
    w = [-1]
    while w:
        w[-1] += 1
        yield "".join("LR"[x] for x in w)
        m = len(w)
        while len(w) < n:
            w.append(w[-m])
        while w and w[-1] == 1:
            w.pop()


def n_lyndon(n):
    mu = lambda d: 0 if any(d % (p * p) == 0 for p in range(2, d + 1)) else (-1) ** sum(
        1 for p in range(2, d + 1) if d % p == 0 and all(p % q for q in range(2, p)))
    return sum(mu(d) * 2 ** (n // d) for d in range(1, n + 1) if n % d == 0) // n


def mat_of(word):
    M = np.array([[1, 0], [0, 1]], dtype=object)
    for ch in word:
        M = M.dot(MAT[ch])
    return M


def real_frame(ML, MR):
    """phases phi with D^-1 M D real for both monomial matrices (D = diag(e^{i phi})), or None"""
    cons = []
    for M in (ML, MR):
        for j in range(3):
            i = int(np.argmax(abs(M[:, j])))
            cons.append((i, j, float(np.angle(M[i, j]))))
    phi = [0.0, None, None]
    for _ in range(6):
        for i, j, a in cons:
            if phi[i] is not None and phi[j] is None:
                phi[j] = phi[i] - a
            elif phi[j] is not None and phi[i] is None:
                phi[i] = a + phi[j]
    if None in phi:
        return None
    for i, j, a in cons:
        x = (a + phi[j] - phi[i]) / np.pi
        if abs(x - round(x)) > 1e-7:
            return None
    return np.array(phi)


def is_monomial(A):
    big = abs(A) > 0.5
    return (big.sum(0) == 1).all() and (big.sum(1) == 1).all() and np.allclose(abs(A[big]), 1, atol=1e-9) and \
        np.allclose(A[~big], 0, atol=1e-9)


def mult_one_exact(S, e):
    """multiplicity of the eigenvalue 1 of zeta8^e S, S an integer rotation of the cube"""
    o = next(k for k in (1, 2, 3, 4) if (np.linalg.matrix_power(S, k) == np.eye(3, dtype=int)).all())
    e %= 8
    if o == 1:
        return 3 if e == 0 else 0
    if o == 2:
        return {0: 1, 4: 2}.get(e, 0)
    if o == 4:
        return 1 if e in (0, 2, 6) else 0
    return 1 if e == 0 else 0


def order_of(A, cap=200):
    P = np.eye(3, dtype=complex)
    for k in range(1, cap + 1):
        P = P @ A
        if np.allclose(P, np.eye(3), atol=1e-8):
            return k
    return None


def line_key(v):
    v = v / np.linalg.norm(v)
    k = int(np.argmax(abs(v) > 1e-6))
    v = v * abs(v[k]) / v[k]
    return tuple(np.round(np.concatenate([v.real, v.imag]), 6) + 0.0)


def closure3(gens):
    """the finite group generated by 3 x 3 matrices"""
    key = lambda A: tuple(np.round(A.flatten(), 6) + 0)
    G = {key(np.eye(3, dtype=complex)): np.eye(3, dtype=complex)}
    fr = list(G.values())
    while fr:
        nx = []
        for A in fr:
            for g in gens:
                Bm = A @ g
                k = key(Bm)
                if k not in G:
                    G[k] = Bm
                    nx.append(Bm)
        fr = nx
        if len(G) > 10000:
            break
    return G


def nullity(A, tol=1e-8):
    s = np.linalg.svd(A, compute_uv=False)
    return int(sum(x < tol for x in s)) + max(0, A.shape[1] - len(s))


