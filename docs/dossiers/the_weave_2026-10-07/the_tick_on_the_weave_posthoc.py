"""W107, POST HOC (after the one run was read). Q4a failed as worded: the run measured the linear span of the odd-trace
ticks (6), while the rule's cell asks what they generate as an algebra. Here, from the run's own exact normal forms:
  - the algebra generated by the odd-trace ticks (the span of all their products, to closure);
  - whether every odd-trace tick has zero diagonal in the parity basis (it cycles the three lines), which would make the
    span of the ticks the six off-diagonal positions.
Run: python3 the_tick_on_the_weave_posthoc.py -> the_tick_on_the_weave_posthoc.json and _run.txt beside it.
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
d = json.loads((HERE / "the_tick_on_the_weave.json").read_text(encoding="utf-8"))
SL, SR = np.array(d["A0"]["S(L)"]), np.array(d["A0"]["S(R)"])
eL, eR = d["A0"]["exponents mod 8 (c = zeta8^e)"]["L"], d["A0"]["exponents mod 8 (c = zeta8^e)"]["R"]
Z8 = np.exp(1j * np.pi / 4)
ticks = []
for r in d["threads"]:
    if not r["odd"]:
        continue
    S = np.eye(3, dtype=int)
    for ch in r["w"]:
        S = S @ (SL if ch == "L" else SR)
    ticks.append(Z8 ** ((eL * r["nL"] + eR * r["nR"]) % 8) * S)
zero_diag = all(np.allclose(np.diag(t), 0) for t in ticks)
basis = []
def add(M):
    global basis
    trial = basis + [M.flatten()]
    if np.linalg.matrix_rank(np.array(trial), tol=1e-8) > len(basis):
        basis = trial
        return True
    return False
for t in ticks:
    add(t)
span = len(basis)
frontier = [b.reshape(3, 3) for b in basis]
while frontier:
    new = []
    for A in frontier:
        for t in ticks[:64]:
            P = A @ t
            if add(P):
                new.append(P)
    frontier = new
out = {"status": "post hoc", "odd-trace ticks": len(ticks), "every odd-trace tick has zero diagonal (parity basis)": zero_diag,
       "linear span of the ticks": span, "algebra generated (span of products, to closure)": len(basis)}
(HERE / "the_tick_on_the_weave_posthoc.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
(HERE / "the_tick_on_the_weave_posthoc_run.txt").write_text(json.dumps(out) + "\n", encoding="utf-8")
print(json.dumps(out))
