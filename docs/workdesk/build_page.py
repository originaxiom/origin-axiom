#!/usr/bin/env python3
"""The Ledger Desk's page, built from the record (see docs/workdesk/README.md).

It takes the page's template, docs/workdesk/the_ledger_desk.template.html, keeps its markup and script, and replaces
three lines: `const DESK=` with a fresh extraction (extract_desk_data.py, plus the index's slice, built in this process
by build_index.py or read from a directory build_index.py wrote), `const SHA = "` with the commit of main that was
read, and `const SEAT_SHA = "` with the commit of the SM seat's branch that was read (empty when it was not), so every
link points at the commit its data came from.

It is read-only on the repository. By default it writes <out>/index.html, where --out lies outside the repository or in
a path git ignores. With --land it writes docs/workdesk/the_ledger_desk.html instead: the one write into the checkout.

    python3 -B docs/workdesk/build_page.py --out /path/outside/the/record
    python3 -B docs/workdesk/build_page.py --land                              # at a landing
    python3 -B docs/workdesk/build_page.py --seat-ref auto --out /path/outside  # with the SM seat's branch as well
"""
import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import extract_desk_data as X  # noqa: E402
import build_index as BI  # noqa: E402

TEMPLATE = HERE / "the_ledger_desk.template.html"
LANDED = "docs/workdesk/the_ledger_desk.html"


def sha256(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def embed(obj):
    """one JSON line for a <script>: '<' is written \\u003c, so no string can close the script or open a comment"""
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")


def main():
    ap = argparse.ArgumentParser()
    BI.add_args(ap)
    ap.add_argument("--index", help="use the page_index.json that a build_index.py run wrote in this directory, run with the "
                                    "same --main-ref and --seat-ref (default: build the index now)")
    ap.add_argument("--out", help="a directory outside the record, or in a path git ignores; index.html is written there")
    ap.add_argument("--land", action="store_true", help=f"write {LANDED} instead (the one write into the checkout)")
    ap.add_argument("--check", action="store_true", help="build the index twice and require identical table hashes")
    a = ap.parse_args()
    if bool(a.out) == a.land:
        raise SystemExit("give exactly one of --out DIR and --land")
    with tempfile.TemporaryDirectory() as scratch:
        BI.setup(a, scratch)
        data = X.desk_data()
        if a.index:
            data["index"] = json.loads((Path(a.index) / "page_index.json").read_text(encoding="utf-8"))
        else:
            data["index"] = BI.build_all(a.check)[3]
    man = data["index"]["manifest"]
    man["extractors_sha256"].update({Path(__file__).name: sha256(__file__), TEMPLATE.name: sha256(TEMPLATE)})
    built = man["built_from"]
    lines = TEMPLATE.read_text(encoding="utf-8").split("\n")
    swaps = {"const DESK=": "const DESK=" + embed(data) + ";",
             'const SHA = "': f'const SHA = "{built["main"]}";',
             'const SEAT_SHA = "': f'const SEAT_SHA = "{built.get("sm", "")}";'}
    for prefix, new in swaps.items():
        at = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
        if len(at) != 1:
            raise SystemExit(f"the template must hold exactly one line starting {prefix!r}; found {len(at)}")
        lines[at[0]] = new
    lines.insert(1, "<!-- GENERATED by docs/workdesk/build_page.py from docs/workdesk/the_ledger_desk.template.html "
                    "-- DO NOT EDIT BY HAND. The record is the only source; the data below is derived from it. -->")
    if a.land:
        dest = BI.REPO / LANDED
    else:
        if not X.out_ok(a.out):
            raise SystemExit("--out must lie outside the repository, or in a path git ignores: the page's data is derived")
        dest = Path(a.out).resolve() / "index.html"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"page": str(dest), "main": built["main"][:9], "seat": built.get("sm", "")[:9],
                      "arcs": man["tables"]["arcs"]["rows"]}))


if __name__ == "__main__":
    main()
