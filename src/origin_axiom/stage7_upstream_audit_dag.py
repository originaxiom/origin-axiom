def build_q8_cayley_and_automorphisms(
    qi_mat: sp.Matrix,
    qj_mat: sp.Matrix,
) -> tuple[np.ndarray, list[tuple[int, ...]], list[tuple[int, ...]], list[tuple[int, int, int]]]:
    """Construct the 8-element quaternion matrix group Q_8 generated by (qi_mat, qj_mat) in
    SL(2, Q(i)), its 8x8 Cayley table, all group automorphisms Aut(Q_8), inner automorphisms
    Inn(Q_8), and the induced permutation action on {<I>, <J>, <K>}.
    """
    eye2 = sp.eye(2)
    qk_mat = (qi_mat * qj_mat).applyfunc(sp.expand)
    elems_q8 = [eye2, -eye2, qi_mat, -qi_mat, qj_mat, -qj_mat, qk_mat, -qk_mat]

    mul_tab = np.zeros((8, 8), dtype=int)
    for idx_a in range(8):
        for idx_b in range(8):
            prod_ab = (elems_q8[idx_a] * elems_q8[idx_b]).applyfunc(sp.expand)
            hit_idx = -1
            for idx_c in range(8):
                if prod_ab == elems_q8[idx_c]:
                    hit_idx = idx_c
                    break
            if hit_idx < 0:
                raise RuntimeError("Q_8 closure failure")
            mul_tab[idx_a, idx_b] = hit_idx

    ord4_indices = [
        idx_x
        for idx_x in range(8)
        if int(mul_tab[idx_x, idx_x]) != 0 and int(mul_tab[int(mul_tab[idx_x, idx_x]), int(mul_tab[idx_x, idx_x])]) == 0
    ]

    aut_list: list[tuple[int, ...]] = []
    for g1_idx in ord4_indices:
        g1_sq = int(mul_tab[g1_idx, g1_idx])
        g1_cu = int(mul_tab[g1_sq, g1_idx])
        for g2_idx in ord4_indices:
            if g2_idx == g1_idx or g2_idx == g1_cu:
                continue
            g2_sq = int(mul_tab[g2_idx, g2_idx])
            g2_cu = int(mul_tab[g2_sq, g2_idx])
            g3_idx = int(mul_tab[g1_idx, g2_idx])
            g3_cu = int(mul_tab[g1_sq, g3_idx])
            cand_perm = (0, g1_sq, g1_idx, g1_cu, g2_idx, g2_cu, g3_idx, g3_cu)
            if len(set(cand_perm)) != 8:
                continue
            hom_ok = True
            for x_i in range(8):
                for y_i in range(8):
                    lhs_v = cand_perm[int(mul_tab[x_i, y_i])]
                    rhs_v = int(mul_tab[cand_perm[x_i], cand_perm[y_i]])
                    if lhs_v != rhs_v:
                        hom_ok = False
                        break
                if not hom_ok:
                    break
            if hom_ok and cand_perm not in aut_list:
                aut_list.append(cand_perm)

    inv_idx = [0] * 8
    for x_i in range(8):
        for y_i in range(8):
            if int(mul_tab[x_i, y_i]) == 0:
                inv_idx[x_i] = y_i
                break

    inn_list: list[tuple[int, ...]] = []
    for g_i in range(8):
        g_inv = inv_idx[g_i]
        conj_perm = tuple(int(mul_tab[int(mul_tab[g_i, x_i]), g_inv]) for x_i in range(8))
        if conj_perm not in inn_list:
            inn_list.append(conj_perm)

    cyc_subgroups = [
        frozenset({0, 1, 2, 3}),
        frozenset({0, 1, 4, 5}),
        frozenset({0, 1, 6, 7}),
    ]
    axis_perms: list[tuple[int, int, int]] = []
    for perm_a in aut_list:
        img_subs = [frozenset(perm_a[idx_el] for idx_el in sub_s) for sub_s in cyc_subgroups]
        p_trip = (
            cyc_subgroups.index(img_subs[0]),
            cyc_subgroups.index(img_subs[1]),
            cyc_subgroups.index(img_subs[2]),
        )
        axis_perms.append(p_trip)

    return mul_tab, aut_list, inn_list, axis_perms


def build_cech_dirac_spinor_cp1_matrix(flux_k: int, cutoff_m: int) -> sp.Matrix:
    """Construct the exact finite-dimensional Cech coboundary matrix on CP^1 = U_0 cup U_1
    for the twisted chiral spinor line bundle S^+ (x) O(flux_k) ~= O(flux_k - 1) on the
    symmetric Laurent window z^n with -cutoff_m <= n <= cutoff_m.
    """
    deg_d = flux_k - 1
    n_rows = 2 * cutoff_m + 1
    cols_list: list[sp.Matrix] = []
    for exp_a in range(0, cutoff_m + 1):
        col_vec = sp.zeros(n_rows, 1)
        col_vec[exp_a + cutoff_m, 0] = 1
        cols_list.append(col_vec)
    upper_b = deg_d + cutoff_m
    if upper_b >= 0:
        for b_val in range(0, upper_b + 1):
            exp_u1 = deg_d - b_val
            if -cutoff_m <= exp_u1 <= cutoff_m:
                col_vec = sp.zeros(n_rows, 1)
                col_vec[exp_u1 + cutoff_m, 0] = -1
                cols_list.append(col_vec)
    return sp.Matrix.hstack(*cols_list)


