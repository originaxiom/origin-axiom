    mul_tab = np.zeros((8, 8), dtype=int)
    for idx_a in range(8):
        for idx_b in range(8):
            prod_ab = (elems_q8[idx_a] * elems_q8[idx_b]).applyfunc(sp.expand)
            hit_idx = -1
