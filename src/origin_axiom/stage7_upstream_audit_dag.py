def kahn_topological_sort(adj_mat: np.ndarray) -> list[int]:
    """Run deterministic Kahn topological sort on integer adjacency matrix adj_mat."""
    n_v = int(adj_mat.shape[0])
    in_deg = np.sum(adj_mat, axis=0).astype(int).copy()
    ready_q = [idx_v for idx_v in range(n_v) if int(in_deg[idx_v]) == 0]
    topo_out: list[int] = []
    while ready_q:
        cur_u = ready_q.pop(0)
        topo_out.append(cur_u)
        for nxt_v in range(n_v):
            if int(adj_mat[cur_u, nxt_v]) != 0:
                in_deg[nxt_v] = int(in_deg[nxt_v]) - 1
                if int(in_deg[nxt_v]) == 0:
                    ready_q.append(nxt_v)
    return topo_out


def compute_boolean_reachability_by_powers(adj_mat: np.ndarray) -> tuple[np.ndarray, int]:
    """Compute boolean transitive reachability R = (sum_{k=1}^n A^k > 0) and max |A^n|."""
    n_v = int(adj_mat.shape[0])
    reach_acc = np.zeros((n_v, n_v), dtype=int)
    cur_pow = (adj_mat > 0).astype(int)
    for _ in range(n_v):
        reach_acc = ((reach_acc + cur_pow) > 0).astype(int)
        cur_pow = ((cur_pow @ adj_mat) > 0).astype(int)
    final_nil_norm = int(np.sum(np.abs(cur_pow)))
    return reach_acc, final_nil_norm


def propagate_max_plus_epistemic(adj_mat: np.ndarray, topo_order: list[int], intrinsic_vec: np.ndarray) -> np.ndarray:
    """Propagate eff(v) = max({intrinsic(v)} cup {eff(u) : (u, v) in E}) along topo_order."""
    eff_out = intrinsic_vec.astype(int).copy()
    n_v = int(adj_mat.shape[0])
    for node_v in topo_order:
        best_val = int(eff_out[node_v])
        for pred_u in range(n_v):
            if int(adj_mat[pred_u, node_v]) != 0 and int(eff_out[pred_u]) > best_val:
                best_val = int(eff_out[pred_u])
        eff_out[node_v] = best_val
    return eff_out


