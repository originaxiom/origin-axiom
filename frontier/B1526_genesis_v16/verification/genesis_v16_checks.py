def cyc_eq(u, v):
    """u and v conjugate in the free group: equal cyclic reductions up to rotation"""
    def cr(w):
        w = red(w)
        while len(w) >= 2 and w[0] == w[-1].swapcase():
            w = w[1:-1]
        return w
    u, v = cr(u), cr(v)
    return len(u) == len(v) and (u in v + v)


