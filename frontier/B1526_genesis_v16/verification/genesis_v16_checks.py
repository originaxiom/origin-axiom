def diff_report(v15, v16):
    """main's words deleted or re-punctuated (token diff), and the changed blocks of lines that carry no [v1.6] mark
    (the version line and §10's own entry excepted: log entries carry no mark)"""
    ta, tb = re.findall(r"\S+", v15), re.findall(r"\S+", v16)
    ops = difflib.SequenceMatcher(None, ta, tb, autojunk=False).get_opcodes()
    deleted = [" ".join(ta[i1:i2]) for op, i1, i2, j1, j2 in ops if op in ("replace", "delete")]
    la, lb = v15.split("\n"), v16.split("\n")
    unmarked = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, la, lb, autojunk=False).get_opcodes():
        if op == "equal" or j1 == j2:
            if op != "equal":
                unmarked.append((j1 + 1, ["(lines of v1.5 removed)"] + la[i1:i1 + 1]))
            continue
        block = lb[j1:j2]
        version_line = j1 < 3 and i1 < len(la) and "** " in la[i1] and \
            block == ["**Version 1.6 · 2026-10-03 · canonical.** " + la[i1].split("** ", 1)[1]]
        log_entry = block[0].startswith("- **v1.6 · 2026-10-03 · sm:B1526.**")
        if not any(MARK in b for b in block) and not version_line and not log_entry:
            unmarked.append((j1 + 1, block[:1]))
    return deleted, unmarked


