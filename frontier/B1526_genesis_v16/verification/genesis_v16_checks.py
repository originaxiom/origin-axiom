def inv(w):
    return "".join(c.swapcase() for c in reversed(w))


def red(w):
    out = []
    for c in w:
        if out and out[-1] == c.swapcase():
            out.pop()
        else:
            out.append(c)
    return "".join(out)


def sub(w, img):
    return red("".join(img[c] if c.islower() else inv(img[c.lower()]) for c in w))


def exponent(w, x):
    return w.count(x) - w.count(x.upper())


def fox_a_at(w, t):
    """the Fox derivative d w / d a, abelianised by a -> 1, b -> t (a has exponent 0 in H1, b generates it): an integer
    Laurent polynomial in t, as a dict exponent -> coefficient"""
    poly, deg = collections.Counter(), 0          # deg: the abelianised exponent of the prefix
    for c in w:
        if c == "a":
            poly[deg] += 1
        elif c == "A":
            poly[deg] -= 1                       # d(a^-1)/da = -a^-1, and a -> 1 leaves the prefix's degree
        if c in "bB":
            deg += 1 if c == "b" else -1
    return {k: v for k, v in poly.items() if v}


