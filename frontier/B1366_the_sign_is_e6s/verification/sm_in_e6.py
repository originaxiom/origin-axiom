for e_c in sing:
    eqs = [sympy.Eq(Ysym(Q_w[0]), sympy.Rational(1, 6)), sympy.Eq(Ysym(e_c), 1)] + [sympy.Eq(Ysym(s), 0) for s in sing if s != e_c]
    sol = sympy.solve(eqs, [x, y, z], dict=True)
    for s_ in sol:
        Y = (tuple(sum(Fr(int(sympy.Rational(s_[c]).p), int(sympy.Rational(s_[c]).q)) * b[0][i] for c, b in zip((x, y, z), basis)) for i in range(5)),
             sum(Fr(int(sympy.Rational(s_[c]).p), int(sympy.Rational(s_[c]).q)) * b[1] for c, b in zip((x, y, z), basis)))
