def Ysym(w):
    return sum(c * sympy.Rational(dot(b, w).numerator, dot(b, w).denominator) for c, b in zip((x, y, z), basis))
Q_w = [w for w in W27 if any(dot(w, s) != 0 for s in S3) and dot(w, A1) != 0]
