orb_pairs = w_orbits(list(pairs), act_pair)
print(f"    pairs (A2, A1 commuting): {len(pairs)}; Weyl orbits: {len(orb_pairs)} -> su(3)_c + su(2)_L sits in E6 in {len(orb_pairs)} way(s) up to conjugacy")

# ---------------------------------------------------------------- (3) the hypercharges
A1 = good[0]
sm_roots = list(S3) + [A1, neg(A1)]
def su3_labels(w):
    pairs_ = [(x, y) for x in S3 for y in S3 if dot(x, y) == -1]; a, b = pairs_[0]
    return (dot(w, a), dot(w, b))
def rep_type(w, Y):
    """(SU(3) content, SU(2) content, Y) of the irreducible piece containing w: SU(3) by the orbit size under its Weyl group is messy;
    use the weight's pairings: colour-charged iff some su(3)_c root pairs non-trivially; weak-charged iff A1 pairs non-trivially."""
    col = any(dot(w, s) != 0 for s in S3); wk = dot(w, A1) != 0
    return (col, wk, dot(Y, w))
# the Cartan subspace orthogonal to the SM roots: 3-dimensional; parametrise Y = x*u + y*v + z*t on a basis (u, v, t)
M = sympy.Matrix([[*[sympy.Rational(x.numerator, x.denominator) for x in r[0]], sympy.Rational(3, 4) * sympy.Rational(r[1].numerator, r[1].denominator)] for r in [*S3, A1]])
ns = M.nullspace(); assert len(ns) == 3
basis = [(tuple(Fr(int(sympy.Rational(x).p), int(sympy.Rational(x).q)) for x in v[:5]), Fr(int(sympy.Rational(v[5]).p), int(sympy.Rational(v[5]).q))) for v in ns]
# the 27's decomposition under su(3)_c + su(2)_L: group weights into irreducibles by (colour-charged?, weak-charged?) and count
groups = Counter((any(dot(w, s) != 0 for s in S3), dot(w, A1) != 0) for w in W27)
print(f"(3) 27 under su(3)_c + su(2)_L by (colour-charged, weak-charged): {dict(groups)}  -> (3,2): 6 weights, (3,1)+(3bar,1)x3: 12, (1,2)x3: 6, (1,1)x3: 3")
