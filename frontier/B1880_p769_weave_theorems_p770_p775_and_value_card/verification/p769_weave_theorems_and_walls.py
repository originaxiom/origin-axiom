    #   Take g = diag(i, i, 1) (a=1, b=1, c=0 -> a+b+c = 2 == 0 mod 2!):
    #   tr_3(g) = 1 + 2i, whereas tr_{3bar}(g) = 1 - 2i != tr_3(g)!!
