def generate_mod_group(gens: List[Tuple[Tuple[int, int], Tuple[int, int]]], N: int) -> set:
    one = ((1 % N, 0), (0, 1 % N))
    gens_mod = [((g[0][0] % N, g[0][1] % N), (g[1][0] % N, g[1][1] % N)) for g in gens]
    seen = {one}
    frontier = [one]
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens_mod:
                x = mat_mul(g, h, N)
                if x not in seen:
                    seen.add(x)
                    nxt.append(x)
        frontier = nxt
    return seen


def quotient_by_scalars(G: set, N: int, pm_only: bool = False) -> Tuple[int, List[int]]:
    if pm_only:
        scalars = sorted({1 % N, (-1) % N} & {c for c in range(N) if ((c, 0), (0, c)) in G})
    else:
        scalars = [c for c in range(1, N) if ((c, 0), (0, c)) in G]
    reps = set()
    for g in G:
        reps.add(min(((c * g[0][0]) % N, (c * g[0][1]) % N, (c * g[1][0]) % N, (c * g[1][1]) % N) for c in scalars))
    return len(reps), scalars


