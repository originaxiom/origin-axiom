def compute_pin_and_modular_debts() -> Dict[str, Any]:
    warnings.filterwarnings("ignore")
    import snappy

    # Debt 1: All 16 non-orientable cyclic run sequences up to 6 letters + m000 -> m004 pullback
    def compositions(n: int):
        for cuts in itertools.product((0, 1), repeat=n - 1):
            out, run = [], 1
            for c in cuts:
                if c:
                    out.append(run)
                    run = 1
                else:
                    run += 1
            out.append(run)
            yield tuple(out)

    odd_runs = sorted(
        {min(c[s:] + c[:s] for s in range(len(c))) for n in range(1, 7) for c in compositions(n) if len(c) % 2 == 1},
        key=lambda c: (sum(c), c),
    )
    assert len(odd_runs) == 16

    pin_rows = []
    rank_gt1_controls = 0
    for c in odd_runs:
        wd = "".join(("L" if i % 2 == 0 else "R") * r for i, r in enumerate(c))
        M = snappy.Manifold("b-+" + wd)
        assert not M.is_orientable()
        A = mat_mul(word_mat(wd), P)
        assert mat_det(A) == -1
        # Exact bundle H_1(M_W; Z) = Z_base (+) coker(A - I_2)
        # Elementary divisors of (A - I_2) over Z give the fibre torsion; base S^1 contributes one free Z summand,
        # and w_1: H_1(M_W; Z) -> Z_base -> F_2 vanishes identically on coker(A - I_2) (hence on ALL 2-torsion!),
        # proving Bockstein(w_1) = w_1^2 = 0 and w_2 = w_1^2 = 0 on every non-orientable bundle!
        B_mat = np.array([[A[0][0] - 1, A[0][1]], [A[1][0], A[1][1] - 1]], dtype=int)
        det_B = abs(int(B_mat[0, 0] * B_mat[1, 1] - B_mat[0, 1] * B_mat[1, 0]))
        gcd_B = math.gcd(math.gcd(abs(int(B_mat[0, 0])), abs(int(B_mat[0, 1]))),
                         math.gcd(abs(int(B_mat[1, 0])), abs(int(B_mat[1, 1]))))
        d1 = gcd_B
        d2 = det_B // gcd_B if gcd_B else 0
        # Compare against SnapPy's elementary divisors (which include the free Z summand as 0)
        snappy_divs = [int(x) for x in M.homology().elementary_divisors()]
        h1_f2_rank = sum(1 for x in snappy_divs if x % 2 == 0)
        fibre_f2_rank = (1 if d1 % 2 == 0 else 0) + (1 if d2 % 2 == 0 else 0)
        assert h1_f2_rank == 1 + fibre_f2_rank, (c, snappy_divs, (d1, d2))

        # Orientation double cover M_cov = b++(wd + wd.translate(SW))
        wd_cov = wd + wd.translate(SW)
        M_cov = snappy.Manifold("b++" + wd_cov)
        assert M_cov.is_orientable()
        # Pullback p*: H^1(M; F_2) -> H^1(M_cov; F_2) kills w_1 = p_base*(u) (since base wraps twice: 2u == 0 mod 2)
        # and on fibre mod-2 classes alpha with A^T alpha = alpha, p*(alpha) restricts to (alpha, alpha) fixed by A^2!
        # Therefore rank(im p*) == fibre_f2_rank == dim H^1(M; F_2) - 1!
        pullback_image_size = 2 ** fibre_f2_rank
        if h1_f2_rank >= 2:
            rank_gt1_controls += 1
        pin_rows.append({
            "runs": list(c),
            "word": wd,
            "fibre_coker_invariants": [d1, d2],
            "snappy_h1_divisors": snappy_divs,
            "h1_f2_rank": h1_f2_rank,
            "pin_minus_count": 2 ** h1_f2_rank,
            "pin_plus_count": 2 ** h1_f2_rank,
            "pullback_to_orient_cover_image_size": pullback_image_size,
            "pullback_constant": pullback_image_size == 1,
        })

    # Verify m000 (runs=[1]) has constant pullback (image size 1), while >= 1 higher-rank control is non-constant!
    m000_row = next(r for r in pin_rows if r["runs"] == [1])
    assert m000_row["pin_minus_count"] == 2 and m000_row["pullback_constant"] is True
    assert rank_gt1_controls >= 4

    # Debt 2: Modular group orders across N = 2..13
    mod_rows = []
    for N in range(2, 14):
        G_lr = generate_mod_group([L, R], N)
        G_lrp = generate_mod_group([L, R, P], N)
        proj_lr, scal_lr = quotient_by_scalars(G_lr, N, pm_only=False)
        proj_lrp, scal_lrp = quotient_by_scalars(G_lrp, N, pm_only=False)
        pm_lr, _ = quotient_by_scalars(G_lr, N, pm_only=True)
        pm_lrp, _ = quotient_by_scalars(G_lrp, N, pm_only=True)
        minus_one_is_sq = any((c * c + 1) % N == 0 for c in range(N))
        if minus_one_is_sq:
            assert proj_lrp == proj_lr, (N, proj_lr, proj_lrp)
        else:
            assert proj_lrp == 2 * proj_lr, (N, proj_lr, proj_lrp)
        mod_rows.append({
            "N": N,
            "sl2_order": len(G_lr),
            "gl2_pm_order": len(G_lrp),
            "projective_two_acts": proj_lr,
            "projective_with_tick": proj_lrp,
            "mod_pmI_two_acts": pm_lr,
            "mod_pmI_with_tick": pm_lrp,
            "minus_one_square_mod_N": minus_one_is_sq,
            "projective_ratio": proj_lrp // proj_lr,
        })
    # Check N=4 specifically: SL_2 -> GL_2^pm goes 48 -> 96, projective goes 24 -> 48; N=5 stays 60 -> 60; N=13 stays 1092 -> 1092
    r4 = next(r for r in mod_rows if r["N"] == 4)
    r5 = next(r for r in mod_rows if r["N"] == 5)
    r13 = next(r for r in mod_rows if r["N"] == 13)
    assert r4["sl2_order"] == 48 and r4["gl2_pm_order"] == 96
    assert r4["projective_two_acts"] == 24 and r4["projective_with_tick"] == 48
    assert r5["projective_two_acts"] == 60 and r5["projective_with_tick"] == 60
    assert r13["projective_two_acts"] == 1092 and r13["projective_with_tick"] == 1092

    # Level-5 involution counts (McKay 2I -> E_8 obstruction under P)
    G5_sl = generate_mod_group([L, R], 5)
    G5_pm = generate_mod_group([L, R, P], 5)
    one5 = ((1, 0), (0, 1))
    inv_sl5 = sum(1 for g in G5_sl if g != one5 and mat_mul(g, g, 5) == one5)
    inv_pm5 = sum(1 for g in G5_pm if g != one5 and mat_mul(g, g, 5) == one5)
    assert len(G5_sl) == 120 and inv_sl5 == 1
    assert len(G5_pm) == 240 and inv_pm5 == 31

    # Odd-length {L, R} exclusion in <sigma_L, sigma_R>^+ where sigma_L = L P, sigma_R = R P
    sigma_L, sigma_R = mat_mul(L, P), mat_mul(R, P)
    det_plus_tick_mats = set()
    for length in range(2, 11, 2):
        for seq in itertools.product((sigma_L, sigma_R), repeat=length):
            M = I2
            for g in seq:
                M = mat_mul(M, g)
            assert mat_det(M) == 1
            det_plus_tick_mats.add(M)
    target_odd_dep = word_mat("LLLLLLRLR")  # length 9 in {L, R}!
    assert target_odd_dep not in det_plus_tick_mats

    return {
        "pin_structures_odd_histories": pin_rows,
        "rank_gt1_nonconstant_controls": rank_gt1_controls,
        "modular_group_orders_N2_to_13": mod_rows,
        "level5_mckay_involutions": {
            "SL2_F5_order": len(G5_sl),
            "SL2_F5_involutions": inv_sl5,
            "SL2_pm_F5_order": len(G5_pm),
            "SL2_pm_F5_involutions": inv_pm5,
        },
        "two_odd_ticks_excludes_L6RLR": target_odd_dep not in det_plus_tick_mats,
    }




def haar_unitary(n: int, rng: np.random.Generator) -> np.ndarray:
    """Draw an exact Haar-random unitary matrix in U(n) via QR with positive diagonal phases."""
    Z = (rng.standard_normal((n, n)) + 1j * rng.standard_normal((n, n))) / math.sqrt(2.0)
    Q, R_qr = np.linalg.qr(Z)
    d = np.diag(R_qr)
    ph = d / np.abs(d)
    return Q * ph[None, :]


