def mat_mul(A: Tuple[Tuple[int, int], Tuple[int, int]],
            B: Tuple[Tuple[int, int], Tuple[int, int]],
            mod: int | None = None) -> Tuple[Tuple[int, int], Tuple[int, int]]:
    out = (
        (A[0][0] * B[0][0] + A[0][1] * B[1][0], A[0][0] * B[0][1] + A[0][1] * B[1][1]),
        (A[1][0] * B[0][0] + A[1][1] * B[1][0], A[1][0] * B[0][1] + A[1][1] * B[1][1]),
    )
    if mod is None:
        return out
    return ((out[0][0] % mod, out[0][1] % mod), (out[1][0] % mod, out[1][1] % mod))


def mat_det(A: Tuple[Tuple[int, int], Tuple[int, int]]) -> int:
    return A[0][0] * A[1][1] - A[0][1] * A[1][0]


