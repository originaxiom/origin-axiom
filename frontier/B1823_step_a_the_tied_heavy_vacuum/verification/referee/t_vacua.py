"""Referee check at every vacuum section D reports (data-free).
(1) V at the reported (tau*, S*) recomputed with the referee's independent code (the draft's normalisation constants);
(2) the gradient on the six coordinates (exponential chart on CP^2, independent of the draft's affine chart);
(3) THE CHARGE-BREAKING TEST the draft does not run: the vev of three Higgs doublets is a 3 x 2 matrix Phi; only
    K = Phi Phi^dag (rank <= 2, trace 1 at fixed |v|) enters, beta_i = W_i^T K conj(W_i).  The draft's vacua are
    K = S S^dag (charge-preserving).  Moving weight eps onto t (t ^ S) changes V at FIRST order by
    eps (t^dag H t - S^dag H S), H = sum_i Phi_i'(beta_i) conj(W_i) W_i^T.  So the reported vacuum is stable against charge
    breaking only if S* is H's LOWEST eigenvector; the slope lam_min(H) - S*^dag H S* < 0 is a descent direction.
Writes t_vacua.json."""
import sys, pathlib, json, time
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(1, str(HERE / "rerun"))
import mpmath as mp
import ref_model as rm
import search as ds

mp.mp.dps = 30
D = json.loads((HERE.parent / "step_a_v2.json").read_text())["D"]["configs"]


def draft_norms(menu, n, tnorm, snorm):
    sc = []
    for i in range(2 * n):
        spr = rm.SINGLETS[i]
        sc.append(1 / mp.sqrt(ds.sup_norm(*spr)) if snorm == "sup" else mp.mpf(1))
    tc = []
    for i in range(n):
        kind, a = rm.MENU[menu][i]
        if kind == "DR":
            tc.append(mp.mpf(24))
        else:
            tc.append(mp.power(2, -mp.mpf(a) / 3) if tnorm == "N" else mp.mpf(1))
    return sc, tc


def exp_chart(S0, x):
    """S = exp(i G(x)) S0 with G Hermitian, generated by the four real directions mixing S0 with its complement"""
    S0 = rm.unit(S0)
    # orthonormal complement by Gram-Schmidt from the standard basis
    basis = []
    for e in ([1, 0, 0], [0, 1, 0], [0, 0, 1]):
        v = [mp.mpc(c) for c in e]
        for b in [S0] + basis:
            ov = mp.fsum(mp.conj(b[k]) * v[k] for k in range(3))
            v = [v[k] - ov * b[k] for k in range(3)]
        nv = mp.sqrt(mp.fsum(abs(c) ** 2 for c in v))
        if nv > mp.mpf("1e-10"):
            basis.append([c / nv for c in v])
        if len(basis) == 2:
            break
    e1, e2 = basis
    G = mp.matrix(3, 3)
    for coef, e in ((mp.mpc(x[0], x[1]), e1), (mp.mpc(x[2], x[3]), e2)):
        for j in range(3):
            for k in range(3):
                G[j, k] += coef * e[j] * mp.conj(S0[k]) + mp.conj(coef) * S0[j] * mp.conj(e[k])
    U = mp.expm(1j * G)
    return [mp.fsum(U[j, k] * S0[k] for k in range(3)) for j in range(3)]


def grad6(model, tau0, S0, h=mp.mpf("1e-10")):
    def V(x):
        return model.V(tau0 + x[0] + 1j * x[1], exp_chart(S0, x[2:]))
    g = []
    for a in range(6):
        xp = [mp.mpf(0)] * 6; xm = [mp.mpf(0)] * 6; xp[a] = h; xm[a] = -h
        g.append((V(xp) - V(xm)) / (2 * h))
    return g


rows = []
t0 = time.time()
for r in D:
    if "best" not in r:
        continue
    b = r["best"]
    sc, tc = draft_norms(r["menu"], r["n"], r["tnorm"], r["snorm"])
    m = rm.RefModel(r["menu"], r["n"], r["mu2"], r["m02"], r["lv"], sc, tc)
    tau = mp.mpc(*b["tau"]); S = rm.unit([mp.mpc(*c) for c in b["S"]])
    Vm = m.V(tau, S)
    K = [[S[j] * mp.conj(S[k]) for k in range(3)] for j in range(3)]
    H = m.Qeff(tau, K)
    ev, U = mp.eighe(H) if hasattr(mp, "eighe") else mp.eig(H)
    evr = sorted([mp.re(e) for e in ev])
    e0 = mp.re(mp.fsum(mp.conj(S[j]) * H[j, k] * S[k] for j in range(3) for k in range(3)))
    HS = [mp.fsum(H[j, k] * S[k] for k in range(3)) for j in range(3)]
    eig_resid = mp.sqrt(mp.fsum(abs(HS[j] - e0 * S[j]) ** 2 for j in range(3)))
    scale = max(abs(e) for e in evr)
    slope = evr[0] - e0                        # < 0: charge breaking lowers V at first order
    A, Dd, W = m.pieces(tau)
    row = dict(menu=r["menu"], n=r["n"], mu2=r["mu2"], m02=r["m02"], lv=r["lv"], tnorm=r["tnorm"],
               draft_class=dict(isolated=b["isolated"], n_flat=b["n_flat"], n_negative=b["n_negative"]),
               runaway=("runaway" in r), tau=b["tau"], V_draft=b["V"], V_referee=float(Vm),
               V_rel_dev=float(abs(Vm - b["V"]) / abs(b["V"])),
               H_eigs=[float(e) for e in evr], S_rayleigh=float(e0), S_eigvec_residual=float(eig_resid),
               charge_breaking_slope=float(slope), slope_over_scale=float(slope / scale),
               unstable_to_charge_breaking=bool(slope < -1e-12 * scale),
               degenerate_lowest=bool(abs(slope) <= 1e-12 * scale and abs(evr[1] - evr[0]) <= 1e-12 * scale),
               c_coefs_draft=b["c_coefs"])
    rows.append(row)
    print("%s %-4s n=%d mu2=%.1f m02=%.4f lv=%.1f | Vdev %.1e | H eigs %s | S'HS %.4e | slope %.3e (%.1e rel) %s" % (
        r["menu"], r["tnorm"], r["n"], r["mu2"], r["m02"], r["lv"], row["V_rel_dev"],
        ["%.3e" % e for e in row["H_eigs"]], row["S_rayleigh"], row["charge_breaking_slope"], row["slope_over_scale"],
        "UNSTABLE" if row["unstable_to_charge_breaking"] else ("degenerate" if row["degenerate_lowest"] else "ok")), flush=True)

summ = {}
for row in rows:
    key = "%s_%s_n%d" % (row["menu"], row["tnorm"], row["n"])
    s = summ.setdefault(key, dict(total=0, unstable=0, degenerate=0, unstable_and_draft_isolated=0))
    s["total"] += 1
    s["unstable"] += row["unstable_to_charge_breaking"]
    s["degenerate"] += row["degenerate_lowest"]
    s["unstable_and_draft_isolated"] += (row["unstable_to_charge_breaking"] and row["draft_class"]["isolated"])
out = dict(rows=rows, summary=summ, max_V_rel_dev=max(r["V_rel_dev"] for r in rows),
           n_unstable=sum(r["unstable_to_charge_breaking"] for r in rows),
           n_unstable_draft_isolated=sum(r["unstable_to_charge_breaking"] and r["draft_class"]["isolated"] for r in rows),
           seconds=round(time.time() - t0, 1))
(HERE / "t_vacua.json").write_text(json.dumps(out, indent=1))
print(json.dumps(summ, indent=0))
print("max V rel dev", out["max_V_rel_dev"], " unstable", out["n_unstable"], " of", len(rows),
      " unstable among draft-isolated", out["n_unstable_draft_isolated"])
