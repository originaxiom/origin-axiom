def exponent_sums(wd, n):
    v = [0] * n
    for ch in wd:
        v[ord(ch.lower()) - 97] += 1 if ch.islower() else -1
    return v


def base_class(M):
    """the map from the fundamental group onto the integers (the base circle), read from the presentation: its values on
    the cusp's two curves"""
    G = M.fundamental_group(); n = G.num_generators()
    A = [[Fraction(x) for x in exponent_sums(r, n)] for r in G.relators()]
    piv, r = [], 0
    for c in range(n):
        p = next((i for i in range(r, len(A)) if A[i][c] != 0), None)
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        A[r] = [x / A[r][c] for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] != 0:
                A[i] = [a - A[i][c] * b for a, b in zip(A[i], A[r])]
        piv.append(c); r += 1
    free = [c for c in range(n) if c not in piv]
    assert len(free) == 1, "the first homology should have rank one"
    phi = [Fraction(0)] * n; phi[free[0]] = Fraction(1)
    for i, c in enumerate(piv):
        phi[c] = -A[i][free[0]]
    d = 1
    for x in phi:
        d = d * x.denominator // math.gcd(d, x.denominator)
    phi = [int(x * d) for x in phi]
    mer, lon = G.peripheral_curves()[0]
    return sum(a * b for a, b in zip(phi, exponent_sums(mer, n))), sum(a * b for a, b in zip(phi, exponent_sums(lon, n)))


def isometries(M):
    """for each isometry of M to itself: (does it keep the orientation, does it reverse the base)"""
    pm, pl = base_class(M)
    out = []
    for iso in M.is_isometric_to(M, return_isometries=True):
        c = iso.cusp_maps()[0]
        a, b, cc, d = int(c[0, 0]), int(c[0, 1]), int(c[1, 0]), int(c[1, 1])
        im_m, im_l = a * pm + cc * pl, b * pm + d * pl          # the columns are the images of the two curves
        assert (im_m, im_l) in ((pm, pl), (-pm, -pl)), "an isometry must act on the base class by a sign"
        out.append((a * d - b * cc == 1, (im_m, im_l) == (-pm, -pl) and (pm, pl) != (0, 0)))
    return out


def half(x):
    x = float(x)
    return x - 0.5 * round(x / 0.5)


