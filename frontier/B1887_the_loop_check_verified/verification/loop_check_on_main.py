def apex_in_the_golden_sea(ones):
    """the record's read-out H = (r + x + y)/2 at a run of 2 of the history (2, 1^ones, 2) in a sea of ones:
    y is the golden tail [0; 1, 1, ...]; x is [0; 1^ones, 2, 1, 1, ...]"""
    g = (mp.sqrt(5) - 1) / 2
    x = 1 / (2 + g)
    for _ in range(ones):
        x = 1 / (1 + x)
    return (2 + x + g) / 2


