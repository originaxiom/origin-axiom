# ------------------------------------------------------------------------------------------------- C: classes of least |Q|
class Axis:
    """A hyperbolic matrix A acting on integer vectors by `act`.  Q(v) = v ^ act(v) is invariant.  With v = alpha e+ + beta e-,
    the action multiplies alpha by lam and divides beta by it, so pos(v) = log|beta/alpha| / (2 log lam) falls by 1 under it,
    and |Q(v)| = C |alpha beta|.  One member of each class, up to sign, has pos in [0, 1)."""

    def __init__(self, A, act):
        self.A, self.Ai, self.act = A, inv(A), act
        r1, r2 = act((1, 0), A), act((0, 1), A)              # v = (x, y) goes to x r1 + y r2
        p, q, r, s = r1[0], r1[1], r2[0], r2[1]
        t = p + s
        assert p * s - q * r == 1 and t > 2 and q != 0
        self.lam = (t + mp.sqrt(t * t - 4)) / 2
        self.ep = (self.lam - s, mp.mpf(q)); self.em = (1 / self.lam - s, mp.mpf(q))      # (mu - s, q) is an eigenvector for mu
        for mu, ev in ((self.lam, self.ep), (1 / self.lam, self.em)):
            im = (ev[0] * p + ev[1] * r, ev[0] * q + ev[1] * s)
            assert abs(im[0] - mu * ev[0]) < mp.mpf(10) ** -30 * abs(mu * ev[0]) + mp.mpf(10) ** -30 and abs(im[1] - mu * ev[1]) < mp.mpf(10) ** -30 * abs(mu * ev[1])
        self.den = self.ep[0] * self.em[1] - self.ep[1] * self.em[0]
        self.C = (self.lam - 1 / self.lam) * abs(self.den)
        self.period = 2 * mp.log(self.lam)                   # the hyperbolic length of one period of the axis

    def Q(self, v):
        w = self.act(v, self.A)
        return v[0] * w[1] - v[1] * w[0]

    def ab(self, v):
        return ((v[0] * self.em[1] - v[1] * self.em[0]) / self.den, (self.ep[0] * v[1] - self.ep[1] * v[0]) / self.den)

    # The origin of the period is set off by a fixed amount.  With none, the vector (1, 0) is e+ - e- up to a factor and sits
    # exactly on the edge of the period, where a class would be counted twice or not at all (main's first run stopped there).
    SHIFT = mp.mpf("0.4142135")

    def pos(self, v):
        a, b = self.ab(v)
        return mp.log(abs(b / a)) / (2 * mp.log(self.lam)) + self.SHIFT

    def canonical(self, v):
        """the member of the class of v with pos in [0, 1), with a fixed sign"""
        n = int(mp.floor(self.pos(v)))
        for _ in range(abs(n)):
            v = self.act(v, self.A if n > 0 else self.Ai)
        p = self.pos(v)
        assert 0 <= p < 1 and min(p, 1 - p) > mp.mpf(10) ** -25, "a class on the edge of the period"
        if v[0] < 0 or (v[0] == 0 and v[1] < 0):
            v = (-v[0], -v[1])
        return v

    def members(self, B, allowed):
        """every integer vector v, not zero, with allowed(v), |Q(v)| <= B and pos in [0, 1), one per class: COMPLETE.
        pos in [0, 1) says lam^(-2 SHIFT) <= |beta/alpha| < lam^(2 - 2 SHIFT); with |alpha beta| <= B/C that gives
        |alpha| <= lam^SHIFT sqrt(B/C) and |beta| <= lam^(1 - SHIFT) sqrt(B/C).  The parallelogram is walked line by line."""
        root = mp.sqrt(B / self.C)
        Aa = float(self.lam ** self.SHIFT * root) * (1 + 1e-9) + 1e-12
        Bb = float(self.lam ** (1 - self.SHIFT) * root) * (1 + 1e-9) + 1e-12
        ep, em, den = (float(self.ep[0]), float(self.ep[1])), (float(self.em[0]), float(self.em[1])), float(self.den)
        found = set()
        # v = alpha ep + beta em.  Walk the coordinate along which em is longer; on each line alpha is confined.
        k = 0 if abs(em[0]) >= abs(em[1]) else 1
        span = int(Aa * abs(ep[k]) + Bb * abs(em[k])) + 2
        for u in range(-span, span + 1):
            # alpha = (x em_y - y em_x) / den, so with coordinate k fixed the other one lies in a short interval
            if k == 0:      # x = u:  y = (u em_y - alpha den) / em_x
                lo, hi = sorted(((u * em[1] - Aa * abs(den)) / em[0], (u * em[1] + Aa * abs(den)) / em[0]))
            else:           # y = u:  x = (alpha den + u em_x) / em_y
                lo, hi = sorted(((-Aa * abs(den) + u * em[0]) / em[1], (Aa * abs(den) + u * em[0]) / em[1]))
            for w in range(int(math.floor(lo)) - 1, int(math.ceil(hi)) + 2):
                v = (u, w) if k == 0 else (w, u)
                if v == (0, 0) or not allowed(v) or abs(self.Q(v)) > B:
                    continue
                found.add(self.canonical(v))
        return found

    def least(self, allowed):
        """(the least |Q| among allowed vectors, the classes that attain it, the next value), by the complete enumeration"""
        B0 = min(abs(self.Q(v)) for v in itertools.product(range(-15, 16), repeat=2) if v != (0, 0) and allowed(v))
        assert B0 > 0
        mem = self.members(B0, allowed)
        low = min(abs(self.Q(v)) for v in mem)
        return low, sorted(v for v in mem if abs(self.Q(v)) == low)


def sector(mark, q):
    res = {((s * q * mark[0]) % 5, (s * q * mark[1]) % 5) for s in (1, -1)}
    return lambda v: (v[0] % 5, v[1] % 5) in res


def offset(ax, v, apex):
    """the place of the class of v along one period, from the apex, in (-1/2, 1/2]"""
    d = ax.pos(v) - ax.pos(apex)
    d = d - mp.floor(d)
    return d - 1 if d > mp.mpf(1) / 2 else d


def table(w, act, mark):
    """for a closed word: how the history acts on the mark; the untwisted least classes; the two twisted sectors"""
    A = word(w); ax = Axis(A, act)
    img = act(mark, A)
    sign = 1 if (img[0] - mark[0]) % 5 == 0 and (img[1] - mark[1]) % 5 == 0 else (-1 if (img[0] + mark[0]) % 5 == 0 and (img[1] + mark[1]) % 5 == 0 else 0)
    low, classes = ax.least(lambda v: True)
    out = {"sign": sign, "untwisted": (low, classes), "axis": ax}
    if sign and len(classes) >= 1:
        apex = classes[0]
        for q in (1, 2):
            lo, cl = ax.least(sector(mark, q))
            out[q] = (lo, sorted(offset(ax, v, apex) for v in cl), cl)
    return out


def shape(t, q):
    """('one', place) or ('pair', distance) or the raw list"""
    offs = t[q][1]
    if len(offs) == 1:
        return ("one", abs(offs[0]))
    if len(offs) == 2 and abs(offs[0] + offs[1]) < mp.mpf(10) ** -25:
        return ("pair", abs(offs[0]))
    return ("other", [mp.nstr(o, 8) for o in offs])


