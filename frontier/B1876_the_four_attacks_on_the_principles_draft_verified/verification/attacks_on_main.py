def histories_by_trace(tmax):
    """every cyclic two-act word (powers included) with trace at most tmax, as run sequences of even length, L first, up to rotation by two runs"""
    found = {}
    def rec(runs, M):
        n = len(runs)
        X = (lambda r: ((1, r), (0, 1))) if n % 2 == 0 else (lambda r: ((1, 0), (r, 1)))
        r = 1
        while True:
            M2 = mul(M, X(r))
            if tr(M2) > tmax and n >= 1:
                break
            if n == 0 and r > tmax:
                break
            runs2 = runs + (r,)
            if len(runs2) % 2 == 0:
                key = min(runs2[s:] + runs2[:s] for s in range(0, len(runs2), 2))
                found.setdefault(tr(M2), set()).add(key)
            rec(runs2, M2)
            r += 1
    rec((), I2)
    return found


