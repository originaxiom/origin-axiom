NAMES = {L: "L", R: "R", F: "F", F2: "F'", P: "P", I2: "1"}


def word(letters, table):
    M = I2
    for ch in letters:
        M = mul(M, table[ch])
    return M


def necklace(w): return min(w[s:] + w[:s] for s in range(len(w)))
def primitive(w): return not any(len(w) % d == 0 and w == w[:d] * (len(w) // d) for d in range(1, len(w)))
SW = str.maketrans("LR", "RL")


def group(gens, N):
    """the group generated by gens modulo N"""
    one = tuple(tuple(x % N for x in r) for r in I2)
    seen, frontier = {one}, [one]
    gens = [tuple(tuple(x % N for x in r) for r in g) for g in gens]
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:
                x = mul(g, h, N)
                if x not in seen:
                    seen.add(x)
                    nxt.append(x)
        frontier = nxt
    return seen


def up_to_scalars(G, N):
    """the number of elements of G modulo the scalar matrices of G"""
    scal = [c for c in range(1, N) if ((c, 0), (0, c)) in G]
    reps = set()
    for g in G:
        reps.add(min(tuple(tuple((c * x) % N for x in r) for r in g) for c in scal))
    return len(reps), scal


