#!/usr/bin/env python3
"""B1535 Part M -- the covers' own classes at the pulled-back members of m135 and m136 (sL-10 item 14, first half), read in two
routes.  Library and runner; the sealed run is `python3 -u part_m.py --record` (after the seal), the controls use the same
functions on banked comparisons only.

The population (PREREGISTRATION section 5): every member nu of sm:B1534 at kappa = +-1 and every subgroup B != 1 of its
contributing group (sm:B1534's C_nu, Lemma Z'): the deck characters of every finite abelian cover that can carry a count at nu.

The classes at (nu, B), each a set of components c_chi in Z^1(M; nu^5 chi rho), chi in B (mixed_lib's comps):
  - pure-1:<name>    the class of sm:B1534 named <name> at chi = 1 (a pulled-back class);
  - pure-<chi0>:<name>  at one chi0 != 1, the class <name> of sm:B1534's member eta = nu^5 chi0 (Lemma R: banked as eta's count
                     over B);
  - mixed-generic-1, -2  every component with h^1 >= 1, each a combination of its representatives with coefficients from a
                     hash of (state, nu, B, name, chi, j) in {1, ..., 97};
  - mixed-interior   every component's interior classes, hashed coefficients, where at least two components have one;
  - mixed-int+gen    the first component with an interior class at its interior class, the others generic;
  - mixed-cancel     at a fibre-direction cover, a combination of the components vanishing on the first non-identity cover
                     cusp g P g^-1 and not interior, where one exists.  On that cusp the class pulled back to P is
                     (nu^5 rho)(g) Sum_chi chi(g) [c_chi|_P] (c_chi(g p g^-1) = M(g) c_chi(p) + (1 - M(g p g^-1)) c_chi(g)).
                     Route RS reads the cusps itself, so its k checks the cancellation.
Route Ind (exact over Q(zeta_24), mixed_lib): the circulant modules on M.  Route RS (GF(p) at two primes, rs_lib): the same
components restricted to the cover's own Reidemeister-Schreier presentation.  Both read Theorem C's identities at every class."""
