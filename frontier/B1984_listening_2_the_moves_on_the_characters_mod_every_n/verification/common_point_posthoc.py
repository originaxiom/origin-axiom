from itertools import product
def orbits(N, pts, maps):
    seen, out = set(), []
    for v in pts:
        if v in seen: continue
        orb, st = {v}, [v]
        while st:
            u = st.pop()
            for f in maps:
                w = f(u)
                if w not in orb: orb.add(w); st.append(w)
        seen |= orb; out.append(frozenset(orb))
    return out
def moves(N): return (lambda v: (v[0], v[2], (v[0] * v[2] - v[1]) % N), lambda v: (v[2], v[1], (v[1] * v[2] - v[0]) % N))
def leaf(N): return [v for v in product(range(N), repeat=3) if (v[0] ** 2 + v[1] ** 2 + v[2] ** 2 - v[0] * v[1] * v[2] - 2) % N == (-2) % N]
def factor(N):
    f, d = {}, 2
    while N > 1:
        while N % d == 0: f[d] = f.get(d, 0) + 1; N //= d
        d += 1
    return f
