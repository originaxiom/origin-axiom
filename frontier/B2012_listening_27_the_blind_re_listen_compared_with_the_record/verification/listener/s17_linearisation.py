# s17_linearisation.py -- derivatives of L and R at the two common fixed points (exact, sympy) and the groups
# they generate (GAP): over Z at (0,0,0); reduced mod p at (2,2,2). Also the quadratic part of k at each point.
import sympy as sp
x, y, z = sp.symbols('x y z')
Lm = sp.Matrix([x, z, x*z - y]); Rm = sp.Matrix([z, y, y*z - x])
k = x**2 + y**2 + z**2 - x*y*z
for pt in [(0, 0, 0), (2, 2, 2)]:
    sub = dict(zip((x, y, z), pt))
    JL = Lm.jacobian([x, y, z]).subs(sub); JR = Rm.jacobian([x, y, z]).subs(sub)
    H = sp.hessian(k, (x, y, z)).subs(sub) / 2
    print("at", pt, " dL =", JL.tolist(), " dR =", JR.tolist(), " charpoly dL:", sp.factor(JL.charpoly().as_expr()), " quadratic part of k:", sp.expand((sp.Matrix([x, y, z]).T*H*sp.Matrix([x, y, z]))[0]))
    print("    dL^T H dL == H:", sp.simplify(JL.T*H*JL - H) == sp.zeros(3), "  dR^T H dR == H:", sp.simplify(JR.T*H*JR - H) == sp.zeros(3))
from sage.all import libgap
JL0 = [[1, 0, 0], [0, 0, 1], [0, -1, 0]]; JR0 = [[0, 0, 1], [0, 1, 0], [-1, 0, 0]]
G0 = libgap.Group([libgap.eval(str(JL0)), libgap.eval(str(JR0))])
print("group generated by dL, dR at (0,0,0) over Z: order", G0.Size(), "structure", G0.StructureDescription())
JL2 = [[1, 0, 0], [0, 0, 1], [2, -1, 2]]; JR2 = [[0, 0, 1], [0, 1, 0], [-1, 2, 2]]
for p in (5, 7, 11, 13):
    F = libgap.GF(p)
    G = libgap.Group([libgap.eval(str(JL2)) * libgap.One(F), libgap.eval(str(JR2)) * libgap.One(F)])
    print("at (2,2,2) mod %d: group order %s = |PSL(2,%d)|=%d ? structure %s" % (p, G.Size(), p, p*(p*p-1)//2, G.StructureDescription()))
