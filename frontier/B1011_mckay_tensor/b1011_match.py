# quaternions as 4-tuples of Z60 (real coeffs in Q(sqrt5) subfield)
def qmul(a, b):
    a0, a1, a2, a3 = a; b0, b1, b2, b3 = b
    return (a0*b0 - a1*b1 - a2*b2 - a3*b3,
            a0*b1 + a1*b0 + a2*b3 - a3*b2,
            a0*b2 - a1*b3 + a2*b0 + a3*b1,
            a0*b3 + a1*b2 - a2*b1 + a3*b0)
def qneg(a): return tuple((-x) for x in a)
ONEQ = (Z60.one(), Z60.zero(), Z60.zero(), Z60.zero())

def close_group(gens):
    seen = {tuple(x.c for x in ONEQ): ONEQ}
    frontier = [ONEQ]
    while frontier:
        nxt = []
        for M in frontier:
            for g in gens:
                Mg = qmul(M, g)
                k = tuple(x.c for x in Mg)
                if k not in seen:
                    seen[k] = Mg; nxt.append(Mg)
        frontier = nxt
    return list(seen.values())

