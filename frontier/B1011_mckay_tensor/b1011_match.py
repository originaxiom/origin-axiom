def qconj_classes(G):
    idx = {tuple(x.c for x in g): g for g in G}
    inv = {}
    for g in G:
        gc = (g[0], *[(-x) for x in g[1:]])   # unit quaternion inverse = conjugate
        inv[tuple(x.c for x in g)] = gc
    unassigned = set(idx.keys())
    classes = []
    while unassigned:
        k = next(iter(unassigned)); M = idx[k]
        orb = set()
        for gk, g in idx.items():
            c = qmul(qmul(g, M), inv[gk])
            orb.add(tuple(x.c for x in c))
        unassigned -= orb
        classes.append((idx[next(iter(orb))], len(orb)))
    return classes

