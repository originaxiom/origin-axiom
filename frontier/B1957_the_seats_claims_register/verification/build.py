"""B1957: the register's state, from UNITS.json and the verification records.
A record is a JSON file under records/: {"id", "date", "verdict", "how", "units": [unit ids], "note"}.
Verdicts: VERIFIED (recomputed on main and it holds), REFUTED (recomputed and it fails, or contradicted by a verified
fact), CONDITIONAL (holds given premises the record lists; the premises are not derived), PARTIAL (part checked; the
record says which), SUPERSEDED (withdrawn or corrected by its own seat, with the successor named), NOTED (not a
mathematical claim: custody, a request, a plan, a caveat; the record says which and what was done with it).
A statement with no record is PENDING.  A file is READ AT ITS SOURCE only when a record of kind "read" names it."""
import collections, json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
VERDICTS = ("VERIFIED", "REFUTED", "CONDITIONAL", "PARTIAL", "SUPERSEDED", "NOTED")


def load():
    U = json.loads((HERE / "UNITS.json").read_text())
    recs = [json.loads(p.read_text()) for p in sorted((HERE / "records").glob("*.json"))]
    return U, recs


def state():
    U, recs = load(); ids = {u[0]: u for u in U["units"]}; status = {}; read = {}
    for r in recs:
        assert r["verdict"] in VERDICTS + ("READ",), r["id"]
        if r["verdict"] == "READ":
            for f in r["files"]: read[r["lane"] + " | " + f] = r["id"]
            continue
        assert r.get("how"), r["id"]
        for u in r["units"]:
            assert u in ids, (r["id"], u)
            assert status.get(u, (r["verdict"],))[0] == r["verdict"], ("two verdicts", u, status.get(u), r["id"])
            status[u] = (r["verdict"], r["id"])
    return U, ids, status, read


def summary():
    U, ids, status, read = state(); per = collections.OrderedDict()
    for f in U["files"]:
        per[f["lane"] + " | " + f["file"]] = {"lane": f["lane"], "units": 0, "statements": 0, "read": (f["lane"] + " | " + f["file"]) in read, **{v: 0 for v in VERDICTS}, "PENDING": 0}
    filemap = {}
    for f in U["files"]:
        filemap[(f["lane"], f["file"])] = f["file"]
    tagmap = {}
    for uid, form, kind, sha in U["units"]:
        lane, tag, line = uid.split(":"); tagmap.setdefault((lane, tag), None)
    # unit id -> file: by lane and tag (the tag is the path without its first folder and extension)
    def tag_of(path):
        parts = path.split("/"); stem = parts[-1][:-3]
        if parts[0] == "relays" and len(parts) == 2: return stem
        return "/".join(parts[1:-1] + [stem]) if parts[0] in ("relays", "reports") else path[:-3]
    t2f = {(f["lane"], tag_of(f["file"])): f["lane"] + " | " + f["file"] for f in U["files"]}
    for uid, form, kind, sha in U["units"]:
        lane, tag, line = uid.split(":"); p = per[t2f[(lane, tag)]]; p["units"] += 1
        if kind == "s":
            p["statements"] += 1; p[status[uid][0] if uid in status else "PENDING"] += 1
    lanes = collections.OrderedDict()
    for f, p in per.items():
        L = lanes.setdefault(p["lane"], {"files": 0, "read": 0, "units": 0, "statements": 0, **{v: 0 for v in VERDICTS}, "PENDING": 0})
        L["files"] += 1; L["read"] += p["read"]
        for k in ("units", "statements", "PENDING") + VERDICTS: L[k] += p[k]
    return per, lanes


if __name__ == "__main__":
    per, lanes = summary()
    (HERE / "SUMMARY.json").write_text(json.dumps({"lanes": lanes, "files": per}, indent=1) + "\n")
    tot = {k: sum(L[k] for L in lanes.values()) for k in ("files", "read", "units", "statements", "PENDING") + VERDICTS}
    hdr = "| lane | files | read at source | statements | verified | refuted | conditional | partial | superseded | noted | **pending** |"
    out = ["# The seats' claims register: where it stands", "", "*Generated by `verification/build.py` from `UNITS.json` and `verification/records/`. Do not edit by hand.*", "", hdr, "|---|---|---|---|---|---|---|---|---|---|---|"]
    row = lambda n, L: "| %s | %d | %d | %d | %d | %d | %d | %d | %d | %d | **%d** |" % (n, L["files"], L["read"], L["statements"], L["VERIFIED"], L["REFUTED"], L["CONDITIONAL"], L["PARTIAL"], L["SUPERSEDED"], L["NOTED"], L["PENDING"])
    for n, L in lanes.items(): out.append(row(n, L))
    out.append(row("**all**", tot)); out += ["", "## By file", "", "| lane | file | read at source | statements | settled | **pending** |", "|---|---|---|---|---|---|"]
    # CHANGED 2026-11-18: a seat's file whose path lies under one of main's own directories, or at the top level, is written
    # as git's <head>:<path>, the form `git show` reads: written bare it reads as main's file, though it is the seat's version on
    # its branch (the stage4-sync lane's arcs and its edits of main's pages; the path-references gate caught the first of them)
    heads = {l["lane"]: l["head"] for l in json.loads((HERE / "UNITS.json").read_text())["lanes"]}
    MAINS = ("docs/", "frontier/", "scripts/", "tests/", "knowledge/", "papers/", "speculations/", "philosophy/", "story/", "src/")
    cite = lambda lane, path: ("%s:%s" % (heads[lane], path)) if (path.startswith(MAINS) or "/" not in path) else path
    for f, p in per.items():
        out.append("| %s | `%s` | %s | %d | %d | **%d** |" % (p["lane"], cite(p["lane"], f.split(" | ", 1)[1]), "yes" if p["read"] else "no", p["statements"], p["statements"] - p["PENDING"], p["PENDING"]))
    (HERE.parent / "REGISTER.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[4:6 + len(lanes) + 1]))
