    def km(rows): return DomainMatrix([[K.from_sympy(sp.nsimplify(e)) for e in r] for r in rows], (len(rows), len(rows[0])), K)
    def simp(M): return M.applyfunc(lambda e: sp.simplify(sp.expand(e)))

