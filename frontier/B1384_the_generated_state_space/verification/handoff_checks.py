LETTERS = "cdefghijk"            # y_0, y_1, ... ; 'z' is a^n


def rs_cover(n):
    """Reidemeister-Schreier for the n-fold cyclic cover (a, b -> 1 in Z/n), transversal a^k.  Generators: z = a^n and
    y_k = a^k b a^-(k+1) (k < n-1), y_{n-1} = a^(n-1) b.  Returns (gens, words-in-a,b of the generators, rewrite)."""
    gens = ["z"] + [LETTERS[k] for k in range(n)]
    words = {"z": "a" * n}
    for k in range(n):
        words[LETTERS[k]] = "a" * k + "b" + ("A" * (k + 1) if k < n - 1 else "")

    def rewrite(w, k=0):
        out = []
        for ch in w:
            if ch == "a":
                if k == n - 1:
                    out.append("z")
                k = (k + 1) % n
            elif ch == "A":
                if k == 0:
                    out.append("Z")
                k = (k - 1) % n
            elif ch == "b":
                out.append(LETTERS[k])
                k = (k + 1) % n
            elif ch == "B":
                k = (k - 1) % n
                out.append(LETTERS[k].upper())
        return "".join(out), k

    rels = []
    for k in range(n):
        r, kk = rewrite(RELATOR, k)
        assert kk == k
        rels.append(r)
    mu, k1 = rewrite("a" * n)
    lam, k2 = rewrite(LONGITUDE)
    assert k1 == 0 and k2 == 0 and mu == "z"
    return gens, words, rewrite, rels, mu, lam


def geometric(F, n):
    """rho_geo on the n-fold cover's generators: A = [[1,1],[0,1]], B = [[1,0],[-w,1]] over GF(p)"""
    w = F.root_of_unity(3)
    A, B = [[1, 1], [0, 1]], [[1, 0], [(-w) % F.p, 1]]
    base = IL.Rep(F, ["a", "b"], {"a": A, "b": B})
    assert base.check_relators([RELATOR])
    gens, words, rewrite, rels, mu, lam = rs_cover(n)
    return {g: base.word(words[g]) for g in gens}, (gens, words, rewrite, rels, mu, lam)


def characters_via_smith(gens, rels, N):
    """all characters pi -> Z/N of a finitely presented group, via an integer Smith decomposition S = U E V"""
    from sympy import Matrix
    from sympy.matrices.normalforms import smith_normal_decomp
    E = Matrix([[IL.abelian_exponents(r, gens)[g] for g in gens] for r in rels])
    S, U, V = smith_normal_decomp(E)
    ranges = []
    for i in range(len(gens)):
        s = abs(S[i, i]) if i < min(S.shape) else 0
        from math import gcd
        step = N // gcd(s, N) if s else 1
        ranges.append([t * step % N for t in range(N // step)] if s else list(range(N)))
    chars = []
    for kp in itertools.product(*ranges):
        k = V * Matrix(kp)
        chars.append({g: int(k[i]) % N for i, g in enumerate(gens)})
    return chars


def induce(F, V6, cover6, cover2):
    """Ind_{Gamma6}^{Gamma2} V on M2's generators; coset representatives r_i = a^(2i), i = 0, 1, 2"""
    gens6, words6, rewrite6, *_ = cover6
    gens2, words2, *_ = cover2
    d = len(V6.M[gens6[0]])
    rep6 = V6
    out = {}
    for g in gens2:
        wg = words2[g]
        eg = sum(1 if ch.islower() else -1 for ch in wg)
        assert eg % 2 == 0
        M = F.zeros(3 * d, 3 * d)
        for i in range(3):
            j = (i + eg // 2) % 3
            h = "A" * (2 * j) + wg + "a" * (2 * i)
            hw, kk = rewrite6(h, 0)
            assert kk == 0
            blk = rep6.word(hw)
            for r in range(d):
                for c in range(d):
                    M[j * d + r][i * d + c] = blk[r][c]
        out[g] = M
    return IL.Rep(F, gens2, out)


def s3_shapiro_mackey(p=601, N=40, want_firing=6, want_quiet=24, seed=3, cap=40000):
    """seeds: rank-2 non-split rho_chi (chi with H^1(M6; chi^2) = 1) twisted by a character psi, V = rho_chi (x) psi;
    about one pair in twenty has I != 0 on M6 (B1375), so pairs are drawn until both kinds are represented"""
    F = IL.GF(p)
    zeta = F.root_of_unity(N)
    _, cover6 = geometric(F, 6)
    _, cover2 = geometric(F, 2)
    gens6, _, _, rels6, mu6, lam6 = cover6
    gens2, _, _, rels2, mu2, lam2 = cover2
    assert len(gens6) == 7 and len(gens2) == 3
    chars = characters_via_smith(gens6, rels6, N)
    assert len(chars) == 12800                                            # H_1(M6) = Z/8 + Z/40 + Z (B1375)
    rng = random.Random(seed)
    seeds = []
    for chi in chars:
        chi_val = {g: pow(zeta, chi[g], p) for g in gens6}
        sq = {g: chi_val[g] * chi_val[g] % p for g in gens6}
        h1, ct = IL.h1_and_cocycle(F, gens6, rels6, mu6, lam6, sq)
        if ct is not None:
            seeds.append(IL.Rep(F, gens6, IL.reducible_rep(F, gens6, chi_val, ct)))
    assert len(seeds) == 640                                              # B1375: 639 non-trivial loci, all h^1 = 1
    tested = nonzero = unip = draws = 0
    quiet = 0
    while (nonzero < want_firing or quiet < want_quiet) and draws < cap:
        draws += 1
        rho = rng.choice(seeds)
        psi = rng.choice(chars)
        psi_val = {g: pow(zeta, psi[g], p) for g in gens6}
        V = IL.Rep(F, gens6, IL.module(F, gens6, rho.M, 1, psi_val))
        assert V.check_relators(rels6)
        I6pre = IL.index(V, rels6, mu6, lam6)[0]
        if I6pre == 0 and quiet >= want_quiet:
            continue
        if I6pre != 0 and nonzero >= want_firing:
            continue
        quiet += I6pre == 0
        Ind = induce(F, V, cover6, cover2)
        assert Ind.check_relators(rels2)
        d6 = IL.cohomology_data(V, rels6, mu6, lam6)
        d6s = IL.cohomology_data(V.dual(), rels6, mu6, lam6)
        d2 = IL.cohomology_data(Ind, rels2, mu2, lam2)
        d2s = IL.cohomology_data(Ind.dual(), rels2, mu2, lam2)
        assert d6 == d2 and d6s == d2s, (d6, d2, d6s, d2s)                    # Shapiro + Mackey: all five numbers
        I6 = IL.index(V, rels6, mu6, lam6)[0]
        I2 = IL.index(Ind, rels2, mu2, lam2)[0]
        assert I6 == I2
        # the coset generator T = Ind(a^2): T^3 = Ind(a^6) = rho(mu6) on each block
        T = Ind.M["z"]
        T3 = F.mul(F.mul(T, T), T)
        Rm = V.word(mu6)
        dd = len(Rm)
        for i in range(3):
            for r in range(dd):
                for c in range(dd):
                    assert T3[i * dd + r][i * dd + c] == Rm[r][c]
        eye = F.eye(3 * dd)
        N3 = F.sub(T3, eye)
        if Rm != F.eye(dd) and all(Rm[i][i] == 1 for i in range(dd)):         # non-trivial unipotent at the cusp
            assert F.mul(N3, N3) == F.zeros(3 * dd, 3 * dd)
            unip += 1
        tested += 1
        nonzero += I6 != 0
    assert nonzero >= want_firing and quiet >= want_quiet and unip > 0
    return {"seeds": tested, "with I != 0": nonzero, "unipotent T^3 != 1 with (T^3-1)^2 = 0": unip, "draws": draws}


