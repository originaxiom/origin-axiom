def e8_roots():
    roots = []
    for i, j in itertools.combinations(range(8), 2):
        for si, sj in itertools.product((1, -1), repeat=2):
            v = [0] * 8
            v[i], v[j] = si, sj
            roots.append(tuple(Fr(x) for x in v))
    for signs in itertools.product((1, -1), repeat=8):
        if signs.count(-1) % 2 == 0:
            roots.append(tuple(Fr(s, 2) for s in signs))
    assert len(roots) == 240
    return roots


def ip(u, v):
    return sum(x * y for x, y in zip(u, v))


def e(i, s=1):
    v = [Fr(0)] * 8
    v[i] = Fr(s)
    return v


def vadd(*vs):
    return tuple(sum(c) for c in zip(*vs))


def cartan(simple):
    return [[int(ip(a, b)) for b in simple] for a in simple]


A4_CARTAN = [[2, -1, 0, 0], [-1, 2, -1, 0], [0, -1, 2, -1], [0, 0, -1, 2]]


def span_roots(roots, basis):
    """roots lying in the Q-span of the basis vectors (exact Gaussian elimination on the Gram system)"""
    from sympy import Matrix
    Bm = Matrix([[x for x in b] for b in basis]).T
    out = []
    for r in roots:
        aug = Bm.row_join(Matrix([x for x in r]))
        if aug.rank() == Bm.rank():
            out.append(r)
    return out


def s1_common_sl5():
    R = e8_roots()
    gauge = [vadd(e(0), e(1, -1)), vadd(e(1), e(2, -1)), vadd(e(2), e(3, -1)), vadd(e(3), e(4, -1))]
    struct = [vadd(e(6), e(7, -1)), vadd(e(5), e(6, -1)), vadd(e(6), e(7)), tuple(Fr(-1, 2) for _ in range(8))]
    assert all(r in R for r in gauge + struct)
    assert cartan(gauge) == A4_CARTAN and sorted(map(sorted, cartan(struct))) == sorted(map(sorted, A4_CARTAN))
    assert all(ip(g, s) == 0 for g in gauge for s in struct)
    gauge_roots = span_roots(R, gauge)
    struct_roots = span_roots(R, struct)
    assert len(gauge_roots) == 20 and len(struct_roots) == 20
    # the Standard Model inside the gauge A4: colour e0-e1, e1-e2; weak e3-e4; hypercharge along (2,2,2,-3,-3,0,0,0)
    colour = [gauge[0], gauge[1], vadd(gauge[0], gauge[1])]
    weak = [gauge[3]]
    Y = tuple(Fr(x) for x in (2, 2, 2, -3, -3, 0, 0, 0))
    sm_roots = colour + weak
    centraliser = [r for r in R if ip(r, Y) == 0 and all(ip(r, s) == 0 for s in sm_roots)]
    assert sorted(centraliser) == sorted(struct_roots)                   # exactly the structure A4's 20 roots
    # the Cartan part commuting with the SM: the orthogonal complement of the SM roots in R^8 (rank 8 - 3 = 5) = Y + 4
    # an E6 through the gauge A4
    x = tuple(Fr(v) for v in (0, 0, 0, 0, 1, 1, 0, 0))
    z = tuple(Fr(v, 2) for v in (-1, -1, -1, 1, 1, -1, 1, 1))
    assert x in R and z in R
    e6_basis = gauge + [x, z]
    from sympy import Matrix
    gram = Matrix([[ip(a, b) for b in e6_basis] for a in e6_basis])
    e6_roots = span_roots(R, e6_basis)
    assert gram.det() == 3 and len(e6_roots) == 72
    e6_centraliser = [r for r in e6_roots if ip(r, Y) == 0 and all(ip(r, s) == 0 for s in sm_roots)]
    beta = vadd(e(6), e(7))
    assert sorted(e6_centraliser) == sorted([beta, tuple(-c for c in beta)]) and beta in struct_roots
    fam = [r for r in struct_roots if ip(r, beta) == 0]
