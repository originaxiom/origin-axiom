def s4_sym4_twists():
    out = {}
    for p in PRIMES:
        F = IL.GF(p)
        geo2, cover2 = geometric(F, 2)
        gens2, _, _, rels2, mu2, lam2 = cover2
        S4 = {g: IL.sym_power(F, geo2[g], 4) for g in gens2}
        V0 = IL.Rep(F, gens2, S4)
        assert V0.check_relators(rels2)
        I0, d0, d0s = IL.index(V0, rels2, mu2, lam2)
        assert I0 == 0                                                        # self-dual: I = 0
        zeta5 = F.root_of_unity(5)
        chars = IL.characters(F, gens2, rels2, 5)
        cusp_trivial = [c for c in chars if any(c.values())
                        and IL.char_value(F, zeta5, c, mu2) == 1 and IL.char_value(F, zeta5, c, lam2) == 1]
        assert len(cusp_trivial) == 4                                         # the four non-trivial characters of Z/5
        rows = set()
        for c in cusp_trivial:
            psi_val = {g: pow(zeta5, c[g], p) for g in gens2}
            V = IL.Rep(F, gens2, {g: F.scale(psi_val[g], S4[g]) for g in gens2})
            assert V.check_relators(rels2)
            dv = IL.cohomology_data(V, rels2, mu2, lam2)
            dvs = IL.cohomology_data(V.dual(), rels2, mu2, lam2)
            I = IL.index(V, rels2, mu2, lam2)[0]
            assert dv == (0, 1, 1, 2, 1) and dvs == (0, 1, 1, 2, 1) and I == 0
            rows.add((dv, dvs, I))
        out[p] = {"Sym4 untwisted I": I0, "twists": sorted(rows)}
    return out


