def s2_parabolic_lemma(trials=60, seed=5):
    import sympy as sp
    A = sp.Matrix(2, 2, sp.symbols("a0:4"))
    B = sp.Matrix(3, 3, sp.symbols("b0:9"))
    X = sp.Matrix(2, 3, sp.symbols("x0:6"))
    Yv = sp.Matrix(2, 3, sp.symbols("y0:6"))
    G = sp.BlockMatrix([[A, X], [sp.zeros(3, 2), B]]).as_explicit()
    Ginv = sp.BlockMatrix([[A.inv(), -A.inv() * X * B.inv()], [sp.zeros(3, 2), B.inv()]]).as_explicit()
    assert sp.simplify(G * Ginv - sp.eye(5)) == sp.zeros(5, 5)
    N = sp.BlockMatrix([[sp.zeros(2, 2), Yv], [sp.zeros(3, 2), sp.zeros(3, 3)]]).as_explicit()
    lhs = sp.simplify(G * N * Ginv)
    rhs = sp.BlockMatrix([[sp.zeros(2, 2), A * Yv * B.inv()], [sp.zeros(3, 2), sp.zeros(3, 3)]]).as_explicit()
    assert sp.simplify(lhs - rhs) == sp.zeros(5, 5)                   # the block X cancels identically
    # N(n_+) = P_{2,3}: a random g preserving U normalises n_+; a random g moving U does not
    rng = random.Random(seed)
    def rand_int_matrix(n, m):
        return sp.Matrix(n, m, lambda i, j: rng.randint(-3, 3))
    basis = []
    for i in range(2):
        for j in range(3):
            Eij = sp.zeros(5, 5)
            Eij[i, 2 + j] = 1
            basis.append(Eij)
    def in_nplus(M):
        return all(M[i, j] == 0 for i in range(5) for j in range(5) if not (i < 2 and j >= 2))
    ok_p = ok_np = 0
    while ok_p < trials // 2 or ok_np < trials // 2:
        g = rand_int_matrix(5, 5)
        if g.det() == 0:
            continue
        preserves_U = all(g[i, j] == 0 for i in range(2, 5) for j in range(2))
        normalises = all(in_nplus(g * Eb * g.inv()) for Eb in basis)
        assert preserves_U == normalises
        if preserves_U:
            ok_p += 1
        else:
            ok_np += 1
        if ok_p < trials // 2 and rng.random() < 0.5:          # also feed in parabolic elements deliberately
            g = rand_int_matrix(5, 5)
            for i in range(2, 5):
                for j in range(2):
                    g[i, j] = 0
            if g.det() != 0:
                assert all(in_nplus(g * Eb * g.inv()) for Eb in basis)
                ok_p += 1
    return {"X cancels": True, "normaliser = P_{2,3} on": trials}


