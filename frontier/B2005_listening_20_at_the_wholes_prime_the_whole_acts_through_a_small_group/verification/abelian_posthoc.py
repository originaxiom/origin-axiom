"""B2005, POST HOC (labelled; written after small_group_run.txt showed the abelianisation Z6 exactly where B2003's halving
holds, k = 3, 4, 5, and Z2 at mod 9): the order of the abelianisation of the group generated by C and sigma at the levels
where B2003 found the halving absent (mod 25, 49, 15, 45 on the orbit of (3,3,3); the leaf mod 5, 7), and whether rho
factors there (it can only if 6 divides the abelianisation's order and the labels agree).
    python3 -B abelian_posthoc.py > abelian_posthoc_run.txt"""
import contextlib, io, pathlib, time
from sympy.combinatorics import Permutation, PermutationGroup
HERE = pathlib.Path(__file__).resolve().parent
src = (HERE.parent.parent / "B2004_listening_19_the_mechanism_of_the_halving_the_modular_group_and_its_order_six_character" / "verification" / "mechanism.py").read_text().split("WORDS = words(10)")[0]
ns = {"__file__": str(HERE / "abelian_posthoc.py")}
with contextlib.redirect_stdout(io.StringIO()): exec(compile(src, "b2004_head", "exec"), ns)
t0 = time.time()
for N, start, lab in ((5, None, "leaf mod 5"), (7, None, "leaf mod 7"), (15, (3, 3, 3), "mod 15"), (45, (3, 3, 3), "mod 45"), (25, (3, 3, 3), "mod 25"), (49, (3, 3, 3), "mod 49")):
    pts, idx, pC, pS, moves = ns["orbit"](N, start); n = len(pts)
    G = PermutationGroup([Permutation([int(i) for i in pC]), Permutation([int(i) for i in pS])])
    o = G.order(); d = G.derived_subgroup().order()
    print("%s: %d points; |G| = %s; abelianisation order %d; 6 divides it: %s  [%.0f s]" % (lab, n, o if o < 10**15 else "%.4e" % o, o // d, (o // d) % 6 == 0, time.time() - t0), flush=True)
