def action_on_cover(u, v, n):
    """the matrix Phi (gens x gens) of the automorphism a -> u, b -> v on the abelianized Schreier generators of Y_n:
    Phi[k][j] = exponent sum of generator j in the rewritten image of generator k."""
    gens, rels = TW.presentation(n, branched=True)
    words = TW.gen_words(n)
    Phi = np.zeros((len(gens), len(gens)), dtype=int)
    for k, g in enumerate(gens):
        img = subst(words[g], u, v)
        rw, kk = TW.rewrite(img, n, 0)
        assert kk == 0, (g, kk)
        for L in rw:
            Phi[k][abs(L) - 1] += (1 if L > 0 else -1)
    return Phi


def deck_action(n):
    gens, rels = TW.presentation(n, branched=True)
    words = TW.gen_words(n)
    Phi = np.zeros((len(gens), len(gens)), dtype=int)
    for k, g in enumerate(gens):
        img = [1] + words[g] + [-1]
        rw, kk = TW.rewrite(img, n, 0)
        assert kk == 0
        for L in rw:
            Phi[k][abs(L) - 1] += (1 if L > 0 else -1)
    return Phi


