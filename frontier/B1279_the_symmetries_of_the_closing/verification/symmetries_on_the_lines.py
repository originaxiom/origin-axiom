                rows = []
                for X, Y, s in ((X1, Y1, s1), (X2, Y2, s2)):
                    # (N X - s Y N)_{ij} = sum_k N_{ik} X_{kj} - s sum_k Y_{ik} N_{kj}
                    for i in range(2):
                        for j in range(2):
                            row = np.zeros(4, dtype=complex)
                            for k in range(2):
                                row[2 * i + k] += X[k, j]
                                row[2 * k + j] -= s * Y[i, k]
                            rows.append(row)
