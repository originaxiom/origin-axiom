    dictionary = {}
    frontier = [([], np.eye(2, dtype=complex))]
    for length in range(1, 10):
        nxt = []
        for w, X in frontier:
            for g in (1, -1, 2, -2):
                if w and w[-1] == -g:
                    continue
                Y = X @ RHO[g]
                nxt.append((w + [g], Y))
                c = Y[1, 0]
                if abs(c) > 1e-9:
                    x, y = reduce(Y[0, 0] / c)
                    key = (round(x, 4) % 1.0, round(y, 4) % 1.0, round(1.0 / abs(c) ** 2, 5))
                    if key not in dictionary:
                        dictionary[key] = Y
        frontier = nxt
