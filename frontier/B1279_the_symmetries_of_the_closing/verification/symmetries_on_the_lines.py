# ------------------------------------------------------------------------------------------------ the geometric holonomy
U = cmath.exp(1j * math.pi / 3)
RHO = {1: np.array([[1, 1], [0, 1]], dtype=complex), 2: np.array([[1, 0], [U, 1]], dtype=complex)}
RHO[-1], RHO[-2] = np.linalg.inv(RHO[1]), np.linalg.inv(RHO[2])


def ev(word, rho=RHO):
    out = np.eye(2, dtype=complex)
    for L in word:
        out = out @ rho[L]
    return out


def subst(word, u, v):
    """the word with a -> u, b -> v (u, v words in +-1, +-2)"""
    out = []
    for L in word:
        img = u if abs(L) == 1 else v
        out += img if L > 0 else [-x for x in reversed(img)]
    return out


def reduced_words(maxlen):
    words = [[]]
    out = []
    for length in range(1, maxlen + 1):
        nxt = []
        for w in words:
            for g in (1, -1, 2, -2):
                if w and w[-1] == -g:
                    continue
                nxt.append(w + [g])
        out += nxt
        words = nxt
    return out


