def target():
    d = json.loads(DATA.read_text())["masses_GeV"]; v, e = d["value"], d["sigma"]
    pr = [("c", "t"), ("u", "t"), ("s", "b"), ("d", "b"), ("mu", "tau"), ("e", "tau")]
