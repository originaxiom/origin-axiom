"""B1859 (data-free; exact integer arithmetic): the own-conductor shadow of the metallic grammar R^m L^m, for every m.

- **The shadow.** G_m is the group generated by the grammar's own letters L^m = [[1, m], [0, 1]] and R^m = [[1, 0], [m, 1]]
  in SL(2, Z/N), with N = m^2 + 4 the grammar's shadow modulus (B666, B1002).
- **B997 bounded another group.** Its proof bounds the order of all of SL(2, Z/N). G_m is a proper subgroup of that
  whenever gcd(m, N) = gcd(m, 4) > 1.
- **What is computed.** For m = 1..60 the closure of the two letters, up to a cap. Where the group is under the cap:
  its order, its involutions, its element orders, the order of its abelianisation.
- **The door.** A finite subgroup of SU(2) has at most one involution. A perfect group of order 120 is SL(2, 5), the
  binary icosahedral group. So a shadow of order 120 that is perfect, with one involution, is the E8 door.
- **The proof for every m** (FINDINGS section 2) has three branches: m odd, 4 | m, and m = 2 (mod 4). The table below
  is its check on m <= 60 and the computed input of its third branch (the order-32 group with seven involutions)."""
from math import gcd

CAP = 400


def mul(A, B, N):
    return ((A[0] * B[0] + A[1] * B[2]) % N, (A[0] * B[1] + A[1] * B[3]) % N,
            (A[2] * B[0] + A[3] * B[2]) % N, (A[2] * B[1] + A[3] * B[3]) % N)


def closure(gens, N, cap=CAP):
    I = (1, 0, 0, 1)
    seen, frontier = {I}, [I]
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:
                x = mul(g, h, N)
                if x not in seen:
                    seen.add(x); nxt.append(x)
                    if len(seen) > cap:
                        return None
        frontier = nxt
    return seen


def order_of(g, N):
    I, x, k = (1, 0, 0, 1), g, 1
    while x != I:
        x = mul(x, g, N); k += 1
    return k


def inverse(g, N):
    return (g[3] % N, (-g[1]) % N, (-g[2]) % N, g[0] % N)


def derived(G, N):
    comms = set()
    L = list(G)
    for a in L:
        ai = inverse(a, N)
        for b in L:
            comms.add(mul(mul(a, b, N), mul(ai, inverse(b, N), N), N))
    return closure(list(comms), N, cap=len(G))


rows, doors = [], []
for m in range(1, 61):
    N = m * m + 4
    assert N % 3 != 0 and gcd(m, N) == gcd(m, 4)
    G = closure([(1, m % N, 0, 1), (1, 0, m % N, 1)], N)
    if G is None:
        rows.append("m = %2d  N = %4d  gcd(m, 4) = %d  shadow order > %d" % (m, N, gcd(m, 4), CAP))
        continue
    hist = {}
    for g in G:
        o = order_of(g, N); hist[o] = hist.get(o, 0) + 1
    D = derived(G, N)
    ab = len(G) // len(D)
    door = len(G) == 120 and ab == 1 and hist.get(2, 0) == 1
    if door:
        doors.append(m)
    rows.append("m = %2d  N = %4d  gcd(m, 4) = %d  shadow order %3d  involutions %d  abelianisation %d  element orders %s%s"
                % (m, N, gcd(m, 4), len(G), hist.get(2, 0), ab, dict(sorted(hist.items())), "   <-- 2I: the E8 door" if door else ""))
print("\n".join(rows))
# the third branch's computed input: the image mod 8 of the letters when m = 2 (mod 4)
P = closure([(1, 2, 0, 1), (1, 0, 2, 1)], 8)
inv = sum(1 for g in P if order_of(g, 8) == 2)
assert len(P) == 32 and inv == 7
for m in (2, 6, 10, 14, 18):                       # for m = 2j, j odd, the letters mod 8 generate the same group
    assert closure([(1, m % 8, 0, 1), (1, 0, m % 8, 1)], 8) == P
# the second branch: for m = 4j the letters are trivial mod 4
for m in (4, 8, 12, 16):
    assert ((1, m % 4, 0, 1), (1, 0, m % 4, 1)) == ((1, 0, 0, 1), (1, 0, 0, 1))
assert doors == [1, 4]
print("=> the letters mod 8, for m = 2 (mod 4), generate a group of order 32 with 7 involutions: not a subgroup of SU(2)")
print("=> the door set on m <= 60 is %s: the golden (N = 5) and m = 4 (N = 20, the letters trivial mod 4 and generating SL(2, 5) mod 5)" % doors)
