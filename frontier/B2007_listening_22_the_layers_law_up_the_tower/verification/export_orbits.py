"""B2007: export the orbit of (3,3,3) mod 3^k (k = 2..6) as permutations C and sigma, with the reduction maps to mod 3^(k-1)
and mod 9, for the GAP run. Writes orbits.json (not committed: regenerated by this script; its SHA-256 is printed).
    python3 -B export_orbits.py > export_orbits_run.txt"""
import contextlib, hashlib, io, json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
src = (HERE.parent.parent / "B2004_listening_19_the_mechanism_of_the_halving_the_modular_group_and_its_order_six_character" / "verification" / "mechanism.py").read_text().split("WORDS = words(10)")[0]
ns = {"__file__": str(HERE / "export_orbits.py")}
with contextlib.redirect_stdout(io.StringIO()): exec(compile(src, "b2004_head", "exec"), ns)
levels = {}
for k in range(2, 7):
    N = 3 ** k; pts, idx, pC, pS, _ = ns["orbit"](N, (3, 3, 3))
    levels[k] = {"N": N, "pts": pts, "idx": idx, "C": [int(i) for i in pC], "S": [int(i) for i in pS]}
out = {}
for k in range(2, 7):
    L = levels[k]; d = {"N": L["N"], "n": len(L["pts"]), "C": L["C"], "S": L["S"]}
    if k >= 3:
        P = levels[k - 1]; d["red_prev"] = [P["idx"][(v[0] % P["N"], v[1] % P["N"], v[2] % P["N"])] for v in L["pts"]]
        Q = levels[2]; d["red9"] = [Q["idx"][(v[0] % 9, v[1] % 9, v[2] % 9)] for v in L["pts"]]
    out[str(k)] = d
    print("k = %d: mod %d, orbit %d points" % (k, L["N"], len(L["pts"])))
blob = json.dumps(out).encode(); (HERE / "orbits.json").write_bytes(blob)
print("orbits.json SHA-256 %s" % hashlib.sha256(blob).hexdigest())
