def realify(M):
    n = M.shape[0]; R = np.zeros((2 * n, 2 * n))
    R[0::2, 0::2] = M.real; R[0::2, 1::2] = -M.imag; R[1::2, 0::2] = M.imag; R[1::2, 1::2] = M.real
    return R
gens = []
def E(i, j, v):
    M = np.zeros((5, 5), complex); M[i, j] = v; return M
for blk in ([0, 1, 2], [3, 4]):
    for i, j in itertools.combinations(blk, 2):
        gens.append(E(i, j, 1) - E(j, i, 1)); gens.append(E(i, j, 1j) + E(j, i, 1j))
    for i, j in zip(blk, blk[1:]):
        gens.append(E(i, i, 1j) - E(j, j, 1j))
Y = 1j * np.diag([-1 / 3, -1 / 3, -1 / 3, 1 / 2, 1 / 2])
