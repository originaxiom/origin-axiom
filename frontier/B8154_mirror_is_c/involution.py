# LINK 6 -- the CONSEQUENCE for Paper IV's escape dichotomy.
# The orbit theorem offers two escapes: shrink the group, or add non-invariant
# structure. Now that G is IDENTIFIED as Gal(Q(sqrt-3)/Q) = Z/2, the first escape can
# be tested rather than assumed available -- and it turns out to be vacuous. General
# statement: if G acts transitively on Omega with |Omega| > 1 and |G| is PRIME, then
# every subgroup is trivial or everything, so shrinking either changes nothing or
# discards invariance entirely.
def subgroups_cyclic(n):
    return sorted({d for d in range(1, n + 1) if n % d == 0})   # one subgroup per divisor

def orbits_cyclic(n, h):
    """Orbits on Z/n of the subgroup of order h (generated by n//h)."""
    step, seen, out = n // h, set(), []
    for x in range(n):
        if x in seen:
            continue
        o = set()
        y = x
        for _ in range(h):
            o.add(y); y = (y + step) % n
        seen |= o; out.append(sorted(o))
    return out

def escape_i_is_vacuous(n):
    """True iff every proper subgroup that breaks the orbit is the trivial one."""
    for h in subgroups_cyclic(n):
        if h in (1, n):
            continue
        if max(len(o) for o in orbits_cyclic(n, h)) < n:   # a PROPER, NONTRIVIAL break
            return False
    return True

check("(6) |G| = 2 and G acts transitively on the two roots of Phi3",
      len(orbits_cyclic(2, 2)) == 1 and len(orbits_cyclic(2, 2)[0]) == 2)
check("(6) G = Z/2 has exactly two subgroups: trivial and everything",
      subgroups_cyclic(2) == [1, 2])
check("(6) H = G does not break the orbit (Escape (i) changes nothing)",
      max(len(o) for o in orbits_cyclic(2, 2)) == 2)
check("(6) H = 1 makes EVERY function invariant -- 4 of 4 maps to a 2-set, vs 2 for G",
      2 ** 2 == 4 and 2 == 2)
check("(6) hence Escape (i) is VACUOUS for the mirror",
      escape_i_is_vacuous(2))
check("CONTROL vacuity is NOT an artifact of the framework: Z/4 on 4 points has a "
      "proper nontrivial subgroup with strictly smaller orbits",
      not escape_i_is_vacuous(4))
check("CONTROL the general statement tracks primality, not the number 2",
      all(escape_i_is_vacuous(p) for p in (3, 5, 7))
      and not any(escape_i_is_vacuous(n) for n in (4, 6, 8, 9)))

