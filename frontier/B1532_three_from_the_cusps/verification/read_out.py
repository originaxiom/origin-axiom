#!/usr/bin/env python3
"""B1532 -- THE READ-OUT: the subgroup sums, the census of counts on every abelian cover, and the run's checks.

    python3 read_out.py [--record]   ->  read_out.json (and read_out_log.txt)

Inputs: terms_T.jsonl and terms_L.jsonl (run_terms.py), part0_T.json and part0_L.json.  Each route is read on its own data; the
census is formed in each route and the two censuses are compared.

The subgroups.  T_n^ is the group of labels (a, b) in (Q/Z)^2 under addition (a character's exponents).  Every subgroup B is
generated by at most two elements (T_n has rank <= 2); all of them are found by closure, and their number is checked against
Toth's count for Z/m x Z/n, s(m, n) = sum over a | m, b | n of gcd(a, b), with (m, n) the invariant factors read from the labels.

The sums (Lemma S).  For a member nu and a class c: S(B) = sum over chi in B of the term T(nu, chi, c), for W1 and Lambda^2 W1.
  - one-class members: the class c1;
  - two-class members: the interior class, the generic class, and every special class x; at x a chi whose special set
    contains x contributes its special term and every other chi its generic term (Lemma J).  Special points are compared and
    merged per member by their exact value in the route's own coordinate; the coincidence structure (which (chi, family) share
    a class) is compared between the routes, and the census uses the structure both routes show.
A count is generation-shaped when S_W = S_L2 != 0; it carries N = -S_W generations (sm:B1515's dictionary).  The W2 order counts
the negatives at the conjugate classes (Lemma D), so |N| is what the question reads.

Checks (each listed with its count of failures):
  D1  Part 0 passed in both routes;
  D2  at every generic class the four pencils predict h^1 of E, E*, Lambda^2 E, (Lambda^2 E)*: h^1 = k + h0(S) - rank delta0
      + m - r, with rank delta0 = h0(Q) - (h0(M) - h0(S)) (a deficiency-one presentation);
  D3  at every rational special point the flagged family's h^1 is above its generic value;
  D4  gen2 = gen wherever gen2 was read;
  D5  route T = route L term by term (the one-class terms, the interior and generic terms, the multiset of special readings and
      the pencils' (m, k, rank, number of points)) under route L's signature;
  D6  conjugation (Lemma D): T(-nu, -chi) = T(nu, chi) at the one-class, interior and generic classes, in each route;
  D7  the design-time theorems, term by term (any failure is a bug): every term is at or above its lower bound
      (1 - h^1(nu chi rho), 1 - h^1(nu^-3 chi rho)); at the interior class a W term with nu chi simple and a Lambda^2 term with
      nu^-3 chi simple are 0 (Corollary I); at a boundary-type class a simple W term lies in [0, 1 - [chi = nu^4]] and a simple
      Lambda^2 term in [0, 1].  The h^1 are sm:B1515's banked census values.
The predictions P1-P8 are read as the PREREGISTRATION's section 7 states them (P1 from route_c_run.json, P2 after adjudicate.py)."""
import argparse
