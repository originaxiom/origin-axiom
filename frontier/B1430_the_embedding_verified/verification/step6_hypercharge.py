"""Construct the hypercharge direction explicitly instead of searching:
find an A4 (su(5)) subsystem of E6 whose Dynkin chain is
      b1 - b2 - delta - gamma
with (b1,b2) the colour A2 and gamma the weak A1.  Then Y is the unique
vector in the A4 span with (Y,b1)=(Y,b2)=(Y,gamma)=0, (Y,delta)=1.
This is the su(5) hypercharge coweight, built from scratch.
"""
from fractions import Fraction as F
