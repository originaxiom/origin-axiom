# --- now: are there OTHER, non-conjugate SM-like lines? ------------------
# enumerate primitive integral coweight lines orthogonal to the A2+A1 in a
# box big enough to contain the hypercharge line, test the SM pattern
conds = [[int(x) for x in simple_coeffs(r)] for r in [b1, b2, gam]]
NBOX = max(6, max(abs(x) for x in nn))
cands = []
for m in product(range(-NBOX, NBOX + 1), repeat=6):
    if any(sum(ci * mi for ci, mi in zip(c, m)) != 0 for c in conds):
        continue
    if all(x == 0 for x in m):
        continue
    g = 0
    for x in m:
        g = gcd(g, abs(x))
    if g != 1:
        continue
    if m > tuple(-x for x in m):
        continue
    cands.append(m)
