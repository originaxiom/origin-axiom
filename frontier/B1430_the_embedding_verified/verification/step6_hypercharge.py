# --- how many W-classes give the SM pattern? -----------------------------
# act on Y by the stabiliser of the A2+A1 and see how many distinct LINES
def lin_of_perm(g):
    images = [roots[g[idx[a]]] for a in simple]

    def act(v):
        c = simple_coeffs(v)
        out = [F(0)] * 8
        for ck, im in zip(c, images):
            out = [x + ck * y for x, y in zip(out, im)]
        return tuple(out)
    return act


stab_lin = [lin_of_perm(g) for g in stab]
orb = set()
for act in stab_lin:
    w = act(Y)
    orb.add(min(w, tuple(-x for x in w)))
