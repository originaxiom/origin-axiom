def sym_power(M, d):
    """Sym^d of a 2x2 matrix, on the monomial basis x^(d-i) y^i.

    NOTE the TRANSPOSE. Substituting the coordinates directly -- b(x,y) -> b(Mv) -- makes
    Sym^d an ANTI-homomorphism: Sym^d(MN) = Sym^d(N)Sym^d(M). Acting through M^T restores
    covariance. This is exactly the contravariance bug-class B154 records catching with its
    figure-eight control ("characters transform CONTRAVARIANTLY"), and it was caught here the
    same way -- by the instrument control below, not by a wrong answer downstream.
    """
    basis = [xs**(d - i) * ys**i for i in range(d + 1)]
    nx = M[0, 0] * xs + M[1, 0] * ys
    ny = M[0, 1] * xs + M[1, 1] * ys
    cols = []
    for b in basis:
        p = sp.Poly(sp.expand(b.subs({xs: nx, ys: ny}, simultaneous=True)), xs, ys)
        cols.append([sp.expand(p.coeff_monomial(bb)) for bb in basis])
    return sp.Matrix(cols).T


def algebra_dim(gens, n):
    """Exact dimension of the unital algebra generated by `gens` inside M_n -- the Burnside test:
    the representation is irreducible iff this is n^2."""
    def rank_of(ms):
        return sp.Matrix([list(m) for m in ms]).rank()
    seen, frontier = [sp.eye(n)], [sp.eye(n)]
    cur = 1
    for _ in range(2 * n * n):
        newf = []
        for m in frontier:
            for g in gens:
                p = sp.expand(m * g)
                if rank_of(seen + [p]) > cur:
                    seen = seen + [p]
                    cur = rank_of(seen)
                    newf.append(p)
        if not newf or cur >= n * n:
            break
        frontier = newf
    return cur


def group_closure(gens, cap=400):
    S = {sp.ImmutableMatrix(sp.expand(g)) for g in gens}
    while True:
        new = {sp.ImmutableMatrix(sp.simplify(sp.expand(a * b))) for a in S for b in S}
        if new <= S:
            return S
        S |= new
        if len(S) > cap:
            return S


