def _red(w):
    out = []
    for gg_ in w:
        if out and out[-1][0] == gg_[0] and out[-1][1] == -gg_[1]:
            out.pop()
        else:
            out.append(gg_)
    return tuple(out)


def _inv(w):
    return _red(tuple((s, -e) for s, e in reversed(w)))


def _mul(*ws):
    out = ()
    for w in ws:
        out = _red(out + w)
    return out


WA, WB = (("A", 1),), (("B", 1),)


def _sub(w, imA, imB):
    out = ()
    for s, e in w:
        im = imA if s == "A" else imB
        out = _red(out + (im if e == 1 else _inv(im)))
    return out


def sig_R(w):
    return _sub(w, WA, _mul(WA, WB))


def sig_L(w):
    return _sub(w, _mul(WA, WB), WB)


def PHI(w, m):
    """phi_m = sigma_R^m o sigma_L^m -- the metallic monodromy on F_2 = <A,B>."""
    for _ in range(m):
        w = sig_L(w)
    for _ in range(m):
        w = sig_R(w)
    return w


def _pow(w, k):
    if k == 0:
        return ()
    return _mul(*([w] * k)) if k > 0 else _inv(_mul(*([w] * (-k))))


