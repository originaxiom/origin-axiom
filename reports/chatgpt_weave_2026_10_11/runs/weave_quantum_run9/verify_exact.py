#!/usr/bin/env python3
"""Run 9 exact algebra. No code imported from previous runs.

Checks finite colour projection, global-flavour covariance, fusion dimensions,
full genus-one coefficient matrices and projective spectral obstructions.
All complex phases used in finite groups are integers modulo 48.
"""
from __future__ import annotations
import json
from pathlib import Path
from fractions import Fraction as Q
from itertools import permutations
from math import lcm
import sympy as s

ROOT = Path(__file__).resolve().parent
checks: list[dict] = []

def check(name: str, condition: bool, detail=None):
    if not bool(condition):
        raise AssertionError(name + (f': {detail}' if detail is not None else ''))
    checks.append({'name': name, 'passed': True, **({'detail':detail} if detail is not None else {})})

def zero(M):
    return all(s.simplify(v)==0 for v in M)

def mat_json(M):
    return [[str(v) for v in row] for row in M.tolist()]

I=s.I
# Vector rotation generators, and their full commutant.
J=[]
for a in range(3):
    J.append(s.Matrix(3,3,lambda b,c:-I*s.LeviCivita(a,b,c)))
unknown=s.symbols('m0:9')
X=s.Matrix(3,3,unknown)
coeff=s.linear_eq_to_matrix([e for j in J for e in X*j-j*X],unknown)[0]
check('flavour vector commutant is one dimensional',9-coeff.rank()==1)
check('flavour vector Casimir is two',zero(sum((j*j for j in J),s.zeros(3))-2*s.eye(3)))
check('flavour commutant is generated by identity',zero(s.Matrix(3,3,coeff.nullspace()[0])-s.eye(3)))

# Fixed Run 6 quaternion-normalizer axes. All scalar/gauge actions cancel at a singlet endpoint.
OL=s.Matrix([[1,0,0],[0,0,1],[0,-1,0]])
OR=s.Matrix([[0,-1,0],[1,0,0],[0,0,1]])
omega=s.Matrix([1 if a==b else 0 for a in range(3) for b in range(3)])
P0=omega*omega.T/3
check('colour endpoint projector has rank one',P0.rank()==1)
check('colour endpoint projector idempotent',zero(P0*P0-P0))
check('colour compensation L fixes endpoint singlet',zero(s.kronecker_product(OL,OL)*omega-omega))
check('colour compensation R fixes endpoint singlet',zero(s.kronecker_product(OR,OR)*omega-omega))
check('source L rotation is not flavour-symmetry equivariant',any(not zero(OL*j-j*OL) for j in J))
check('source R rotation is not flavour-symmetry equivariant',any(not zero(OR*j-j*OR) for j in J))
# A gauge-colour singlet leaves its independent five-component multiplicity untouched.
Omega=s.kronecker_product(omega/s.sqrt(3),s.eye(5))
for name,O in [('L',OL),('R',OR)]:
    U=s.kronecker_product(O,O,s.eye(5))
    check(f'projected {name} action on all five components is identity',zero(Omega.T*U*Omega-s.eye(5)))

# Fusion order (1,F,Sigma) of SO(5)_1 and all odd orthogonal level-one controls.
N0=s.eye(3)
NF=s.Matrix([[0,1,0],[1,0,0],[0,0,1]])
NS=s.Matrix([[0,0,1],[0,0,1],[1,1,0]])
check('vector fusion square is vacuum',NF*NF==N0)
check('spinor square is vacuum plus vector',NS*NS==N0+NF)
check('vector times spinor is spinor',NF*NS==NS)
check('paired vector torus has three handle channels',s.trace(NF**2)==3)
check('central vector plus pair has one handle channel',s.trace(NF**3)==1)
# The general formula is derived from these matrix identities; finite values are controls.
dims=[]
for nf in range(6):
    for ns in range(7):
        actual=int(s.trace(NF**nf*NS**ns))
        predicted=(0 if ns%2 else (2**(ns//2+1) if ns else (1 if nf%2 else 3)))
        if actual != predicted:
            raise AssertionError((nf,ns,actual,predicted))
        dims.append({'F':nf,'Sigma':ns,'rank':actual})
check('all ordinary puncture count formula checked on 42 cases',len(dims)==42)

# Monomial matrices (permutation p, exponents e) act by v'_i = zeta48**e_i v[p_i].
UNIT=((0,1,2),(0,0,0))
def mul(a,b):
    p,e=a; q,f=b
    return tuple(q[p[i]] for i in range(3)), tuple((e[i]+f[p[i]])%48 for i in range(3))
def inv(a):
    p,e=a; q=tuple(p.index(i) for i in range(3))
    return q,tuple((-e[q[i]])%48 for i in range(3))
def power(a,n):
    if n<0:return power(inv(a),-n)
    out=UNIT
    while n:
        if n&1:out=mul(out,a)
        a=mul(a,a); n//=2
    return out

def group(gens):
    seen={UNIT};todo=[UNIT]
    while todo:
        x=todo.pop()
        for g in gens:
            y=mul(g,x)
            if y not in seen:
                seen.add(y);todo.append(y)
    return seen

SP=((2,1,0),(0,0,0))
TP=((0,2,1),(10,43,43))
STARGET=((2,1,0),(6,6,6))
TTARGET=((0,2,1),(6,42,42))
check('pair-only S square is identity',power(SP,2)==UNIT)
check('pair-only modular relation',power(mul(SP,TP),3)==UNIT)
check('target lifted modular relation',power(STARGET,2)==power(mul(STARGET,TTARGET),3))
check('target central fourth power minus identity',power(STARGET,4)==((0,1,2),(24,24,24)))
RP=mul(mul(SP,inv(TP)),inv(SP))
RT=mul(mul(STARGET,inv(TTARGET)),inv(STARGET))
# Source L,R comparison without permuting new flavour labels.
check('pair R is inverse conjugate Dehn twist',mul(mul(RP,inv(TP)),RP)==SP)
check('source R is inverse conjugate Dehn twist',mul(mul(RT,inv(TTARGET)),RT)==STARGET)
gpair=group([SP,TP]);gtarget=group([STARGET,TTARGET])
check('target image 96',len(gtarget)==96)
check('pair image finite enumeration complete',all(mul(g,h) in gpair for g in [SP,TP] for h in gpair))

# Change from spin-trace basis (2,3,4) to affine handle basis (1,F,Sigma).
C=s.Matrix([[0,s.Rational(1,2),s.Rational(1,2)],[0,s.Rational(1,2),-s.Rational(1,2)],[1/s.sqrt(2),0,0]])
P=s.Matrix([[0,0,1],[0,1,0],[1,0,0]])
SM=s.Matrix([[1,1,s.sqrt(2)],[1,1,-s.sqrt(2)],[s.sqrt(2),-s.sqrt(2),0]])/2
check('spin to affine S basis transformation',zero(C*P*C.inv()-SM))
aa,bb=s.symbols('aa bb')
Tm=s.Matrix([[aa,0,0],[0,0,bb],[0,bb,0]])
check('spin to affine T basis transformation',zero(C*Tm*C.inv()-s.diag(bb,-bb,aa)))
check('affine S is unitary',zero(SM*SM.T-s.eye(3)))

# Rational phase multisets: normalizing by any common scalar does not alter differences.
target=[Q(1,8),Q(3,8),Q(7,8)]
pair=[Q(-5,48)%1,Q(19,48),Q(5,24)]
def proj_order(phases):
    return lcm(*[(p-phases[0]).denominator for p in phases])
def shift_matches(a,b):
    # Every possible common shift is determined by a possible image of a[0].
    return [str((bj-a[0])%1) for bj in b if sorted((x+bj-a[0])%1 for x in a)==sorted(x%1 for x in b)]
check('source projective T order four',proj_order(target)==4)
check('pair projective T order sixteen',proj_order(pair)==16)
check('pair has no scalar-shift spectral match',shift_matches(pair,target)==[])
check('orientation reversal cannot repair projective T order',proj_order([-p for p in pair])==16)
# General odd N theorem: h=(0,1/2,N/16), c=N/2, relative phases (0,1/2,N/16).
odd_results=[]
for n in range(1,100,2):
    pp=[Q(-n,48)%1,Q(24-n,48)%1,Q(n,24)%1]
    ok=proj_order(pp)==16 and shift_matches(pp,target)==[]
    if not ok:raise AssertionError(n)
    odd_results.append({'N':n,'projective_T_order':16})
check('50 odd-Majorana phase controls',len(odd_results)==50)
check('opposite even-N control permits projective spectral match',shift_matches([Q(-4,48),Q(20,48),Q(4,24)],target)!=[])

# Entire triplet space with scalar flavour action has a 9-dimensional commutant,
# source irreducible T has only scalar commutant. Compute source using OL,OR.
ceq=s.linear_eq_to_matrix([e for O in [OL,OR] for e in X*O-O*X],unknown)[0]
check('source rotation and its scalar twist have scalar commutant',9-ceq.rank()==1)
check('scalar physical flavour transport cannot be source T',9 != 9-ceq.rank())
# The OPE fusion metric is the sole 5-vector invariant.
Q5=[]
for i in range(5):
    for j in range(i+1,5):
        z=s.zeros(5);z[i,j]=1;z[j,i]=-1;Q5.append(z)
vv=s.symbols('y0:25');Y=s.Matrix(5,5,vv)
cc=s.linear_eq_to_matrix([e for j in Q5 for e in Y*j-j*Y],vv)[0]
check('full five-component global commutant is scalar',25-cc.rank()==1)

# Additional diagnostic: a hypothetical covariantly constant adjoint
# colour-to-flavour frame in the fixed Q8 background. Not an added field theory.
QA=s.diag(1,-1,-1);QB=s.diag(-1,1,-1)
lock=s.linear_eq_to_matrix([e for O in [QA,QB] for e in O*X-X],unknown)[0]
check('no nonzero parallel adjoint reference with trivial flavour holonomy',lock.rank()==9)
check('matched flavour holonomy is a positive frame control',zero(QA*s.eye(3)-s.eye(3)*QA) and zero(QB*s.eye(3)-s.eye(3)*QB))
lock2=s.linear_eq_to_matrix([e for O in [QA,QB,OL,OR] for e in O*X-X*O],unknown)[0]
check('matched colour-flavour holonomies and normalizer leave scalar frame',9-lock2.rank()==1)

out={
 'scope':'exact finite algebra; the general proofs are in TECHNICAL_REPORT.md',
 'checks':checks,'number_of_named_checks':len(checks),
 'pair_image_order':len(gpair),'source_image_order':len(gtarget),
 'pair_S_spin_basis':SP,'pair_T_spin_basis':TP,'pair_R_spin_basis':RP,
 'source_S_spin_basis':STARGET,'source_T_spin_basis':TTARGET,
 'affine_S':mat_json(SM),'basis_spin_to_affine':mat_json(C),
 'pair_T_exponents':[str(x) for x in pair],'source_T_exponents':[str(x) for x in target],
 'ordinary_puncture_ranks':dims,'odd_family_controls':odd_results,
 'endpoint_projector':mat_json(P0),
}
(ROOT/'results').mkdir(exist_ok=True)
(ROOT/'results'/'exact.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps({'passed':len(checks),'pair_image_order':len(gpair),'source_image_order':len(gtarget)},indent=2))
