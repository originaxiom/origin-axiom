#!/usr/bin/env python3
"""THE TOTAL-INPUTS SCOREBOARD (the owner's ruling of 2026-10-29, P-418; the borrowed-joints scaffold, P-661).

'0 of 19' alone hid the drift: a frame can reach more rows by borrowing more joints. This prints, beside '0 of 19', what
each frame borrows to reach what it claims -- every joint typed, counted once however many rows it feeds -- and the
identification price. Progress means these totals fall.

    python3 scripts/checks/inputs_scoreboard.py            # validate, print the headline (exit 1 on a defect)
    python3 scripts/checks/inputs_scoreboard.py --write    # also (re)write docs/TOTAL_INPUTS_SCOREBOARD.md
    python3 scripts/checks/inputs_scoreboard.py --check    # fail if the rendered page is stale
    python3 scripts/checks/inputs_scoreboard.py --selftest # planted defects must be caught

Data: docs/total_inputs_scoreboard.json. A joint typed FORCED-BY-MAIN or VERIFIED-BY-MAIN must name a row that exists in
THEOREM_REGISTRY or LAW_MAP (a T- name, or a quoted LAW_MAP title); everything else is BORROWED.
"""
import copy, json, pathlib, re, sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "total_inputs_scoreboard.json"
PAGE = ROOT / "docs" / "TOTAL_INPUTS_SCOREBOARD.md"
EARNED_TYPES = {"FORCED-BY-MAIN", "VERIFIED-BY-MAIN"}
BORROWED_TYPES = {"FORCED-CLAIMED", "CHOSEN", "FITTED", "MEASURED-INPUT", "ANSATZ", "REFUTED", "UNKNOWN"}


def _basis_exists(basis, reg, lm):
    names = re.findall(r"\bT-[A-Z0-9][A-Z0-9-]+", basis)
    titles = re.findall(r"(?<![A-Za-z])'([^']{6,}?)'(?![A-Za-z])", basis)   # an apostrophe inside a word opens no title
    if not names and not titles:
        return False
    return all(n in reg for n in names) and all(t.upper() in lm.upper() for t in titles)


def validate(d, reg, lm):
    bad = []
    n = len(d["observables"])
    for key, fr in d["frames"].items():
        ids = [j["id"] for j in fr["joints"]]
        if len(ids) != len(set(ids)):
            bad.append("frame %s: a joint id twice" % key)
        for j in fr["joints"]:
            if j["type"] not in EARNED_TYPES | BORROWED_TYPES:
                bad.append("%s %s: unknown type %s" % (key, j["id"], j["type"]))
            if j["type"] in EARNED_TYPES and not _basis_exists(j.get("basis", ""), reg, lm):
                bad.append("%s %s: typed %s but its basis names no existing registry or law-map row" % (key, j["id"], j["type"]))
            if any(not (1 <= f <= n) for f in j.get("feeds", [])):
                bad.append("%s %s: feeds a row outside 1..%d" % (key, j["id"], n))
            if j.get("same_as"):
                other = "A" if key == "B" else "B"
                if other in d["frames"] and j["same_as"] not in {x["id"] for x in d["frames"][other]["joints"]}:
                    bad.append("%s %s: same_as %s does not exist" % (key, j["id"], j["same_as"]))
        if any(not (1 <= c <= n) for c in fr["claims"]):
            bad.append("frame %s: a claimed row outside 1..%d" % (key, n))
    for s in d["shared_block"]:
        if s["type"] not in BORROWED_TYPES | EARNED_TYPES:
            bad.append("shared %s: unknown type" % s["id"])
    return bad


def tally(d):
    out = {}
    shared = [s for s in d["shared_block"] if s["type"] in BORROWED_TYPES]
    for key, fr in d["frames"].items():
        borrowed = [j for j in fr["joints"] if j["type"] in BORROWED_TYPES and set(j.get("feeds", [])) & set(fr["claims"])]
        by_type = Counter(j["type"] for j in borrowed) + Counter(s["type"] for s in shared)
        per_row = {r: sum(1 for j in borrowed if r in j.get("feeds", [])) + len(shared) for r in fr["claims"]}
        reach = sorted(((len(set(j["feeds"]) & set(fr["claims"])), j["id"], j["type"], j["name"]) for j in borrowed),
                       key=lambda x: (-x[0], x[1]))
        out[key] = {"claims": len(fr["claims"]), "borrowed": len(borrowed) + len(shared), "by_type": dict(by_type),
                    "per_row": per_row, "reach": reach}
    return out


def headline(d, t):
    parts = ["%d of 19 earned" % d["earned"], "identification price %d" % d["identification_price"]["count"]]
    for key in sorted(t):
        fr = d["frames"][key]
        parts.append("frame %s (%s): %d rows claimed, %d borrowed joints [%s]" % (
            key, fr["name"].split(":")[0], t[key]["claims"], t[key]["borrowed"],
            ", ".join("%d %s" % (v, k.lower()) for k, v in sorted(t[key]["by_type"].items(), key=lambda kv: -kv[1]))))
    return "inputs-scoreboard: " + " | ".join(parts)


def render(d, t):
    L = ["# THE TOTAL-INPUTS SCOREBOARD", "",
         "*Generated by `scripts/checks/inputs_scoreboard.py --write` from `docs/total_inputs_scoreboard.json`; do not edit by hand.*", "",
         "**The rule.** " + d["rule"], "",
         "**Headline.** " + headline(d, t).split(": ", 1)[1], "",
         "A joint is EARNED only if a banked theorem or law on main supplies it (FORCED-BY-MAIN, or VERIFIED-BY-MAIN for an "
         "exact identity checked but not proved); every other joint is BORROWED: CHOSEN, FITTED, MEASURED-INPUT, ANSATZ, "
         "FORCED-CLAIMED (a seat's word), REFUTED or UNKNOWN. A joint counts once however many rows it feeds. Progress means "
         "the borrowed totals fall.", "",
         "**The identification price:** %d (%s)." % (d["identification_price"]["count"], d["identification_price"]["basis"]), "",
         "## The shared block (both frames stand on it)", "", "| id | joint | type | basis | register |", "|---|---|---|---|---|"]
    for s in d["shared_block"]:
        L.append("| %s | %s | %s | %s | %s |" % (s["id"], s["name"], s["type"], s["basis"], s.get("register", "")))
    for key in sorted(d["frames"]):
        fr = d["frames"][key]; tk = t[key]; obs = d["observables"]
        L += ["", "## Frame %s — %s" % (key, fr["name"]), "", "*Status:* " + fr["status"] + ".", "",
              "Rows claimed: %s." % ", ".join(obs[c - 1] for c in fr["claims"])]
        for lab, k in (("Held out (sealed)", "held_out"), ("Graded an input", "graded_input"), ("No frame", "no_frame")):
            if fr.get(k):
                L.append("%s: %s." % (lab, ", ".join(obs[c - 1] for c in fr[k])))
        L += ["", "**Borrowed joints: %d** (%s), the shared block included." % (
            tk["borrowed"], ", ".join("%d %s" % (v, k2) for k2, v in sorted(tk["by_type"].items(), key=lambda kv: -kv[1]))), "",
              "| id | joint | type | rows fed | same as | register | basis |", "|---|---|---|---|---|---|---|"]
        for j in fr["joints"]:
            fed = len(set(j.get("feeds", [])) & set(fr["claims"]))
            L.append("| %s | %s | %s | %d | %s | %s | %s |" % (j["id"], j["name"].replace("|", "∣"), j["type"], fed,
                                                              j.get("same_as", ""), j.get("register", ""), j.get("basis", "").replace("|", "∣")[:300]))
        L += ["", "Borrowed joints per claimed row (shared block included): " +
              "; ".join("%s %d" % (obs[r - 1], v) for r, v in tk["per_row"].items()) + "."]
        L += ["", "**The joints to earn first (by rows released):** " +
              "; ".join("%s %s (%s, %d rows)" % (i, n, ty.lower(), k) for k, i, ty, n in tk["reach"][:8]) + "."]
    return "\n".join(L).replace("|  |", "| |") + "\n"


def load():
    return (json.loads(DATA.read_text(encoding="utf-8")), (ROOT / "docs" / "THEOREM_REGISTRY.md").read_text(encoding="utf-8"),
            (ROOT / "docs" / "LAW_MAP.md").read_text(encoding="utf-8"))


def selftest():
    d, reg, lm = load()
    assert not validate(d, reg, lm), validate(d, reg, lm)
    p = copy.deepcopy(d); p["frames"]["A"]["joints"][0]["type"] = "FORCED-BY-MAIN"; p["frames"]["A"]["joints"][0]["basis"] = "T-NO-SUCH-THEOREM"
    assert validate(p, reg, lm), "a FORCED-BY-MAIN joint with a nonexistent basis was not caught"
    p = copy.deepcopy(d); p["frames"]["A"]["joints"].append(copy.deepcopy(p["frames"]["A"]["joints"][0]))
    assert validate(p, reg, lm), "a duplicate joint id was not caught"
    p = copy.deepcopy(d); p["frames"]["B"]["joints"][0]["feeds"] = [99]
    assert validate(p, reg, lm), "a feed outside the rows was not caught"
    t = tally(d); p = copy.deepcopy(d); p["frames"]["A"]["joints"][0]["type"] = "VERIFIED-BY-MAIN"
    p["frames"]["A"]["joints"][0]["basis"] = "T-FA-NORM"
    assert tally(p)["A"]["borrowed"] == t["A"]["borrowed"] - 1, "earning a joint did not lower the total"
    print("selftest: 4 planted defects caught; earning one joint lowers the total by one")


def main(argv):
    if "--selftest" in argv:
        selftest(); return 0
    d, reg, lm = load()
    bad = validate(d, reg, lm)
    if bad:
        print("inputs-scoreboard: " + "; ".join(bad[:6])); return 1
    t = tally(d)
    if "--write" in argv:
        PAGE.write_text(render(d, t), encoding="utf-8")
    if "--check" in argv and (not PAGE.exists() or PAGE.read_text(encoding="utf-8") != render(d, t)):
        print("inputs-scoreboard: docs/TOTAL_INPUTS_SCOREBOARD.md is stale (run --write)"); return 1
    print(headline(d, t)); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
