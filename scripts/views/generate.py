def _title(h1):
    b = h1.lstrip("# ").strip()
    b = re.sub(r"^FINDINGS\s*[—:\-–]+\s*", "", b, flags=re.I)
    return re.sub(r"^B\d+[a-zA-Z]?\s*[—:\-–(]*\s*", "", b).strip()


def collect():
    """Every arc, with whatever layers exist for it. Missing layers are reported, not faked."""
    arcs = []
    fdir = os.path.join(ROOT, "frontier")
    for d in sorted(os.listdir(fdir)):
        fp = os.path.join(fdir, d, "FINDINGS.md")
        if not os.path.isfile(fp):
            continue
        m = re.match(r"(B\d+)[a-zA-Z]?_", d)
        if not m:
            continue
        text = open(fp, encoding="utf-8").read()
        h1 = next((l for l in text.splitlines() if l.startswith("# ")), "")
        a = {"id": m.group(1), "n": int(m.group(1)[1:]), "dir": d,
             "title": _title(h1), "words": len(text.split()),
             "tests": sorted(set(re.findall(r"tests/(test_[A-Za-z0-9_]+\.py)", text))),
             "has_verdict_block": bool(re.search(r"^#{2,3}\s*Verdict", text, re.M | re.I))}
        vp = os.path.join(fdir, d, "arc_verdict.json")
        a["verdict_record"] = json.load(open(vp, encoding="utf-8")) if os.path.isfile(vp) else None
        arcs.append(a)
    kgp = os.path.join(fdir, "B738_pathfinder_compiler", "kill_graph.json")
    kills = json.load(open(kgp, encoding="utf-8")) if os.path.isfile(kgp) else []
    return arcs, kills


def view_coverage(arcs, kills):
    """The view that must exist first: how much of the record is actually projected."""
    n = len(arcs)
    authored = [a for a in arcs if a["verdict_record"]]
    kg_ids = {r["id"] for r in kills}
    arc_ids = {a["id"] for a in arcs}
    L = [HEADER, "# Coverage of the generated views\n",
         "How much of the record these views actually project. This view exists so that no other\n"
         "view can quietly imply completeness it does not have.\n",
         "| layer | count | of | share |", "|---|---|---|---|",
         f"| arcs with `FINDINGS.md` | **{n}** | — | 100 % |",
         f"| arcs with an authored verdict (W1) | **{len(authored)}** | {n} | {len(authored)/n*100:.1f} % |",
         f"| classified in `kill_graph` | **{len(kills)}** | — | — |",
         f"| kill records resolving to an arc | **{len(kg_ids & arc_ids)}** | {len(kills)} | {len(kg_ids & arc_ids)/len(kills)*100:.0f} % |",
         f"| kill records with no arc directory | **{len(kg_ids - arc_ids)}** | {len(kills)} | {len(kg_ids - arc_ids)/len(kills)*100:.0f} % |",
         ""]
    # the honest gap: negatives the kill graph does not carry
    unreg = [a["id"] for a in authored
             if a["verdict_record"]["verdict"] == "NEGATIVE" and a["id"] not in kg_ids]
    if unreg:
        L += ["## Negatives absent from `kill_graph`\n",
              "Found among the authored arcs: " + ", ".join(f"`{i}`" for i in sorted(unreg)) + ".\n"]
    cen = os.path.join(ROOT, "frontier", "B801_negative_census", "census.json")
    if os.path.isfile(cen):
        c = json.load(open(cen, encoding="utf-8"))
        L += ["### Measured (B801), not merely flagged\n",
              f"A seeded random sample of **{c['sample']}** of the **{c['pool']}** arcs with findings "
              f"and no kill record found **{c['negatives']}** negatives "
              f"(p = {c['p']:.2f}, 95 % CI {c['ci'][0]:.2f}–{c['ci'][1]:.2f}).\n",
              "| | estimate | 95 % CI |", "|---|---|---|",
              f"| unregistered negatives | **{c['estimated_unregistered']:.0f}** | "
              f"{c['pool']*c['ci'][0]:.0f}–{c['pool']*c['ci'][1]:.0f} |",
              f"| **true negative count** | **≈ {c['estimated_total']:.0f}** | "
              f"{c['ci_total'][0]:.0f}–{c['ci_total'][1]:.0f} |",
              f"| `kill_graph` coverage | **{c['coverage_pct']:.0f} %** | "
              f"{c['kill_graph']/c['ci_total'][1]*100:.0f} %–{c['kill_graph']/c['ci_total'][0]*100:.0f} % |",
              "", "Ambiguous arcs were counted as NON-negative, so the true count is likely **at or "
              "above** this estimate. So the map above projects about **two-thirds** of the "
              "programme's negatives, not all of them.\n"]
    strata = Counter("A_verdict_block" if a["has_verdict_block"]
                     else ("C_neither" if len(a["title"]) < 22
                           or a["title"].lower().startswith("findings") else "B_informative_title")
                     for a in arcs)
    L += ["## Classifiability strata\n",
          "Measured, not assumed. The W1 pilot's original premise — that malformed titles mark the\n"
          "hard arcs — was **refuted**: 83 % of uninformative-title arcs carry an explicit `## Verdict`\n"
          "block against 19 % of the rest, so the title heuristic *anti*-correlates with difficulty.\n",
          "| stratum | meaning | count | share |", "|---|---|---|---|"]
    for k, lab in (("A_verdict_block", "explicit `## Verdict` block — directly extractable"),
                   ("B_informative_title", "no block, but the title carries the verdict"),
                   ("C_neither", "neither — genuinely hard, needs a full read")):
        L.append(f"| **{k[0]}** | {lab} | {strata[k]} | {strata[k]/n*100:.1f} % |")
    return "\n".join(L) + "\n"


def view_claims(arcs):
    """The claim ledger, grouped by verdict. Generated -- so it cannot drift from the arcs."""
    authored = [a for a in arcs if a["verdict_record"]]
    L = [HEADER, "# Arc verdict ledger (generated)\n",
         f"{len(authored)} of {len(arcs)} arcs carry an authored verdict. "
         "Arcs without one are absent from this ledger by construction, not by judgement.\n"]
    order = ["PROVED", "NEGATIVE", "OPEN", "RETRACTED"]
    by = {k: [] for k in order}
    for a in authored:
        by.setdefault(a["verdict_record"]["verdict"], []).append(a)
    for k in order:
        rows = sorted(by.get(k, []), key=lambda a: a["n"])
        if not rows:
            continue
        L += [f"\n## {k} ({len(rows)})\n", "| arc | claim | instrument | locks |", "|---|---|---|---|"]
        for a in rows:
            v = a["verdict_record"]
            L.append(f"| `{a['id']}` | {v['claim_one_line']} | "
                     f"{'yes' if v.get('instrument') else ''} | {len(a['tests'])} |")
    return "\n".join(L) + "\n"


def _apply_taxonomy(kills):
    """W5: fold the B799 taxonomy patch over the raw kill forms.

    `other` was the second-largest mechanism (46 of 217 = 21.2%), i.e. the taxonomy did not
    cover its own corpus. Four mechanisms were separated out, each required to hold >= 3
    records so the distribution is not tidied by inventing one-record categories:
      incoming-claim-refuted · census-counterexample · self-audit-retraction · selection-not-unique
    `other` falls to 16 = 7.4%. The remainder are genuinely one-off, and half of them are the
    orphan (non-arc) records -- so that residue is reported, not driven to zero."""
    patch = os.path.join(ROOT, "frontier", "B799_uncomputed_doors", "taxonomy_patch.json")
    if not os.path.isfile(patch):
        return kills
    reclass = json.load(open(patch, encoding="utf-8"))["reclassified"]
    out = []
    for r in kills:
        r = dict(r)
        if r["kill_form"] == "other" and r["id"] in reclass:
            r["kill_form"] = reclass[r["id"]]
        out.append(r)
    return out


def view_closed_doors(arcs, kills):
    """The negatives, indexed by the MECHANISM that shut them -- the asset a reviewer can actually use."""
    kills = _apply_taxonomy(kills)
    byform = {}
    for r in kills:
        byform.setdefault(r["kill_form"], []).append(r)
    # B836 routed every NEGATIVE-verdict arc into the graph, so "classified" is no longer true of
    # all of them: routed records carry kill_form="unrouted-unclassified" and DELIBERATELY unset
    # judgement fields. Say which is which rather than letting a reader count them as classified.
    n_unrouted = sum(1 for r in kills if r["kill_form"] == "unrouted-unclassified")
    n_class = len(kills) - n_unrouted
    L = [HEADER, "# The closed-door map (generated)\n",
         f"**{len(kills)} recorded closures — of which {n_class} are CLASSIFIED by mechanism and\n"
         f"{n_unrouted} are merely ROUTED**, carrying an authored NEGATIVE verdict but no read of the\n"
         "arc yet: their `kill_form`, `fact_computed` and revival fields are deliberately UNSET\n"
         "rather than guessed (B836). Indexed by the mechanism that shut them rather than by arc\n"
         "number. A programme whose firewall works is mostly negatives; this is the shape of them.\n",
         "| mechanism | doors | facts not computed |", "|---|---|---|"]
    for form, rs in sorted(byform.items(), key=lambda kv: -len(kv[1])):
        unc = sum(1 for r in rs if not r["fact_computed"])
        L.append(f"| `{form}` | {len(rs)} | {unc or ''} |")
    unc = [r for r in kills if not r["fact_computed"]]
    L += ["", f"## Closures whose discriminating fact was not computed ({len(unc)})\n",
          "The standing rule is that a negative is only as sound as the in-sandbox computation of\n"
          "its discriminating fact. **B799 resolved all of these** — see "
          "`frontier/B799_uncomputed_doors/`.\n",
          "| arc | claim killed | mechanism |", "|---|---|---|"]
    for r in unc:
        L.append(f"| `{r['id']}` | {r['claim_killed'][:110]} | `{r['kill_form']}` |")
    return "\n".join(L) + "\n"


def view_reviewer(arcs, kills):
    """The ~15-page front door. Kill criterion (masterplan W4): readable end-to-end in <30 min.

    A reviewer needs the object, what is claimed, what is closed, worked exemplars of each
    disposition, and how to falsify any of it -- NOT 470,639 words of findings."""
    authored = [a for a in arcs if a["verdict_record"]]
    byv = Counter(a["verdict_record"]["verdict"] for a in authored)
    unc = [r for r in kills if not r["fact_computed"]]
    forms = Counter(r["kill_form"] for r in _apply_taxonomy(kills))

    def exemplar(kind):
        for a in sorted(authored, key=lambda a: -a["n"]):
            if a["verdict_record"]["verdict"] == kind:
                return a
        return None

    L = [HEADER, "# The programme, for a reviewer\n",
         "A generated front door. Every figure below is derived from the repository's own metadata;\n"
         "none is transcribed. Where coverage is partial, this page says so rather than rounding up.\n",
         "## The object\n",
         "The figure-eight knot complement **m004** -- the unique arithmetic knot complement, trace\n"
         "field `Q(sqrt-3)`. The programme asks what such an object forces, and reports that it forces\n"
         "**form** while refusing **values**. Most results are therefore negatives, and that is the\n"
         "result, not the debt.\n",
         "## What is in the record\n",
         "| | |", "|---|---|",
         f"| research arcs with findings | **{len(arcs)}** |",
         f"| words of findings prose | **{sum(a['words'] for a in arcs):,}** |",
         f"| test lock files referenced | **{len({t for a in arcs for t in a['tests']})}** |",
         f"| arcs carrying an authored verdict | **{len(authored)}** ({len(authored)/len(arcs)*100:.1f} %) |",
         f"| recorded closures | **{len(kills)}** ({sum(1 for r in kills if r['kill_form'] != 'unrouted-unclassified')} classified, "
         f"{sum(1 for r in kills if r['kill_form'] == 'unrouted-unclassified')} routed-only) |",
         "",
         "**Read `COVERAGE.md` before drawing conclusions from any other view.** The verdict ledger\n"
         "projects only the authored fraction; the closed-door map projects only classified closures,\n"
         "and those are a lower bound on the corpus's negatives, not a census.\n",
         "## Verdicts, so far\n", "| verdict | arcs |", "|---|---|"]
    for k in ("PROVED", "NEGATIVE", "OPEN", "RETRACTED"):
        if byv.get(k):
            L.append(f"| {k} | {byv[k]} |")
    L += ["", "## How the doors were shut\n",
          "Closures indexed by *mechanism*, not by arc number -- the form a reviewer can actually use.\n",
          "| mechanism | doors |", "|---|---|"]
    for f, n in forms.most_common(8):
        L.append(f"| `{f}` | {n} |")
    L += [f"| *(all {len(forms)} mechanisms in `CLOSED_DOORS.md`)* | |", "",
          "### The quality signal a reviewer should check first\n",
          f"**{len(unc)} closures** were classified as having had their discriminating fact *not* "
          "computed in-sandbox -- a violation of the programme's own standing rule.\n"
          "**All were resolved in `frontier/B799_uncomputed_doors/`**: 2 computed here in exact\n"
          "arithmetic, 5 shown to rest on locks in other arcs (each lock re-run, not trusted), and\n"
          "5 relabelled honestly as uncomputed with the reason stated.\n",
          "## Worked exemplars\n",
          "One of each disposition, so the ledger's vocabulary can be checked against real arcs.\n"]
    for kind in ("PROVED", "NEGATIVE", "RETRACTED"):
        a = exemplar(kind)
        if a:
            L += [f"**{kind} — `{a['id']}`** ({a['words']} words, {len(a['tests'])} locks)  ",
                  f"{a['verdict_record']['claim_one_line']}  ",
                  f"`{a['dir']}/FINDINGS.md`\n"]
    L += ["## How to falsify any of this\n",
          "1. Every closure names an **escape hatch** -- the computation that would reopen it. Pick a\n"
          "   door in `CLOSED_DOORS.md`, run its hatch; the door holds or it does not.\n"
          "2. Every PROVED arc names its **test locks**. Run them.\n"
          "3. The gates (`python3 scripts/gates/gates.py`) enforce the governance invariants, and each\n"
          "   was verified by deliberate breakage -- a gate never observed to fail is not a gate.\n",
          "You do not need to read the record to check the programme. That is the point of this page.\n"]
    return "\n".join(L) + "\n"


def view_context_recovery(arcs, kills):
    """docs/views/CONTEXT_RECOVERY.md -- main's first read after a compaction (P-506, the owner's 'two readers, one
    source'). Built from tracked files only, so the views gate can regenerate it byte for byte: the newest arcs, what
    waits for the owner, the queue's head, the last landings, the latest campaign line, the record's counts, and the
    completeness checks (arc folders without a verdict file, verification scripts without an output). Live state that
    is not tracked -- runs in flight, seat heads past their pins -- is pointed to, not copied."""
    import glob

    def rd(rel):
        p = os.path.join(ROOT, rel)
        return open(p, encoding="utf-8").read() if os.path.isfile(p) else ""

    def clip(s, n):
        s = " ".join(s.split())
        return s if len(s) <= n else s[: n - 1].rstrip() + "…"

    def num(a):
        return a["n"]

    def vr(a):
        return a.get("verdict_record") or {}

    out = [HEADER.replace("Source of truth: frontier/<arc>/arc_verdict.json + kill_graph.json.",
                          "Source of truth: the tracked record (verdict files, the point register, the ledgers, the logs)."),
           "# CONTEXT RECOVERY — the first read after a compaction\n",
           "*Generated at every landing from tracked files (P-506). Read this, then the memory index, then `audit/IN_FLIGHT.md`",
           "(runs in flight and unlanded work; gitignored), then the newest CHANGELOG entry. Live seat debt:",
           "`python3 scripts/checks/harvest_debt.py`. Nothing here is hand-kept.*\n"]

    # ---- counts
    verdicts = Counter(vr(a).get("verdict") for a in arcs if vr(a).get("verdict"))
    reg = rd("docs/POINT_REGISTER.md").splitlines()
    rows = [l for l in reg if l.startswith("| P-")]
    cells = [l.strip().strip("|").split(" | ") for l in rows]
    disp = Counter(c[4].split("(")[0].strip() if len(c) == 7 else "MALFORMED" for c in cells)
    hv = [l for l in rd("docs/HARVEST_LEDGER.md").splitlines() if re.match(r"^\| \d+ \|", l)]
    last_h = max((int(l.split(" | ")[0][2:]) for l in hv), default=0)
    out.append("## The record's counts\n")
    out.append("| what | count |\n|---|---|")
    out.append("| arcs with a verdict file | %d |" % sum(verdicts.values()))
    for k in ("PROVED", "NEGATIVE", "OPEN", "RETRACTED"):
        out.append("| … %s | %d |" % (k, verdicts.get(k, 0)))
    out.append("| register points | %d |" % len(rows))
    for k in ("QUEUED", "LEAD", "OWNER", "DONE", "DECLINED"):
        out.append("| … %s | %d |" % (k, sum(v for d, v in disp.items() if d.startswith(k))))
    out.append("| harvest rows (the last number) | %d |" % last_h)
    out.append("| the Standard Model's 19 derived | 0 |\n")

    # ---- the newest arcs
    out.append("## The newest arcs\n")
    out.append("| arc | verdict | claim |\n|---|---|---|")
    for a in sorted(arcs, key=num, reverse=True)[:12]:
        out.append("| %s | %s | %s |" % (a["id"], vr(a).get("verdict") or "—", clip((vr(a).get("claim_one_line") or a["title"] or "").replace("|", "∣"), 220)))
    out.append("")

    # ---- what waits for the owner, and the queue's head
    owner = [c for c in cells if len(c) == 7 and c[4].startswith("OWNER")]
    out.append("## Waiting for the owner (register rows with disposition OWNER)\n")
    out.extend("- **%s** — %s → *%s*" % (c[0], clip(c[3], 220), clip(c[5], 160)) for c in owner) if owner else out.append("- none")
    out.append("")
    q1 = [c for c in cells if len(c) == 7 and c[4].startswith("QUEUED") and re.match(r"Q1\b", c[5])]
    out.append("## The queue's head (QUEUED in slot Q1, newest first)\n")
    out.extend("- **%s** (%s) — %s" % (c[0], c[1], clip(c[3], 200)) for c in sorted(q1, key=lambda c: c[0], reverse=True)[:25])
    out.append("")

    # ---- the last landings and the campaign line
    ch = [l[3:].strip() for l in rd("CHANGELOG.md").splitlines() if l.startswith("## S")][:8]
    out.append("## The last landings (CHANGELOG)\n")
    out.extend("- " + clip(h, 200) for h in ch)
    latest = next((l for l in rd("docs/CAMPAIGN_STATUS.md").splitlines() if l.startswith("**LATEST")), "")
    out.append("\n## The latest campaign line\n")
    out.append(clip(latest.strip("*"), 700) + "\n")

    # ---- completeness: nothing skipped silently
    folders = sorted(d for d in os.listdir(os.path.join(ROOT, "frontier")) if re.match(r"B\d+", d) and os.path.isdir(os.path.join(ROOT, "frontier", d)))
    no_verdict = [d for d in folders if not os.path.isfile(os.path.join(ROOT, "frontier", d, "arc_verdict.json"))]
    scripts = sorted(glob.glob(os.path.join(ROOT, "frontier", "B*", "verification", "*.py")))
    lone = []
    for s_ in scripts:
        d = os.path.dirname(s_)
        if not any(not f.endswith(".py") and not f.startswith("__") for f in os.listdir(d)):
            lone.append(os.path.relpath(s_, ROOT))
    out.append("## Completeness (nothing skipped silently)\n")
    out.append("| check | count | first items |\n|---|---|---|")
    out.append("| arc folders without a verdict file (scripts/checks/arc_data.py classifies them; its resolved R-classes are not defects) | %d | %s |" % (len(no_verdict), ", ".join(no_verdict[:6]) or "—"))
    out.append("| verification scripts in folders with no output file beside them (helpers and libraries among them; to classify, P-507) | %d | %s |" % (len(lone), ", ".join("`%s`" % x for x in lone[:4]) or "—"))
    out.append("| register rows not in the 7-cell form | %d | — |" % disp.get("MALFORMED", 0))
    out.append("")
    return "\n".join(out) + "\n"


def main():
    arcs, kills = collect()
    os.makedirs(OUT, exist_ok=True)
    views = {"COVERAGE.md": view_coverage(arcs, kills),
             "VERDICT_LEDGER.md": view_claims(arcs),
             "CLOSED_DOORS.md": view_closed_doors(arcs, kills),
             "REVIEWER.md": view_reviewer(arcs, kills),
             "CONTEXT_RECOVERY.md": view_context_recovery(arcs, kills)}
    changed = []
    for name, body in views.items():
        p = os.path.join(OUT, name)
        old = open(p, encoding="utf-8").read() if os.path.isfile(p) else None
        if old != body:
            open(p, "w", encoding="utf-8").write(body)
            changed.append(name)
    print(f"arcs={len(arcs)}  authored={sum(1 for a in arcs if a['verdict_record'])}  "
          f"kills={len(kills)}")
    print(f"views written to docs/views/: {', '.join(views)}")
    print(f"changed this run: {', '.join(changed) if changed else 'none (already current)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
