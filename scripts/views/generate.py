def view_claims(arcs):
    """The claim ledger, grouped by verdict. Generated -- so it cannot drift from the arcs."""
    authored = [a for a in arcs if a["verdict_record"]]
    L = [HEADER, "# Arc verdict ledger (generated)\n",
         f"{len(authored)} of {len(arcs)} arcs carry an authored verdict. "
         "Arcs without one are absent from this ledger by construction, not by judgement.\n"]
    order = ["PROVED", "NEGATIVE", "OPEN", "RETRACTED"]
    by = {k: [] for k in order}
    for a in authored:
        by.setdefault(a["verdict_record"]["verdict"], []).append(a)
    for k in order:
        rows = sorted(by.get(k, []), key=lambda a: a["n"])
        if not rows:
            continue
        L += [f"\n## {k} ({len(rows)})\n", "| arc | claim | instrument | locks |", "|---|---|---|---|"]
        for a in rows:
            v = a["verdict_record"]
            L.append(f"| `{a['id']}` | {quoted(v['claim_one_line'])} | "
                     f"{'yes' if v.get('instrument') else ''} | {len(a['tests'])} |")
    return "\n".join(L) + "\n"


def _apply_taxonomy(kills):
    """W5: fold the B799 taxonomy patch over the raw kill forms.

    `other` was the second-largest mechanism (46 of 217 = 21.2%), i.e. the taxonomy did not
    cover its own corpus. Four mechanisms were separated out, each required to hold >= 3
    records so the distribution is not tidied by inventing one-record categories:
      incoming-claim-refuted · census-counterexample · self-audit-retraction · selection-not-unique
    `other` falls to 16 = 7.4%. The remainder are genuinely one-off, and half of them are the
    orphan (non-arc) records -- so that residue is reported, not driven to zero."""
    patch = os.path.join(ROOT, "frontier", "B799_uncomputed_doors", "taxonomy_patch.json")
    if not os.path.isfile(patch):
        return kills
    reclass = json.load(open(patch, encoding="utf-8"))["reclassified"]
    out = []
    for r in kills:
        r = dict(r)
        if r["kill_form"] == "other" and r["id"] in reclass:
            r["kill_form"] = reclass[r["id"]]
        out.append(r)
    return out


def view_closed_doors(arcs, kills):
    """The negatives, indexed by the MECHANISM that shut them -- the asset a reviewer can actually use."""
    kills = _apply_taxonomy(kills)
    byform = {}
    for r in kills:
        byform.setdefault(r["kill_form"], []).append(r)
    # B836 routed every NEGATIVE-verdict arc into the graph, so "classified" is no longer true of
    # all of them: routed records carry kill_form="unrouted-unclassified" and DELIBERATELY unset
    # judgement fields. Say which is which rather than letting a reader count them as classified.
    n_unrouted = sum(1 for r in kills if r["kill_form"] == "unrouted-unclassified")
    n_class = len(kills) - n_unrouted
    L = [HEADER, "# The closed-door map (generated)\n",
         f"**{len(kills)} recorded closures — of which {n_class} are CLASSIFIED by mechanism and\n"
         f"{n_unrouted} are merely ROUTED**, carrying an authored NEGATIVE verdict but no read of the\n"
         "arc yet: their `kill_form`, `fact_computed` and revival fields are deliberately UNSET\n"
         "rather than guessed (B836). Indexed by the mechanism that shut them rather than by arc\n"
         "number. A programme whose firewall works is mostly negatives; this is the shape of them.\n",
         "| mechanism | doors | facts not computed |", "|---|---|---|"]
    for form, rs in sorted(byform.items(), key=lambda kv: -len(kv[1])):
        unc = sum(1 for r in rs if not r["fact_computed"])
        L.append(f"| `{quoted(form)}` | {len(rs)} | {unc or ''} |")   # a mechanism as the kill graph names it, quoted
    unc = [r for r in kills if not r["fact_computed"]]
    L += ["", f"## Closures whose discriminating fact was not computed ({len(unc)})\n",
          "The standing rule is that a negative is only as sound as the in-sandbox computation of\n"
          "its discriminating fact. **B799 resolved all of these** — see "
          "`frontier/B799_uncomputed_doors/`.\n",
          "| arc | claim killed | mechanism |", "|---|---|---|"]
    for r in unc:
        L.append(f"| `{r['id']}` | {quoted(r['claim_killed'][:110])} | `{quoted(r['kill_form'])}` |")
    return "\n".join(L) + "\n"


